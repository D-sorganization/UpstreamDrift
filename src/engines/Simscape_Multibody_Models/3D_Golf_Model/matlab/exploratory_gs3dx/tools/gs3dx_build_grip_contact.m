function report = gs3dx_build_grip_contact(repo_root, out_dir, opts)
%GS3DX_BUILD_GRIP_CONTACT  Build GS3DX_GripContact fixture model (#13334, HRG-GS-M12).
%
%   REPORT = GS3DX_BUILD_GRIP_CONTACT(REPO_ROOT, OUT_DIR, OPTS) builds the
%   standalone Simscape Multibody grip-contact fixture model
%   GS3DX_GripContact (registered in GS3DX_NAMES.variants.grip_contact) that
%   mirrors the Pinocchio G6 reference scenario without any hand-on-club
%   Weld Joint:
%     * World Frame + Mechanism Configuration (gravity from Python spec) +
%       Solver Configuration;
%     * Club as a free body on a 6-DOF Joint (sm_lib/Joints/6-DOF Joint)
%       with exact mass, CoM, and principal inertia exported from Python
%       (gs3dx_grip_contact_scenarios.json);
%     * Left and Right hand bodies whose 6-DOF trajectories are prescribed
%       from the shared Forsythe-Malcolm-Moler / Hermite prescribed-motion
%       trajectory exported from Python;
%     * Three Transform Sensors (Club, Hand_L, Hand_R) feeding a MATLAB
%       Function block that calls the generated codegen kernel
%       gs3dx_grip_contact_kernel.  The shared law is stateless (regularized
%       friction), so the block has no state of its own;
%     * External Force and Torque block applying the net contact wrench
%       (F_club_w, M_club_w) in World axes at the club body origin;
%     * Signal logging on every per-pair channel (normal, tangential, spin,
%       penetration, slip speed, signed distance, force, moment, contact
%       point) and on the net club and per-hand wrenches.
%
%   Assumes nothing about pwd; asserts MATLAB R2025b and the 1000-block
%   Home license compiled block budget via GS3DX_BLOCK_BUDGET.

    arguments
        repo_root = ""
        out_dir = ""
        opts.overwrite (1,1) logical = true
        opts.save_model (1,1) logical = true
        opts.style (1,:) char = 'overlap'
        opts.scenario (1,:) char = 'hold'
    end

    assert(string(version('-release')) == "2025b", ...
        'gs3dx:grip_contact:WrongRelease', ...
        'MATLAB R2025b is required; running on %s.', version('-release'));

    [repo_root_str, out_dir_str, tools_dir, gen_dir] = local_resolve_paths(repo_root, out_dir);
    addpath(tools_dir);
    addpath(gen_dir);

    names = gs3dx_names();
    mdl = char(names.variants.grip_contact);
    slx_path = fullfile(out_dir_str, [mdl '.slx']);
    if isfile(slx_path) && ~opts.overwrite
        error('gs3dx:grip_contact:ModelExists', ...
            'Model %s already exists and overwrite=false.', slx_path);
    end

    scenarios_file = fullfile(gen_dir, 'gs3dx_grip_contact_scenarios.json');
    assert(isfile(scenarios_file), 'gs3dx:grip_contact:MissingScenarios', ...
        'Missing generated scenarios JSON: %s', scenarios_file);
    sc_data = jsondecode(fileread(scenarios_file));

    if bdIsLoaded(mdl)
        close_system(mdl, 0);
    end
    load_system('simulink');
    load_system('sm_lib');
    load_system('nesl_utility');

    new_system(mdl);
    cleanup = onCleanup(@() local_safe_close(mdl));

    set_param(mdl, ...
        'SolverType', 'Variable-step', ...
        'Solver', char(sc_data.solver.solver_name), ...
        'RelTol', num2str(sc_data.solver.rel_tol, 17), ...
        'AbsTol', num2str(sc_data.solver.abs_tol, 17), ...
        'MaxStep', num2str(sc_data.solver.max_step_s, 17), ...
        'StopTime', num2str(sc_data.scenarios.(opts.scenario).duration_s, 17), ...
        'SignalLogging', 'on', ...
        'SignalLoggingName', 'logsout', ...
        'ReturnWorkspaceOutputs', 'on');

    ws = get_param(mdl, 'ModelWorkspace');
    local_assign_workspace_vars(ws, sc_data, opts.style, opts.scenario);

    % 1. World, Mechanism Configuration, Solver Configuration
    world_port = local_build_world(mdl);

    % 2. Free-body club branch (6-DOF Joint + principal Inertia + Transform Sensor + External Force and Torque)
    [club_sensor_ports, club_eft_blk] = local_build_club_branch(mdl, world_port);

    % 3. Prescribed Hand_L and Hand_R branches (Init Pose -> Bushing Joint -> Inertia + Transform Sensor)
    [hand_l_in_ports, hand_l_sensor_ports] = local_build_hand_branch(mdl, world_port, 'L', 350);
    [hand_r_in_ports, hand_r_sensor_ports] = local_build_hand_branch(mdl, world_port, 'R', 700);

    % 4. Hand trajectory generator (Clock -> MATLAB Function -> Demux -> Simulink-PS Converters)
    local_build_trajectory_driver(mdl, hand_l_in_ports, hand_r_in_ports);

    % 5. Grip Contact Kernel MATLAB Function + External Wrench + Logging
    local_build_kernel_and_logging(mdl, club_sensor_ports, hand_l_sensor_ports, ...
        hand_r_sensor_ports, club_eft_blk);

    % 6. Assert compiled block budget (< 1000 Home license ceiling) and absence of hand-club welds
    weld_blocks = find_system(mdl, 'ReferenceBlock', 'sm_lib/Joints/Weld Joint');
    assert(isempty(weld_blocks), 'gs3dx:grip_contact:UnexpectedWeld', ...
        'GS3DX_GripContact must not contain any hand-on-club Weld Joint blocks.');

    budget = gs3dx_block_budget(mdl, compiled=true);
    reserve = 25;
    assert(budget.compiled_total <= names.license_block_limit - reserve, ...
        'gs3dx:grip_contact:BudgetExceeded', ...
        '%s compiles to %d blocks; ceiling %d with reserve %d exceeded.', ...
        mdl, budget.compiled_total, names.license_block_limit, reserve);

    if opts.save_model
        if ~isfolder(out_dir_str)
            mkdir(out_dir_str);
        end
        save_system(mdl, slx_path);
    end

    report = struct( ...
        'model_name', mdl, ...
        'model_path', slx_path, ...
        'repo_root', repo_root_str, ...
        'budget', budget, ...
        'style', opts.style, ...
        'scenario', opts.scenario);
end

function [repo_root_str, out_dir_str, tools_dir, gen_dir] = local_resolve_paths(repo_root, out_dir)
    here = fileparts(mfilename('fullpath'));
    if isstruct(repo_root)
        info = repo_root;
        out_dir_str = char(info.models_dir);
        repo_root_str = char(fullfile(here, '..', '..', '..', '..', '..', '..'));
    else
        repo_root_str = char(repo_root);
        if isempty(strtrim(repo_root_str))
            repo_root_str = char(fullfile(here, '..', '..', '..', '..', '..', '..'));
        end
        out_dir_str = char(out_dir);
        if isempty(strtrim(out_dir_str))
            out_dir_str = fullfile(here, '..', 'models');
        end
    end
    tools_dir = fullfile(repo_root_str, ...
        'src/engines/Simscape_Multibody_Models/3D_Golf_Model/matlab/exploratory_gs3dx/tools');
    if ~isfolder(tools_dir)
        tools_dir = here;
    end
    gen_dir = fullfile(tools_dir, 'generated');
end

function local_safe_close(mdl)
    if bdIsLoaded(mdl)
        close_system(mdl, 0);
    end
end

function local_assign_workspace_vars(ws, sc_data, style_name, scenario_name)
    st = sc_data.styles.(style_name);
    sc = sc_data.scenarios.(scenario_name);
    club = sc_data.club;

    assignin(ws, 'GripStyleId', double(st.style_id));
    assignin(ws, 'GravityVec', reshape(double(sc_data.gravity_m_s2), 1, 3));
    assignin(ws, 'ClubMassKg', double(club.mass_kg));
    assignin(ws, 'ClubComOffset', reshape(double(club.com_m), 1, 3));
    assignin(ws, 'ClubPrincipalMoments', reshape(double(club.principal_moments_kg_m2), 1, 3));
    assignin(ws, 'ClubPrincipalAxes', double(club.principal_axes_club));

    c0 = sc.initial_club_state;
    assignin(ws, 'ClubInitPos', reshape(double(c0.position_m), 1, 3));
    assignin(ws, 'ClubInitRot', double(c0.rotation_world_from_club));
    assignin(ws, 'ClubInitVelLocal', reshape(double(c0.velocity_local_m_s), 1, 3));
    assignin(ws, 'ClubInitOmegaLocal', reshape(double(c0.omega_local_rad_s), 1, 3));

    hl0 = sc.initial_hand_states.L;
    hr0 = sc.initial_hand_states.R;
    assignin(ws, 'HandLInitPos', reshape(double(hl0.position_m), 1, 3));
    assignin(ws, 'HandLInitRot', double(hl0.rotation_world_from_hand));
    assignin(ws, 'HandRInitPos', reshape(double(hr0.position_m), 1, 3));
    assignin(ws, 'HandRInitRot', double(hr0.rotation_world_from_hand));

    assignin(ws, 'TrajTimeGrid', reshape(double(sc.time_s), [], 1));
    assignin(ws, 'HandLQRel', double(sc.hand_trajectories.L.q_rel));
    assignin(ws, 'HandLB', double(sc.hand_trajectories.L.hermite_b));
    assignin(ws, 'HandLC', double(sc.hand_trajectories.L.hermite_c));
    assignin(ws, 'HandLD', double(sc.hand_trajectories.L.hermite_d));
    assignin(ws, 'HandRQRel', double(sc.hand_trajectories.R.q_rel));
    assignin(ws, 'HandRB', double(sc.hand_trajectories.R.hermite_b));
    assignin(ws, 'HandRC', double(sc.hand_trajectories.R.hermite_c));
    assignin(ws, 'HandRD', double(sc.hand_trajectories.R.hermite_d));
end

function world_port = local_build_world(mdl)
    wf = add_block('sm_lib/Frames and Transforms/World Frame', [mdl '/World'], ...
        'Position', [40 120 80 160]);
    mc = add_block('sm_lib/Utilities/Mechanism Configuration', [mdl '/Mechanism Configuration'], ...
        'GravityVector', 'GravityVec', 'GravityVectorUnits', 'm/s^2', ...
        'Position', [40 200 100 240]);
    sc = add_block('nesl_utility/Solver Configuration', [mdl '/Solver Configuration'], ...
        'Position', [40 280 100 320]);
    world_port = local_port(wf, 'RConn', 1);
    add_line(mdl, world_port, local_port(mc, 'RConn', 1), 'autorouting', 'on');
    add_line(mdl, world_port, local_port(sc, 'RConn', 1), 'autorouting', 'on');
end

function [sensor_ports, eft_blk] = local_build_club_branch(mdl, world_port)
    rt0 = add_block('sm_lib/Frames and Transforms/Rigid Transform', [mdl '/Club Init Pose'], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', 'ClubInitPos', ...
        'TranslationCartesianOffsetUnits', 'm', ...
        'RotationMethod', 'RotationMatrix', ...
        'RotationMatrix', 'ClubInitRot', ...
        'Position', [180 110 230 150]);
    add_line(mdl, world_port, local_port(rt0, 'LConn', 1), 'autorouting', 'on');

    j6 = add_block('sm_lib/Joints/6-DOF Joint', [mdl '/Club 6DOF Joint'], ...
        'PxPositionTargetSpecify', 'on', 'PxPositionTargetPriority', 'High', ...
        'PxPositionTargetValue', '0', 'PxPositionTargetValueUnits', 'm', ...
        'PyPositionTargetSpecify', 'on', 'PyPositionTargetPriority', 'High', ...
        'PyPositionTargetValue', '0', 'PyPositionTargetValueUnits', 'm', ...
        'PzPositionTargetSpecify', 'on', 'PzPositionTargetPriority', 'High', ...
        'PzPositionTargetValue', '0', 'PzPositionTargetValueUnits', 'm', ...
        'PxVelocityTargetSpecify', 'on', 'PxVelocityTargetPriority', 'High', ...
        'PxVelocityTargetValue', 'ClubInitVelLocal(1)', 'PxVelocityTargetValueUnits', 'm/s', ...
        'PyVelocityTargetSpecify', 'on', 'PyVelocityTargetPriority', 'High', ...
        'PyVelocityTargetValue', 'ClubInitVelLocal(2)', 'PyVelocityTargetValueUnits', 'm/s', ...
        'PzVelocityTargetSpecify', 'on', 'PzVelocityTargetPriority', 'High', ...
        'PzVelocityTargetValue', 'ClubInitVelLocal(3)', 'PzVelocityTargetValueUnits', 'm/s', ...
        'SphPositionTargetSpecify', 'on', 'SphPositionTargetPriority', 'High', ...
        'SphPositionTargetRotationMethod', 'RotationSequence', ...
        'SphPositionTargetRotationSequence', 'XYZ', ...
        'SphPositionTargetRotationSequenceAngles', '[0 0 0]', ...
        'SphPositionTargetRotationSequenceAnglesUnits', 'deg', ...
        'SphVelocityTargetSpecify', 'on', 'SphVelocityTargetPriority', 'High', ...
        'SphVelocityTargetInFollowerFrame', 'on', ...
        'SphVelocityTargetValue', 'ClubInitOmegaLocal', ...
        'SphVelocityTargetValueUnits', 'rad/s', ...
        'Position', [280 100 340 160]);
    add_line(mdl, local_port(rt0, 'RConn', 1), local_port(j6, 'LConn', 1), 'autorouting', 'on');
    club_origin = local_port(j6, 'RConn', 1);

    rt_com = add_block('sm_lib/Frames and Transforms/Rigid Transform', [mdl '/Club COM Transform'], ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', 'ClubComOffset', ...
        'TranslationCartesianOffsetUnits', 'm', ...
        'RotationMethod', 'RotationMatrix', ...
        'RotationMatrix', 'ClubPrincipalAxes', ...
        'Position', [400 60 450 100]);
    add_line(mdl, club_origin, local_port(rt_com, 'LConn', 1), 'autorouting', 'on');

    in_blk = add_block('sm_lib/Body Elements/Inertia', [mdl '/Club Inertia'], ...
        'InertiaType', 'Custom', 'Mass', 'ClubMassKg', 'MassUnits', 'kg', ...
        'CenterOfMass', '[0 0 0]', 'CenterOfMassUnits', 'm', ...
        'MomentsOfInertia', 'ClubPrincipalMoments', 'MomentsOfInertiaUnits', 'kg*m^2', ...
        'ProductsOfInertia', '[0 0 0]', 'ProductsOfInertiaUnits', 'kg*m^2', ...
        'Position', [500 60 550 100]);
    add_line(mdl, local_port(rt_com, 'RConn', 1), local_port(in_blk, 'RConn', 1), 'autorouting', 'on');

    sensor_ports = local_add_pose_twist_sensor(mdl, 'Club', world_port, club_origin, [400 130]);

    eft_blk = add_block('sm_lib/Forces and Torques/External Force and Torque', ...
        [mdl '/Club External Wrench'], 'Position', [400 220 470 280]);
    local_attach_external_wrench_frame(mdl, eft_blk, club_origin);
end

function [in_ports, sensor_ports] = local_build_hand_branch(mdl, world_port, side, y0)
    rt0 = add_block('sm_lib/Frames and Transforms/Rigid Transform', ...
        sprintf('%s/Hand %s Init Pose', mdl, side), ...
        'TranslationMethod', 'Cartesian', ...
        'TranslationCartesianOffset', sprintf('Hand%sInitPos', side), ...
        'TranslationCartesianOffsetUnits', 'm', ...
        'RotationMethod', 'RotationMatrix', ...
        'RotationMatrix', sprintf('Hand%sInitRot', side), ...
        'Position', [180 y0 230 y0 + 40]);
    add_line(mdl, world_port, local_port(rt0, 'LConn', 1), 'autorouting', 'on');

    bj = add_block('sm_lib/Joints/Bushing Joint', ...
        sprintf('%s/Hand %s Prescribed Joint', mdl, side), ...
        'Position', [280 y0 - 20 340 y0 + 120]);
    prims = {'Px', 'Py', 'Pz', 'Rx', 'Ry', 'Rz'};
    for k = 1:numel(prims)
        P = prims{k};
        set_param(bj, ...
            [P 'MotionActuationMode'], 'InputMotion', ...
            [P 'TorqueActuationMode'], 'ComputedTorque', ...
            [P 'PositionTargetSpecify'], 'off', ...
            [P 'VelocityTargetSpecify'], 'off');
    end
    add_line(mdl, local_port(rt0, 'RConn', 1), local_port(bj, 'LConn', 1), 'autorouting', 'on');
    hand_frame = local_port(bj, 'RConn', 1);

    in_blk = add_block('sm_lib/Body Elements/Inertia', ...
        sprintf('%s/Hand %s Inertia', mdl, side), ...
        'InertiaType', 'Custom', 'Mass', '1.0', 'MassUnits', 'kg', ...
        'CenterOfMass', '[0 0 0]', 'CenterOfMassUnits', 'm', ...
        'MomentsOfInertia', '[1e-3 1e-3 1e-3]', 'MomentsOfInertiaUnits', 'kg*m^2', ...
        'ProductsOfInertia', '[0 0 0]', 'ProductsOfInertiaUnits', 'kg*m^2', ...
        'Position', [400 y0 - 20 450 y0 + 20]);
    add_line(mdl, hand_frame, local_port(in_blk, 'RConn', 1), 'autorouting', 'on');

    in_ports = zeros(1, 6);
    for k = 1:6
        in_ports(k) = local_port(bj, 'LConn', k + 1);
    end
    sensor_ports = local_add_pose_twist_sensor(mdl, ['Hand_' side], world_port, hand_frame, [400 y0 + 40]);
end

function out_ports = local_add_pose_twist_sensor(mdl, prefix, world_port, follower_port, xy)
    ts = add_block('sm_lib/Frames and Transforms/Transform Sensor', ...
        sprintf('%s/%s Transform Sensor', mdl, prefix), ...
        'MeasurementFrame', 'World', ...
        'SenseR', 'on', ...
        'SenseOmega', 'on', ...
        'SenseXYZ', 'on', ...
        'SenseXYZDot', 'on', ...
        'Position', [xy(1) xy(2) xy(1) + 60 xy(2) + 80]);
    add_line(mdl, world_port, local_port(ts, 'LConn', 1), 'autorouting', 'on');
    add_line(mdl, follower_port, local_port(ts, 'RConn', 1), 'autorouting', 'on');

    % Transform Sensor RConn port order when SenseR, SenseOmega, SenseXYZ, SenseXYZDot are on:
    % RConn(2) = R (1), RConn(3) = w (rad/s), RConn(4) = p (m), RConn(5) = v (m/s).
    % Return Simulink Outports ordered [p, R, v, omega] to match gs3dx_grip_contact_kernel.
    specs = { ...
        'p', 4, 'm'; ...
        'R', 2, '1'; ...
        'v', 5, 'm/s'; ...
        'w', 3, 'rad/s'};
    out_ports = zeros(1, 4);
    for k = 1:4
        yy = xy(2) + 22 * (k - 1);
        cv = add_block('nesl_utility/PS-Simulink Converter', ...
            sprintf('%s/%s_%s_PS2S', mdl, prefix, specs{k, 1}), ...
            'Unit', specs{k, 3}, ...
            'Position', [xy(1) + 90 yy xy(1) + 120 yy + 18]);
        add_line(mdl, local_port(ts, 'RConn', specs{k, 2}), local_port(cv, 'LConn', 1), 'autorouting', 'on');
        out_ports(k) = local_port(cv, 'Outport', 1);
    end
end

function local_build_trajectory_driver(mdl, hand_l_in_ports, hand_r_in_ports)
    clk = add_block('simulink/Sources/Clock', [mdl '/Trajectory Clock'], ...
        'Position', [40 500 65 525]);
    gen = add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/Hand Trajectory Generator'], ...
        'Position', [110 470 250 580]);
    chart = local_chart(gen);
    params = {'TrajTimeGrid', 'HandLQRel', 'HandLB', 'HandLC', 'HandLD', ...
        'HandRQRel', 'HandRB', 'HandRC', 'HandRD'};
    p_list = strjoin(params, ', ');
    chart.Script = sprintf([ ...
        'function [q_L, qd_L, qdd_L, q_R, qd_R, qdd_R] = fcn(t, %s)\n' ...
        '%% Evaluate Hermite cubic 6-DOF hand trajectories (#13334).\n' ...
        'n = numel(TrajTimeGrid);\n' ...
        'tc = min(max(t, TrajTimeGrid(1)), TrajTimeGrid(n));\n' ...
        'idx = 1;\n' ...
        'for k = 1:(n - 1)\n' ...
        '    if tc >= TrajTimeGrid(k)\n' ...
        '        idx = k;\n' ...
        '    end\n' ...
        'end\n' ...
        'dt = tc - TrajTimeGrid(idx);\n' ...
        'q_L = (HandLQRel(idx, :) + dt * (HandLB(idx, :) + dt * (HandLC(idx, :) + dt * HandLD(idx, :)))).'';\n' ...
        'qd_L = (HandLB(idx, :) + dt * (2.0 * HandLC(idx, :) + 3.0 * dt * HandLD(idx, :))).'';\n' ...
        'qdd_L = (2.0 * HandLC(idx, :) + 6.0 * dt * HandLD(idx, :)).'';\n' ...
        'q_R = (HandRQRel(idx, :) + dt * (HandRB(idx, :) + dt * (HandRC(idx, :) + dt * HandRD(idx, :)))).'';\n' ...
        'qd_R = (HandRB(idx, :) + dt * (2.0 * HandRC(idx, :) + 3.0 * dt * HandRD(idx, :))).'';\n' ...
        'qdd_R = (2.0 * HandRC(idx, :) + 6.0 * dt * HandRD(idx, :)).'';\n' ...
        'end\n'], p_list);
    for k = 1:numel(params)
        d = chart.find('-isa', 'Stateflow.Data', 'Name', params{k});
        assert(isscalar(d), 'gs3dx:grip_contact:MissingParam', 'Missing parameter %s', params{k});
        d.Scope = 'Parameter';
    end
    add_line(mdl, local_port(clk, 'Outport', 1), local_port(gen, 'Inport', 1), 'autorouting', 'on');

    local_wire_hand_converters(mdl, 'L', gen, [1 2 3], hand_l_in_ports, 350);
    local_wire_hand_converters(mdl, 'R', gen, [4 5 6], hand_r_in_ports, 700);
end

function local_wire_hand_converters(mdl, side, gen_blk, out_idx, dst_lconn_ports, y0)
    units = {'m', 'm', 'm', 'rad', 'rad', 'rad'};
    d_q = add_block('simulink/Signal Routing/Demux', sprintf('%s/Hand_%s_q_Demux', mdl, side), ...
        'Outputs', '6', 'Position', [290 y0 295 y0 + 90]);
    d_qd = add_block('simulink/Signal Routing/Demux', sprintf('%s/Hand_%s_qd_Demux', mdl, side), ...
        'Outputs', '6', 'Position', [290 y0 + 100 295 y0 + 190]);
    d_qdd = add_block('simulink/Signal Routing/Demux', sprintf('%s/Hand_%s_qdd_Demux', mdl, side), ...
        'Outputs', '6', 'Position', [290 y0 + 200 295 y0 + 290]);

    add_line(mdl, local_port(gen_blk, 'Outport', out_idx(1)), local_port(d_q, 'Inport', 1), 'autorouting', 'on');
    add_line(mdl, local_port(gen_blk, 'Outport', out_idx(2)), local_port(d_qd, 'Inport', 1), 'autorouting', 'on');
    add_line(mdl, local_port(gen_blk, 'Outport', out_idx(3)), local_port(d_qdd, 'Inport', 1), 'autorouting', 'on');

    for k = 1:6
        cv = add_block('nesl_utility/Simulink-PS Converter', ...
            sprintf('%s/Hand_%s_Axis_%d_S2PS', mdl, side, k), ...
            'Unit', units{k}, ...
            'FilteringAndDerivatives', 'provide', ...
            'UdotUserProvided', '2', ...
            'Position', [320 y0 + 35 * (k - 1) 350 y0 + 35 * (k - 1) + 25]);
        ph = get_param(cv, 'PortHandles');
        if numel(ph.Inport) == 3
            add_line(mdl, local_port(d_q, 'Outport', k), ph.Inport(1), 'autorouting', 'on');
            add_line(mdl, local_port(d_qd, 'Outport', k), ph.Inport(2), 'autorouting', 'on');
            add_line(mdl, local_port(d_qdd, 'Outport', k), ph.Inport(3), 'autorouting', 'on');
        else
            set_param(cv, 'FilteringAndDerivatives', 'filter', ...
                'SimscapeFilterOrder', '2', 'InputFilterTimeConstant', '1e-5');
            ph = get_param(cv, 'PortHandles');
            add_line(mdl, local_port(d_q, 'Outport', k), ph.Inport(1), 'autorouting', 'on');
        end
        add_line(mdl, ph.RConn(1), dst_lconn_ports(k), 'autorouting', 'on');
    end
end

function local_build_kernel_and_logging(mdl, club_sp, hl_sp, hr_sp, eft_blk)
    kern = add_block('simulink/User-Defined Functions/MATLAB Function', ...
        [mdl '/Grip Contact Kernel'], ...
        'Position', [650 120 860 520]);
    chart = local_chart(kern);
    chart.Script = strrep([ ...
        'function [F_club_w, M_club_w, F_hand_L_w, M_hand_L_w, F_hand_R_w, M_hand_R_w, ' ...
        'pair_normal_n, pair_tangent_n, pair_spin_nm, pair_penetration_m, ' ...
        'pair_slip_speed_m_s, pair_signed_dist_m, pair_force_club_w, ' ...
        'pair_moment_club_w, pair_contact_point_w] = fcn(' ...
        'p_club, R_club, v_club, omega_club, ' ...
        'p_hand_L, R_hand_L, v_hand_L, omega_hand_L, ' ...
        'p_hand_R, R_hand_R, v_hand_R, omega_hand_R, ' ...
        'GripStyleId)\n' ...
        '% Call generated codegen grip contact kernel (#13334).\n' ...
        '[F_club_w, M_club_w, F_hand_L_w, M_hand_L_w, F_hand_R_w, M_hand_R_w, ' ...
        'pair_normal_n, pair_tangent_n, pair_spin_nm, pair_penetration_m, ' ...
        'pair_slip_speed_m_s, pair_signed_dist_m, pair_force_club_w, ' ...
        'pair_moment_club_w, pair_contact_point_w] = gs3dx_grip_contact_kernel(' ...
        'reshape(p_club, 3, 1), reshape(R_club, 3, 3), reshape(v_club, 3, 1), reshape(omega_club, 3, 1), ' ...
        'reshape(p_hand_L, 3, 1), reshape(R_hand_L, 3, 3), reshape(v_hand_L, 3, 1), reshape(omega_hand_L, 3, 1), ' ...
        'reshape(p_hand_R, 3, 1), reshape(R_hand_R, 3, 3), reshape(v_hand_R, 3, 1), reshape(omega_hand_R, 3, 1), ' ...
        'GripStyleId);\n' ...
        'end\n'], '\n', newline);
    d_style = chart.find('-isa', 'Stateflow.Data', 'Name', 'GripStyleId');
    assert(isscalar(d_style), 'gs3dx:grip_contact:MissingStyleParam', 'Missing GripStyleId');
    d_style.Scope = 'Parameter';

    all_sp = [club_sp, hl_sp, hr_sp];
    for k = 1:12
        add_line(mdl, all_sp(k), local_port(kern, 'Inport', k), 'autorouting', 'on');
    end

    % Connect F_club_w (Outport 1) and M_club_w (Outport 2) to External Force and Torque
    local_wire_external_wrench_inputs(mdl, eft_blk, ...
        local_port(kern, 'Outport', 1), local_port(kern, 'Outport', 2));

    % Log all sensed kinematics and kernel outputs
    kin_names = {'club_p_w', 'club_R_w', 'club_v_w', 'club_omega_w', ...
        'hand_L_p_w', 'hand_L_R_w', 'hand_L_v_w', 'hand_L_omega_w', ...
        'hand_R_p_w', 'hand_R_R_w', 'hand_R_v_w', 'hand_R_omega_w'};
    for k = 1:numel(kin_names)
        local_log_port(mdl, all_sp(k), kin_names{k}, [560, 40 + 25 * k]);
    end

    out_names = {'F_club_w', 'M_club_w', 'F_hand_L_w', 'M_hand_L_w', ...
        'F_hand_R_w', 'M_hand_R_w', 'pair_normal_n', 'pair_tangent_n', ...
        'pair_spin_nm', 'pair_penetration_m', 'pair_slip_speed_m_s', ...
        'pair_signed_dist_m', 'pair_force_club_w', 'pair_moment_club_w', ...
        'pair_contact_point_w'};
    for k = 1:numel(out_names)
        local_log_port(mdl, local_port(kern, 'Outport', k), out_names{k}, [940, 100 + 26 * k]);
    end
end

function local_attach_external_wrench_frame(mdl, eft_blk, club_origin_port)
    ph0 = get_param(eft_blk, 'PortHandles');
    if ~isempty(ph0.RConn)
        frame_port = ph0.RConn(1);
    else
        frame_port = ph0.LConn(1);
    end
    add_line(mdl, club_origin_port, frame_port, 'autorouting', 'on');
end

function local_wire_external_wrench_inputs(mdl, eft_blk, f_outport, m_outport)
    ph_before = get_param(eft_blk, 'PortHandles');
    dp = get_param(eft_blk, 'DialogParameters');
    if isfield(dp, 'ForceResolutionFrame')
        set_param(eft_blk, 'ForceResolutionFrame', 'World');
    end
    if isfield(dp, 'TorqueResolutionFrame')
        set_param(eft_blk, 'TorqueResolutionFrame', 'World');
    end
    if isfield(dp, 'EnableForce')
        try
            set_param(eft_blk, 'EnableForce', 'Vector');
        catch
            set_param(eft_blk, 'EnableForce', 'on');
        end
    else
        for ax = {'X', 'Y', 'Z'}
            if isfield(dp, ['EnableForce' ax{1}])
                set_param(eft_blk, ['EnableForce' ax{1}], 'on');
            end
        end
    end
    if isfield(dp, 'EnableTorque')
        try
            set_param(eft_blk, 'EnableTorque', 'Vector');
        catch
            set_param(eft_blk, 'EnableTorque', 'on');
        end
    else
        for ax = {'X', 'Y', 'Z'}
            if isfield(dp, ['EnableTorque' ax{1}])
                set_param(eft_blk, ['EnableTorque' ax{1}], 'on');
            end
        end
    end

    ph_after = get_param(eft_blk, 'PortHandles');
    ps_ports = setdiff([ph_after.LConn, ph_after.RConn], [ph_before.LConn, ph_before.RConn]);
    if numel(ps_ports) == 2
        f_cv = add_block('nesl_utility/Simulink-PS Converter', [mdl '/Club_F_S2PS'], ...
            'Unit', 'N', 'Position', [520 220 550 240]);
        m_cv = add_block('nesl_utility/Simulink-PS Converter', [mdl '/Club_M_S2PS'], ...
            'Unit', 'N*m', 'Position', [520 255 550 275]);
        add_line(mdl, f_outport, local_port(f_cv, 'Inport', 1), 'autorouting', 'on');
        add_line(mdl, m_outport, local_port(m_cv, 'Inport', 1), 'autorouting', 'on');
        add_line(mdl, local_port(f_cv, 'RConn', 1), ps_ports(1), 'autorouting', 'on');
        add_line(mdl, local_port(m_cv, 'RConn', 1), ps_ports(2), 'autorouting', 'on');
    elseif numel(ps_ports) == 6
        df = add_block('simulink/Signal Routing/Demux', [mdl '/Club_F_Demux'], ...
            'Outputs', '3', 'Position', [490 215 495 245]);
        dm = add_block('simulink/Signal Routing/Demux', [mdl '/Club_M_Demux'], ...
            'Outputs', '3', 'Position', [490 255 495 285]);
        add_line(mdl, f_outport, local_port(df, 'Inport', 1), 'autorouting', 'on');
        add_line(mdl, m_outport, local_port(dm, 'Inport', 1), 'autorouting', 'on');
        for k = 1:3
            f_cv = add_block('nesl_utility/Simulink-PS Converter', ...
                sprintf('%s/Club_F_%d_S2PS', mdl, k), 'Unit', 'N', ...
                'Position', [520 200 + 18 * k 545 215 + 18 * k]);
            m_cv = add_block('nesl_utility/Simulink-PS Converter', ...
                sprintf('%s/Club_M_%d_S2PS', mdl, k), 'Unit', 'N*m', ...
                'Position', [520 260 + 18 * k 545 275 + 18 * k]);
            add_line(mdl, local_port(df, 'Outport', k), local_port(f_cv, 'Inport', 1), 'autorouting', 'on');
            add_line(mdl, local_port(dm, 'Outport', k), local_port(m_cv, 'Inport', 1), 'autorouting', 'on');
            add_line(mdl, local_port(f_cv, 'RConn', 1), ps_ports(k), 'autorouting', 'on');
            add_line(mdl, local_port(m_cv, 'RConn', 1), ps_ports(k + 3), 'autorouting', 'on');
        end
    else
        error('gs3dx:grip_contact:UnexpectedEFTPorts', ...
            'Expected 2 or 6 physical-signal ports on External Force and Torque, found %d.', ...
            numel(ps_ports));
    end
end

function local_log_port(mdl, src_outport, sig_name, xy)
    term = add_block('simulink/Sinks/Terminator', sprintf('%s/Log_%s', mdl, sig_name), ...
        'Position', [xy(1) xy(2) xy(1) + 20 xy(2) + 16]);
    h = add_line(mdl, src_outport, local_port(term, 'Inport', 1), 'autorouting', 'on');
    set_param(h, 'Name', sig_name);
    set_param(src_outport, 'DataLogging', 'on');
end

function p = local_port(blk, kind, idx)
    ph = get_param(blk, 'PortHandles');
    p = ph.(kind)(idx);
end

function chart = local_chart(blk)
    chart = sfroot().find('-isa', 'Stateflow.EMChart', 'Path', getfullname(blk));
    assert(isscalar(chart), 'gs3dx:grip_contact:MissingChart', ...
        'No MATLAB Function chart found for %s', getfullname(blk));
end
