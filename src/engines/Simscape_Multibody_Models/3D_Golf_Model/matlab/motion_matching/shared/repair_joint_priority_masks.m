function reports = repair_joint_priority_masks(model_directory)
%REPAIR_JOINT_PRIORITY_MASKS Connect declared priority controls to primitives.
% None disables a state target. Low/High enable it at the selected priority.
% The callback is embedded so the subsystem files have no new path dependency.
    arguments
        model_directory (1,1) string {mustBeFolder}
    end
    kinds = ["Gimbal", "Universal", "Revolute"];
    primitives = ["Kinetically Driven", "Kinetically Driven Universal Joint", ...
        "Kinetically Driven Revolute"];
    axes = {{'Rx','Ry','Rz'}, {'Rx','Ry'}, {'Rz'}};
    reports = struct('file', {}, 'changed', {});
    for k = 1:numel(kinds)
        model = "Kinetically_Driven_" + kinds(k) + "_Joint";
        file = fullfile(model_directory, model + ".slx");
        assert(isfile(file) && ~bdIsLoaded(model), ...
            'repair_joint_priority_masks:unavailableModel', ...
            'Model must exist and be closed: %s', file);
        load_system(file);
        cleanup = onCleanup(@() bdclose(model));
        mask = Simulink.Mask.get(model);
        assert(~isempty(mask), 'repair_joint_priority_masks:missingMask', ...
            'Referenced subsystem requires a system mask.');
        target_axes = axes{k};
        if kinds(k) == "Revolute", target_axes = {''}; end
        callback = priority_callback(primitives(k), axes{k}, target_axes);
        previous = string(mask.Initialization);
        assert(previous == "" || previous == string(callback), ...
            'repair_joint_priority_masks:unexpectedCallback', ...
            'Existing initialization is not owned by this migration.');
        changed = previous ~= string(callback) || string(mask.SelfModifiable) ~= "on";
        if changed
            mask.SelfModifiable = 'on';
            mask.RunInitForIconRedraw = 'on';
            mask.Initialization = callback;
            save_system(model, file);
        end
        reports(end+1) = struct('file', file, 'changed', changed); %#ok<AGROW>
        clear cleanup;
    end
end

function callback = priority_callback(primitive, mask_axes, target_axes)
    mask_literal = "{'" + strjoin(string(mask_axes), "','") + "'}";
    target_literal = "{'" + strjoin(string(target_axes), "','") + "'}";
    lines = [ ...
        "% Joint target priority binding, issue #9927."; ...
        "jointMaskAxes = " + mask_literal + ";"; ...
        "jointTargetAxes = " + target_literal + ";"; ...
        "jointPrimitive = [gcb '/" + primitive + "'];"; ...
        "for jointAxisIndex = 1:numel(jointMaskAxes)"; ...
        "  for jointQuantity = {'Position','Velocity'}"; ...
        "    jointMaskKey = [jointMaskAxes{jointAxisIndex} jointQuantity{1} 'TargetPriority'];"; ...
        "    jointPriority = get_param(gcb, jointMaskKey);"; ...
        "    assert(ismember(jointPriority, {'None','Low','High'}), 'Invalid joint target priority');"; ...
        "    jointTargetKey = [jointTargetAxes{jointAxisIndex} jointQuantity{1} 'Target'];"; ...
        "    if strcmp(jointPriority, 'None')"; ...
        "      set_param(jointPrimitive, [jointTargetKey 'Specify'], 'off');"; ...
        "    else"; ...
        "      set_param(jointPrimitive, [jointTargetKey 'Specify'], 'on', ..."; ...
        "        [jointTargetKey 'Priority'], jointPriority);"; ...
        "    end"; ...
        "  end"; ...
        "end"];
    callback = char(strjoin(lines, newline));
end
