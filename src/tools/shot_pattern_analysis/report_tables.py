"""Render the article's numerical tables from the hash-bound headline dataset.

Every number the LaTeX article states about the headline conditions comes
from ``headline_dataset.json`` through this module, so prose, tables and data
cannot drift apart. Strokes gained is shown per 100 modeled shots; distances
are metres with yards in parentheses. ``--check`` fails when the committed
tables differ from a fresh render.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any, Final

from .assumption_band import CURVED_PATTERNS
from .core import PATTERN_NAMES
from .headline_selection import (
    CLUB_LABELS,
    CLUB_ORDER,
    PROTOCOL_KEYS,
    condition_parts,
)

METRES_PER_YARD: Final = 0.9144
SG_SCALE: Final = 100.0
"""Strokes gained is tabulated per 100 modeled shots."""

HEADER: Final = (
    "% Generated by src.tools.shot_pattern_analysis.report_tables from\n"
    "% phase2/statistics_v2/headline_dataset.json. Do not edit by hand.\n"
)
CONTRAST_LABELS: Final = {
    "shaft_rotation_sd": r"Twist SD $1^\circ \to 2^\circ$",
    "curve_strength": r"Curve $1\times \to 2\times$",
    "across_lean": r"Lean $0^\circ \to 5^\circ$",
}
DIRECTION_LABELS: Final = {
    "positive": "Positive",
    "negative": "Negative",
    "spans_zero": "Spans 0",
}


def signed(value: float, digits: int = 3) -> str:
    """Format a signed number in math mode with a true minus sign."""
    text = f"{value:+.{digits}f}"
    if float(text) == 0:
        text = f"{0:.{digits}f}"
    return f"${text}$"


def sg(value: float) -> str:
    """Strokes gained per 100 shots, signed, three decimals."""
    return signed(SG_SCALE * value)


def sg_interval(lower: float, upper: float) -> str:
    """Bracketed interval per 100 shots, e.g. ``[+0.248, +0.335]``."""
    low = f"{SG_SCALE * lower:+.3f}"
    high = f"{SG_SCALE * upper:+.3f}"
    return f"$[{low},\\ {high}]$"


def metres(value: float, digits: int = 2) -> str:
    """Metres with yards in parentheses."""
    return f"{value:.{digits}f} ({value / METRES_PER_YARD:.{digits}f})"


def count(value: int) -> str:
    return f"{value:,}".replace(",", "{,}")


def direction(interval: Mapping[str, float]) -> str:
    if interval["lower_95"] > 0:
        return "positive"
    if interval["upper_95"] < 0:
        return "negative"
    return "spans_zero"


def longtable(
    caption: str,
    columns: str,
    header: Sequence[str] | str,
    rows: Iterable[Sequence[str]],
    size: str = "small",
) -> str:
    """A captioned booktabs longtable that repeats its header across pages.

    ``header`` is a sequence of column titles or one preformatted header row;
    ``size`` is a LaTeX font-size command name such as ``footnotesize``.
    """
    head = header if isinstance(header, str) else " & ".join(header)
    head += r" \\ \midrule"
    body = "\n".join(" & ".join(row) + r" \\" for row in rows)
    return (
        HEADER
        + f"{{\\{size}\n\\Needspace{{10\\baselineskip}}\n"
        + f"\\begin{{longtable}}{{{columns}}}\n"
        + f"\\caption{{{caption}}}\\\\\n\\toprule {head}\n\\endfirsthead\n"
        + f"\\caption[]{{{caption} (Continued)}}\\\\\n\\toprule {head}\n\\endhead\n"
        + body
        + "\n\\bottomrule\\end{longtable}\n}\n"
    )


def _cells(dataset: Mapping[str, Any], club_id: str | None = None) -> list[dict]:
    return [
        cell
        for cell in dataset["cells"]
        if club_id is None or cell["club_id"] == club_id
    ]


def conditions_table(dataset: Mapping[str, Any]) -> str:
    rows = []
    for cell in _cells(dataset):
        club, curve, sd, profile = condition_parts(cell["cell"])
        rows.append(
            (
                cell["key"],
                club,
                f"${curve}\\times$",
                f"${sd}^\\circ$",
                profile,
                PROTOCOL_KEYS[cell["protocol"]],
                metres(cell["target_x_m"], 1),
            )
        )
    return longtable(
        "Selected Zero-Lean Conditions",
        "lllllll",
        (
            "Key",
            "Club",
            "Curve",
            "Twist SD",
            "Noise Profile",
            "Protocol",
            "Target, m (yd)",
        ),
        rows,
    )


def geometry_table(dataset: Mapping[str, Any], club_id: str) -> str:
    rows = []
    for cell in _cells(dataset, club_id):
        for pattern in PATTERN_NAMES:
            item = cell["geometry"][pattern]
            rows.append(
                (
                    cell["key"],
                    pattern,
                    count(item["supported_n"]),
                    metres(item["lateral_sd_m"]),
                    metres(item["downrange_sd_m"]),
                    metres(item["mean_carry_m"], 1),
                    metres(item["target_rmse_m"]),
                    signed(cell["mean_strokes_gained"][pattern], 4),
                )
            )
    return longtable(
        f"{CLUB_LABELS[club_id]} Endpoint Dispersion and Absolute Strokes Gained",
        "llrrrrrr",
        (
            "Key",
            "Pattern",
            "$n_e$",
            "Lateral SD",
            "Downrange SD",
            "Mean Carry",
            "Target RMSE",
            "Mean SG",
        ),
        rows,
    )


def paired_table(dataset: Mapping[str, Any], club_id: str) -> str:
    rows = []
    for cell in _cells(dataset, club_id):
        for pattern in CURVED_PATTERNS:
            interval = cell["paired_benefit_vs_straight"][pattern]
            band = cell["assumption_band"][pattern]
            rows.append(
                (
                    cell["key"],
                    pattern,
                    count(cell["paired_n"]),
                    sg(interval["estimate"]),
                    sg_interval(interval["lower_95"], interval["upper_95"]),
                    DIRECTION_LABELS[direction(interval)],
                    sg_interval(band["band_lower_95"], band["band_upper_95"]),
                    DIRECTION_LABELS[band["direction"]],
                )
            )
    return longtable(
        f"{CLUB_LABELS[club_id]} Relative Strokes Gained per 100 Shots",
        "llrrlllc",
        (
            "Key",
            "Pattern",
            "$n_3$",
            "Estimate",
            "Sampling 95\\%",
            "Direction",
            "With Head Band",
            "Direction",
        ),
        rows,
    )


VARIANT_LABELS: Final = {
    "cg_depth_x0.8": r"CG depth $\times0.8$",
    "cg_depth_x1.2": r"CG depth $\times1.2$",
    "inertia_x0.8": r"Inertias $\times0.8$",
    "inertia_x1.2": r"Inertias $\times1.2$",
    "face_radii_x0.8": r"Face radii $\times0.8$",
    "face_radii_x1.2": r"Face radii $\times1.2$",
    "newton_contact_law": "Newton contact law",
}


def _variant_names(dataset: Mapping[str, Any]) -> list[str]:
    names: set[str] = set()
    for cell in _cells(dataset):
        names |= set(cell["variant_status"])
    unknown = names - set(VARIANT_LABELS)
    if unknown:
        raise ValueError(f"no label for head variants {sorted(unknown)}")
    return [name for name in VARIANT_LABELS if name in names]


def variant_table(dataset: Mapping[str, Any]) -> str:
    """Largest change in relative SG and target caused by each head variant."""
    rows = []
    for variant in _variant_names(dataset):
        row = [VARIANT_LABELS[variant]]
        for club_id in CLUB_ORDER:
            cells = [
                c for c in _cells(dataset, club_id) if variant in c["variant_status"]
            ]
            if not cells:
                row += ["---", "---"]
                continue
            shift = max(
                abs(
                    cell["assumption_band"][pattern]["variant_estimates"][variant]
                    - cell["paired_benefit_vs_straight"][pattern]["estimate"]
                )
                for cell in cells
                for pattern in CURVED_PATTERNS
            )
            target = max(
                abs(cell["variant_target_x_m"][variant] - cell["target_x_m"])
                for cell in cells
            )
            row += [f"{SG_SCALE * shift:.3f}", f"{target:.2f}"]
        rows.append(row)
    groups = " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{CLUB_LABELS[club_id]}}}" for club_id in CLUB_ORDER
    )
    rules = "".join(
        f"\\cmidrule(lr){{{2 * i + 2}-{2 * i + 3}}}" for i in range(len(CLUB_ORDER))
    )
    units = " & ".join(["SG / 100", "Target (m)"] * len(CLUB_ORDER))
    return longtable(
        "Largest Effect of Each Head Variant Across the Eight Conditions per Club",
        "lrrrrrr",
        f"& {groups} \\\\ {rules}\nHead Variant & {units}",
        rows,
    )


def contrast_table(dataset: Mapping[str, Any]) -> str:
    rows = []
    for key, item in dataset["contrasts"].items():
        protocols = " $\\to$ ".join(
            PROTOCOL_KEYS[protocol] for protocol in item["source_protocols"]
        )
        for pattern in CURVED_PATTERNS:
            effect = item["effect_modification"][pattern]
            first = pattern == CURVED_PATTERNS[0]
            rows.append(
                (
                    key if first else "",
                    CONTRAST_LABELS[item["comparison_kind"]] if first else "",
                    _contrast_context(item) if first else "",
                    protocols if first else "",
                    count(item["common_six_n"]) if first else "",
                    pattern,
                    sg(effect["estimate"]),
                    sg_interval(effect["lower_95"], effect["upper_95"]),
                    DIRECTION_LABELS[direction(effect)],
                )
            )
    return longtable(
        "Change in Relative Strokes Gained per 100 Shots Between Paired Conditions",
        f"l{_WRAP}{{1.9cm}}{_WRAP}{{3.1cm}}lrlrll",
        (
            "Key",
            "Change",
            "Held Fixed",
            "Sources",
            "$n_6$",
            "Pattern",
            "Estimate",
            "Sampling 95\\%",
            "Direction",
        ),
        rows,
        size="footnotesize",
    )


_WRAP: Final = r">{\raggedright\arraybackslash}p"
"""Column prefix for wrapped, ragged-right text of a given width."""


def _contrast_context(item: Mapping[str, Any]) -> str:
    """The held-fixed part of a contrast, e.g. ``Curve 1×, Shaft Only``."""
    club, curve, sd, profile = condition_parts(item["cells"][0])
    kind = item["comparison_kind"]
    if kind == "shaft_rotation_sd":
        return f"{club}, Curve ${curve}\\times$, {profile}"
    if kind == "curve_strength":
        return f"{club}, SD ${sd}^\\circ$, {profile}"
    return f"{club}, Curve ${curve}\\times$, SD ${sd}^\\circ$, {profile}"


def synthesis_counts(dataset: Mapping[str, Any]) -> dict[str, dict[str, Any]]:
    """Per club and pattern: estimate range and direction counts."""
    result: dict[str, dict[str, Any]] = {}
    for club_id in CLUB_ORDER:
        for pattern in CURVED_PATTERNS:
            cells = _cells(dataset, club_id)
            estimates = [
                c["paired_benefit_vs_straight"][pattern]["estimate"] for c in cells
            ]
            sampling = [
                direction(c["paired_benefit_vs_straight"][pattern]) for c in cells
            ]
            band = [c["assumption_band"][pattern]["direction"] for c in cells]
            result[f"{club_id}/{pattern}"] = {
                "minimum": min(estimates),
                "maximum": max(estimates),
                "sampling": [sampling.count(name) for name in DIRECTION_LABELS],
                "band": [band.count(name) for name in DIRECTION_LABELS],
            }
    return result


def synthesis_table(dataset: Mapping[str, Any]) -> str:
    rows = []
    for name, item in synthesis_counts(dataset).items():
        club_id, pattern = name.split("/")
        rows.append(
            (
                CLUB_LABELS[club_id],
                pattern,
                sg(item["minimum"]),
                sg(item["maximum"]),
                "/".join(map(str, item["sampling"])),
                "/".join(map(str, item["band"])),
            )
        )
    return longtable(
        "Relative Strokes Gained per 100 Shots Across the Eight Conditions per Club",
        "llrrcc",
        (
            "Club",
            "Pattern",
            "Minimum",
            "Maximum",
            "Sampling +/$-$/0",
            "With Head Band +/$-$/0",
        ),
        rows,
    )


def _macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def values_file(dataset: Mapping[str, Any]) -> str:
    """Scalar macros the prose cites, so the text cannot drift from the data."""
    cells = _cells(dataset)
    repro = [cell["nominal_reproduction"] for cell in cells]
    variants = sum(len(cell["variant_status"]) for cell in cells)
    flips = sum(
        direction(cell["paired_benefit_vs_straight"][p])
        != cell["assumption_band"][p]["direction"]
        for cell in cells
        for p in CURVED_PATTERNS
    )
    unavailable = sum(
        status == "unavailable"
        for cell in cells
        for status in cell["variant_status"].values()
    )
    text = HEADER + _macro("BootstrapResamples", count(dataset["bootstrap_resamples"]))
    text += _macro("BandVariantRuns", count(variants))
    text += _macro("BandUnavailableRuns", count(unavailable))
    text += _macro("BandShots", count(variants * 3 * 10_000))
    text += _macro("BandDirectionChanges", str(flips))
    text += _macro("ReproCells", str(len(repro)))
    text += _macro("ReproShots", count(sum(r["shots_compared"] for r in repro)))
    text += _macro(
        "ReproStatusMismatches", str(sum(r["status_mismatches"] for r in repro))
    )
    text += _macro(
        "ReproMaxEndpointDifference",
        f"{max(r['max_abs_endpoint_difference_m'] for r in repro):.1g}",
    )
    for name, item in synthesis_counts(dataset).items():
        club_id, pattern = name.split("/")
        stem = "".join(part.title() for part in club_id.split("_")) + pattern
        text += _macro(f"{stem}Min", sg(item["minimum"]))
        text += _macro(f"{stem}Max", sg(item["maximum"]))
    return text


def render_all(dataset: Mapping[str, Any]) -> dict[str, str]:
    """Return ``{file name: LaTeX}`` for every generated article table."""
    tables = {
        "values.tex": values_file(dataset),
        "conditions.tex": conditions_table(dataset),
        "synthesis.tex": synthesis_table(dataset),
        "head_variants.tex": variant_table(dataset),
        "contrasts.tex": contrast_table(dataset),
    }
    for club_id in CLUB_ORDER:
        tables[f"geometry_{club_id}.tex"] = geometry_table(dataset, club_id)
        tables[f"paired_{club_id}.tex"] = paired_table(dataset, club_id)
    return tables


def stale_tables(dataset: Mapping[str, Any], output_dir: Path) -> list[str]:
    """Names whose committed text differs from a fresh render (or is missing)."""
    output_dir = Path(output_dir)
    return sorted(
        name
        for name, text in render_all(dataset).items()
        if not (output_dir / name).is_file()
        or (output_dir / name).read_text(encoding="utf-8") != text
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path)
    parser.add_argument("output_dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    dataset = json.loads(args.dataset.read_text(encoding="utf-8"))
    if args.check:
        stale = stale_tables(dataset, args.output_dir)
        if stale:
            sys.stderr.write(f"stale generated tables: {', '.join(stale)}\n")
            return 1
        return 0
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, text in render_all(dataset).items():
        (args.output_dir / name).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
