"""Simscape (MATLAB R2025b) Closed-Loop Snapshot Loader & Adapter (#12583 / NSX-55).

Loads and validates Simscape Multibody closed-loop snapshot exports generated by
``scripts/matlab/export_simscape_closed_loop_snapshot.m`` under MATLAB ``R2025b``
only (never ``R2026a``). On hosts without a live MATLAB R2025b runtime or a
pre-exported snapshot artifact, ``SimscapeClosedLoopSnapshotAdapter`` reports
``CapabilityLevel.NONE`` and cites ``DV-12583``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from src.shared.python.contracts import ensure, require
from src.shared.python.engine_core.capabilities import CapabilityLevel
from src.shared.python.loop_nullspace.engine_adapters import (
    SIMSCAPE_CLOSURE_CONVENTION,
    CapabilityUnavailableError,
    ClosedLoopSnapshot,
    _BaseSnapshotAdapter,
    _build_snapshot_instance,
    to_canonical_closure,
)

Array = NDArray[np.float64]

REQUIRED_MATLAB_RELEASE = "R2025b"
DEFERRED_VALIDATION_ID = "DV-12583"
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")

REPO_ROOT = Path(__file__).resolve().parents[4]
MATLAB_EXPORT_SCRIPT_PATH = (
    REPO_ROOT / "scripts" / "matlab" / "export_simscape_closed_loop_snapshot.m"
)


def _validate_simscape_payload(payload: dict) -> None:
    """Validate Simscape R2025b snapshot schema, release gate, and SHA-256 checksum."""
    release = str(payload.get("matlab_release", ""))
    if release != REQUIRED_MATLAB_RELEASE:
        raise ValueError(
            f"Simscape closed-loop snapshot requires MATLAB {REQUIRED_MATLAB_RELEASE} "
            f"(never R2026a); got matlab_release={release!r}"
        )
    model_sha256 = str(payload.get("model_sha256", ""))
    if not _SHA256_RE.match(model_sha256):
        raise ValueError(
            f"Invalid or missing 64-hex model_sha256 in Simscape snapshot: {model_sha256!r}"
        )
    for section in ("topology", "state", "dynamics"):
        if not isinstance(payload.get(section), dict):
            raise ValueError(f"Simscape snapshot missing required '{section}' object")


def load_simscape_closed_loop_snapshot(
    snapshot_path: Path | str,
) -> ClosedLoopSnapshot:
    """Load and validate a Simscape R2025b ``ClosedLoopSnapshot`` from JSON."""
    require(snapshot_path is not None, "snapshot_path must not be None")
    path = Path(snapshot_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("Simscape snapshot JSON root must be an object")
    _validate_simscape_payload(payload)

    topo = payload["topology"]
    state = payload["state"]
    dyn = payload["dynamics"]
    closure_meta = topo.get("closure", {})

    q = np.asarray(state["q"], dtype=np.float64)
    v = np.asarray(state["v"], dtype=np.float64)
    a = np.asarray(state["a"], dtype=np.float64)
    mass = np.asarray(dyn["M"], dtype=np.float64)
    bias = np.asarray(dyn["h"], dtype=np.float64)
    j_raw = np.asarray(dyn["J_c"], dtype=np.float64)
    jdot_raw = np.asarray(dyn["Jdot_v"], dtype=np.float64)
    s_raw = dyn.get("S")
    s_mat = None if s_raw is None else np.asarray(s_raw, dtype=np.float64)
    j_g_raw = dyn.get("J_g")
    j_g = None if j_g_raw is None else np.asarray(j_g_raw, dtype=np.float64)

    grip_origin = np.asarray(
        closure_meta.get("grip_origin_in_club_m", [0.0, 0.0, 0.0]), dtype=np.float64
    )
    j_c, jdot_v = to_canonical_closure(
        j_raw,
        jdot_raw,
        native=SIMSCAPE_CLOSURE_CONVENTION,
        grip_frame_rotation=np.eye(3, dtype=np.float64),
        grip_origin=grip_origin,
        reference_point=grip_origin,
    )

    result = _build_snapshot_instance(
        q,
        v,
        a,
        {
            "coordinate_order": tuple(topo["coordinate_order"]),
            "actuated_indices": tuple(topo["actuated_indices"]),
            "contact_names": tuple(topo.get("contact_names", ())),
            "model_sha256": str(payload["model_sha256"]),
            "inertial_source": str(
                payload.get("inertial_source", "simscape_multibody_r2025b")
            ),
            "bare_club_bench_id": payload.get("bare_club_bench_id"),
            "engine_name": "simscape",
            "M": mass,
            "h": bias,
            "J_c": j_c,
            "Jdot_v": jdot_v,
            "S": s_mat,
            "J_g": j_g,
            "drift_method": str(payload.get("drift_method", "analytic")),
            "kkt_regularization": 0.0,
            "matlab_release": REQUIRED_MATLAB_RELEASE,
        },
    )
    ensure(
        result.model_provenance.matlab_release == REQUIRED_MATLAB_RELEASE,
        "Loaded Simscape snapshot must record matlab_release == 'R2025b'",
    )
    return result


class SimscapeClosedLoopSnapshotAdapter(_BaseSnapshotAdapter):
    """Simscape R2025b Closed-Loop Snapshot Adapter (#12583 / NSX-55).

    When initialized without a checked-in R2025b export path, reports
    ``CapabilityLevel.NONE`` and cites ``DV-12583`` so callers fail closed
    rather than substituting a mock engine.
    """

    engine_name = "simscape"
    native_convention = SIMSCAPE_CLOSURE_CONVENTION
    deferred_validation_id = DEFERRED_VALIDATION_ID

    def __init__(self, snapshot_path: Path | str | None = None) -> None:
        super().__init__()
        self._snapshot: ClosedLoopSnapshot | None = None
        if snapshot_path is not None:
            snap = load_simscape_closed_loop_snapshot(snapshot_path)
            self._snapshot = snap
            self.coordinate_order = snap.topology.coordinate_order
            self.nv = len(self.coordinate_order)
            self.model_sha256 = snap.model_provenance.spec_sha256
            self._static_quantities = {
                "coordinate_order": self.coordinate_order,
                "actuated_indices": snap.topology.actuated_indices,
                "contact_names": snap.topology.contact_names,
                "model_sha256": self.model_sha256,
                "inertial_source": snap.model_provenance.inertial_source,
                "bare_club_bench_id": snap.model_provenance.bare_club_bench_id,
                "engine_name": self.engine_name,
                "M": snap.M,
                "h": snap.h,
                "J_c": snap.J_c,
                "Jdot_v": snap.Jdot_v,
                "S": snap.S,
                "J_g": snap.J_g,
                "q_manifold": snap.q,
                "drift_method": "analytic",
                "kkt_regularization": 0.0,
                "matlab_release": REQUIRED_MATLAB_RELEASE,
            }

    def capability_level(
        self, capability: str = "closed_loop_snapshot"
    ) -> CapabilityLevel:
        """Return FULL when backed by a verified R2025b export, otherwise NONE."""
        if capability == "closed_loop_snapshot":
            if self._snapshot is not None:
                return CapabilityLevel.FULL
            return CapabilityLevel.NONE
        return CapabilityLevel.NONE

    def build_snapshot(
        self, q: Array, v: Array, a: Array | None = None
    ) -> ClosedLoopSnapshot:
        if self._snapshot is None:
            raise CapabilityUnavailableError(
                f"Live MATLAB {REQUIRED_MATLAB_RELEASE} Simscape Multibody runtime is not "
                f"available in CI; tracked under deferred validation {DEFERRED_VALIDATION_ID}"
            )
        return super().build_snapshot(q, v, a)


