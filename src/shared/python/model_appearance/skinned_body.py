_COMPONENT_FLOAT, _COMPONENT_USHORT, _COMPONENT_UINT = 5126, 5123, 5125
_TARGET_ARRAY_BUFFER, _TARGET_ELEMENT_ARRAY_BUFFER = 34962, 34963


def _transform(value: Any, name: str) -> Array:
    m = np.asarray(value, dtype=float)
    if m.shape != (4, 4) or not np.isfinite(m).all():
        raise ValueError(f"{name} must be a finite 4x4 transform")
    return m


def _primitive_transform(primitive: str, value: float) -> Array:
    if primitive not in _PRIMITIVES:
        raise ValueError(
            f"Unsupported primitive {primitive!r}; use {sorted(_PRIMITIVES)}"
        )
    m = np.eye(4)
    if primitive == "Px":
        m[0, 3] = value
    elif primitive == "Py":
        m[1, 3] = value
    elif primitive == "Pz":
        m[2, 3] = value
    else:
        c, s = math.cos(value), math.sin(value)
        if primitive == "Rx":
            m[1, 1], m[1, 2], m[2, 1], m[2, 2] = c, -s, s, c
        elif primitive == "Ry":
            m[0, 0], m[0, 2], m[2, 0], m[2, 2] = c, s, -s, c
        else:  # Rz
            m[0, 0], m[0, 1], m[1, 0], m[1, 1] = c, -s, s, c
    return m


def spec_body_poses(
    spec: Mapping[str, Any], q: Mapping[str, float] | None = None
) -> dict[str, Array]:
    """World 4x4 pose of every spec body (including ``"world"``) at coordinates ``q``.

    Missing coordinates default to zero. Preconditions: every name in ``q``
    is a coordinate declared by the spec and every value is finite.
    """
    given = dict(q) if q is not None else {}
    declared = set(spec["coordinate_order"])
    unknown = set(given) - declared
    if unknown:
        raise ValueError(f"Unknown coordinate name(s): {sorted(unknown)}")
    for name, value in given.items():
        if not math.isfinite(value):
            raise ValueError(f"Coordinate {name!r} must be finite")

    poses: dict[str, Array] = {"world": np.eye(4)}
    pending = list(spec["joints"])
    while pending:
        progressed = False
        for joint in list(pending):
            if joint["parent"] not in poses:
                continue
            base = poses[joint["parent"]] @ _transform(
                joint["parent_to_base"], "parent_to_base"
            )
            for primitive in joint["primitives"]:
                value = given.get(primitive["coordinate"], 0.0)
                base = base @ _primitive_transform(primitive["primitive"], value)
            poses[joint["child"]] = base @ np.linalg.inv(
                _transform(joint["child_to_follower"], "child_to_follower")
            )
            pending.remove(joint)
            progressed = True
        if not progressed:
            raise ValueError("Joint tree is not rooted at world")
    return poses


@dataclass(frozen=True)
class SkinnedBody:
    """A rigidly skinned procedural mesh over a spec skeleton (CMB-6, #11657).

    Every vertex is weighted 1.0 to the single bone whose capsule produced
    it (rigid skinning); smooth blending across a joint is a follow-up.
    """

    bone_names: tuple[str, ...]
    bone_parents: tuple[int, ...]
    rest_poses: Array  # (B, 4, 4) world pose at zero q
    vertices: Array  # (N, 3) world rest-pose positions
    faces: NDArray[np.int64]  # (M, 3)
    joints: NDArray[np.uint16]  # (N, 4)
    weights: NDArray[np.float32]  # (N, 4)
    spec_sha256: str | None = None
    up_axis: tuple[float, float, float] = (0.0, 0.0, 1.0)  # spec frame, -gravity

    @property
    def vertex_bone(self) -> NDArray[np.uint16]:
        """Owning bone index of every vertex (column 0 of ``joints``)."""
        return self.joints[:, 0]


def _spec_up_axis(spec: Mapping[str, Any]) -> tuple[float, float, float]:
    """Unit up axis of the spec frame: the negated, normalised gravity vector.

    Raises ``ValueError`` unless ``gravity_m_s2`` is a finite, nonzero 3-vector.
    """
    gravity = np.asarray(spec["gravity_m_s2"], dtype=float)
    if gravity.shape != (3,) or not np.isfinite(gravity).all():
        raise ValueError("gravity_m_s2 must be a finite 3-vector")
    if np.linalg.norm(gravity) <= 0:
        raise ValueError("Gravity must be nonzero to define the up axis")
    up = -gravity / np.linalg.norm(gravity)
    return (float(up[0]), float(up[1]), float(up[2]))


def build_skinned_body(
    spec: Mapping[str, Any],
    *,
    spec_sha256: str | None = None,
    rings: int = 10,
    sides: int = 12,
) -> SkinnedBody:
    """Loft a capsule mesh per visual-skeleton segment and rigidly skin it.

    Postconditions: every bone name is a spec body and every non-world spec
    body has exactly one bone (parent-first order); every ``joints`` entry
    indexes a valid bone; every ``weights`` row sums to 1.
    """
    ordered_joints = order_directed_tree(spec["joints"])
    body_names = {b["name"] for b in spec["bodies"] if b["name"] != "world"}
    bone_names = tuple(joint["child"] for joint in ordered_joints)
    if set(bone_names) != body_names or len(bone_names) != len(body_names):
        raise ValueError(
            "Spec bodies and the joint tree's children must be a bijection"
        )
    index_of = {name: i for i, name in enumerate(bone_names)}
    bone_parents = tuple(
        -1 if joint["parent"] == "world" else index_of[joint["parent"]]
        for joint in ordered_joints
    )

    rest_poses_map = spec_body_poses(spec)
    rest_poses = np.stack([rest_poses_map[name] for name in bone_names])

    skeleton = derive_visual_skeleton(spec)
    capsules_by_body: dict[str, list[Any]] = {}
    for capsule in skeleton.capsules:
        if capsule.length_m() <= 1e-9:
            continue
        capsules_by_body.setdefault(capsule.body, []).append(capsule)

    # Deferred: cross_section uses this module's spec_body_poses (import cycle).
    from src.shared.python.model_appearance.cross_section import (
        body_sections,
        width_hint_for,
    )

    sections = body_sections(spec)
    vertex_chunks: list[Array] = []
    face_chunks: list[NDArray[np.int64]] = []
    joint_chunks: list[NDArray[np.uint16]] = []
    offset = 0
    for bone_idx, name in enumerate(bone_names):
        pose = rest_poses_map[name]
        part = classify_body(name)
        for capsule in capsules_by_body.get(name, []):
            radius = PART_RADIUS_M.get(part, capsule.radius_m)
            aspect = PART_ASPECT.get(part, 1.0)
            mesh = lofted_segment(
                np.asarray(capsule.start_m, dtype=float),
                np.asarray(capsule.end_m, dtype=float),
                radius,
                LoftOptions(
                    aspect=aspect,
                    rings=rings,
                    sides=sides,
                    width_hint=width_hint_for(
                        sections, name, capsule.start_m, capsule.end_m
                    ),
                ),
            )
            world_vertices = mesh.vertices @ pose[:3, :3].T + pose[:3, 3]
            vertex_chunks.append(world_vertices)
            face_chunks.append(mesh.faces + offset)
            joint_chunks.append(
                np.full(world_vertices.shape[0], bone_idx, dtype=np.uint16)
            )
            offset += world_vertices.shape[0]
    if not vertex_chunks:
        raise ValueError("No capsules were derived from the spec skeleton")

    vertices = np.concatenate(vertex_chunks, axis=0)
    faces = np.concatenate(face_chunks, axis=0).astype(np.int64)
    n_vertices = vertices.shape[0]
    joints = np.zeros((n_vertices, 4), dtype=np.uint16)
    joints[:, 0] = np.concatenate(joint_chunks, axis=0)
    weights = np.zeros((n_vertices, 4), dtype=np.float32)
    weights[:, 0] = 1.0
    up_axis = _spec_up_axis(spec)

    return SkinnedBody(
        bone_names=bone_names,
        bone_parents=bone_parents,
        rest_poses=rest_poses,
        vertices=vertices,
        faces=faces,
        joints=joints,
        weights=weights,
        spec_sha256=spec_sha256,
        up_axis=up_axis,
    )


def pose_skinned_vertices(body: SkinnedBody, body_poses: Mapping[str, Array]) -> Array:
    """Linear-blend-skin ``body``'s rest vertices through posed bone transforms.

    ``v' = sum_k w_k * P[j_k] @ inv(Rest[j_k]) @ v`` over the (up to four)
    joint influences of every vertex. Precondition: ``body_poses`` carries a
    pose for every bone name.
    """
    missing = set(body.bone_names) - set(body_poses)
    if missing:
        raise ValueError(f"Missing posed transform for bones: {sorted(missing)}")
    posed_bones = np.stack(
        [_transform(body_poses[name], f"pose of {name}") for name in body.bone_names]
    )
    rest_inv = np.linalg.inv(body.rest_poses)
    n_vertices = body.vertices.shape[0]
    homogeneous = np.concatenate([body.vertices, np.ones((n_vertices, 1))], axis=1)
    result = np.zeros((n_vertices, 3))
    for k in range(body.joints.shape[1]):
        weight = body.weights[:, k]
        if not np.any(weight):
            continue
        bone_idx = body.joints[:, k]
        delta = posed_bones[bone_idx] @ rest_inv[bone_idx]
        transformed = np.einsum("nij,nj->ni", delta, homogeneous)[:, :3]
        result += weight[:, None] * transformed
    return result


def _vertex_normals(vertices: Array, faces: NDArray[np.int64]) -> Array:
    """Area-weighted, unit-normalised vertex normals."""
    normals = np.zeros_like(vertices)
    tri = vertices[faces]
    face_normals = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    for i in range(3):
        np.add.at(normals, faces[:, i], face_normals)
    lengths = np.linalg.norm(normals, axis=1, keepdims=True)
    lengths[lengths < 1e-12] = 1.0
    return normals / lengths


def gltf_up_rotation(up_axis: Any) -> Array:
    """Proper rotation (4x4) taking the spec ``up_axis`` onto glTF's +Y.

    glTF 2.0 is Y-up; the spec is typically Z-up. Applying this to the world
    side of every rest pose keeps each bone's local frame the spec body frame.
    """
    up = np.asarray(up_axis, dtype=float)
    if up.shape != (3,) or not np.isfinite(up).all() or np.linalg.norm(up) <= 0:
        raise ValueError("up_axis must be a finite nonzero 3-vector")
    a, b = up / np.linalg.norm(up), np.array([0.0, 1.0, 0.0])
    cross, dot = np.cross(a, b), float(np.dot(a, b))
    m = np.eye(4)
    if dot < -1.0 + 1e-12:  # antiparallel: half turn about x
        m[:3, :3] = np.diag([1.0, -1.0, -1.0])
        return m
    k = np.array(
        [
            [0.0, -cross[2], cross[1]],
            [cross[2], 0.0, -cross[0]],
            [-cross[1], cross[0], 0.0],
        ]
    )
    m[:3, :3] = np.eye(3) + k + k @ k / (1.0 + dot)
    return m


def _pack_accessors(
    arrays: list[tuple[np.ndarray, int, str, int | None]],
) -> tuple[bytes, list[dict[str, Any]], list[dict[str, Any]]]:
    """Pack ``(data, componentType, type, target)`` into one 4-byte-aligned buffer.

    Returns the buffer bytes, one bufferView per array and one accessor per
    array (accessor ``i`` reads bufferView ``i``).
    """
    counts = {"SCALAR": 1, "VEC3": 3, "VEC4": 4, "MAT4": 16}
    buffer = bytearray()
    views: list[dict[str, Any]] = []
    accessors: list[dict[str, Any]] = []
    for data, component, kind, target in arrays:
        buffer.extend(b"\x00" * (-len(buffer) % 4))
        raw = np.ascontiguousarray(data).tobytes()
        view: dict[str, Any] = {
            "buffer": 0,
            "byteOffset": len(buffer),
            "byteLength": len(raw),
        }
        if target is not None:
            view["target"] = target
        buffer.extend(raw)
        accessors.append(
            {
                "bufferView": len(views),
                "componentType": component,
                "count": int(data.size // counts[kind]),
                "type": kind,
            }
        )
        views.append(view)
    return bytes(buffer), views, accessors


def quaternion_xyzw(rotation: Any) -> Array:
    """Unit quaternion ``(x, y, z, w)`` of a 3x3 rotation matrix, with ``w >= 0``.

    Precondition: ``rotation`` is a finite proper rotation (orthonormal,
    determinant +1, to 1e-6).
    """
    r = np.asarray(rotation, dtype=float)
    if r.shape != (3, 3) or not np.isfinite(r).all():
        raise ValueError("rotation must be a finite 3x3 matrix")
    if not np.allclose(r @ r.T, np.eye(3), atol=1e-6) or np.linalg.det(r) <= 0:
        raise ValueError("rotation must be a proper orthonormal matrix")
    # Shepperd: pivot on the largest of (w, x, y, z) for numerical stability.
    diag = (np.trace(r), r[0, 0], r[1, 1], r[2, 2])
    pivot = int(np.argmax(diag))
    if pivot == 0:
        s = 2.0 * math.sqrt(1.0 + diag[0])
        q = [(r[2, 1] - r[1, 2]) / s, (r[0, 2] - r[2, 0]) / s, (r[1, 0] - r[0, 1]) / s]
        q.append(0.25 * s)
    else:
        i = pivot - 1
        j, k = (i + 1) % 3, (i + 2) % 3
        s = 2.0 * math.sqrt(1.0 + r[i, i] - r[j, j] - r[k, k])
        q = [0.0, 0.0, 0.0, (r[k, j] - r[j, k]) / s]
        q[i] = 0.25 * s
        q[j] = (r[j, i] + r[i, j]) / s
        q[k] = (r[k, i] + r[i, k]) / s
    quat = np.asarray(q) / np.linalg.norm(q)
    return -quat if quat[3] < 0 else quat


def _local_poses(parents: tuple[int, ...], global_poses: Array) -> Array:
    """Parent-relative bone transforms ``(..., B, 4, 4)`` from world ones."""
    local = np.empty_like(global_poses)
    for i, parent in enumerate(parents):
        if parent == -1:
            local[..., i, :, :] = global_poses[..., i, :, :]
        else:
            local[..., i, :, :] = (
                np.linalg.inv(global_poses[..., parent, :, :])
                @ global_poses[..., i, :, :]
            )
    return local


def _bone_nodes(
    names: tuple[str, ...], parents: tuple[int, ...], rest_poses: Array
) -> list[dict[str, Any]]:
    """One glTF node per bone with its local (parent-relative) rest TRS.

    Nodes carry ``translation``/``rotation`` rather than ``matrix`` because
    glTF animations can only target TRS nodes.
    """
    local = _local_poses(parents, rest_poses)
    nodes: list[dict[str, Any]] = []
    for i, name in enumerate(names):
        node: dict[str, Any] = {
            "name": name,
            "translation": local[i, :3, 3].tolist(),
            "rotation": quaternion_xyzw(local[i, :3, :3]).tolist(),
        }
        children = [j for j, p in enumerate(parents) if p == i]
        if children:
            node["children"] = children
        nodes.append(node)
    return nodes


def spec_motion_bone_poses(
    body: SkinnedBody,
    spec: Mapping[str, Any],
    frames: Sequence[Mapping[str, float]],
) -> Array:
    """World pose ``(F, B, 4, 4)`` of every bone at each spec-coordinate frame.

    Precondition: at least one frame; each frame obeys ``spec_body_poses``.
    """
    if not frames:
        raise ValueError("frames must contain at least one coordinate frame")
    return np.stack(
        [
            np.stack([poses[name] for name in body.bone_names])
            for poses in (spec_body_poses(spec, q) for q in frames)
        ]
    )


def _motion_arrays(
    parents: tuple[int, ...], motion_y_up: Array, fps: float
) -> tuple[Array, Array, Array]:
    """Key times ``(F,)``, local translations ``(F, B, 3)`` and rotations ``(F, B, 4)``.

    Consecutive quaternions are kept in one hemisphere so a viewer's slerp
    takes the short way between keys.
    """
    local = _local_poses(parents, motion_y_up)
    n_frames, n_bones = local.shape[:2]
    rotations = np.empty((n_frames, n_bones, 4))
    for f in range(n_frames):
        for b in range(n_bones):
            quat = quaternion_xyzw(local[f, b, :3, :3])
            if f and float(np.dot(quat, rotations[f - 1, b])) < 0:
                quat = -quat
            rotations[f, b] = quat
    times = np.arange(n_frames, dtype=float) / fps
    return times, local[:, :, :3, 3], rotations


def _mesh_skin_accessor_data(
    body: SkinnedBody, to_y_up: Array, rest_poses_y_up: Array
) -> list[tuple[np.ndarray, int, str, int | None]]:
    """``_pack_accessors`` entries 0-5: position, normal, joints, weights,
    indices and inverse bind matrices, all in the Y-up glTF frame."""
    world_vertices = body.vertices @ to_y_up[:3, :3].T
    # glTF mat4 accessor data is column-major per matrix.
    inverse_bind = np.transpose(np.linalg.inv(rest_poses_y_up), (0, 2, 1))
    return [
        (
            world_vertices.astype(np.float32),
            _COMPONENT_FLOAT,
            "VEC3",
            _TARGET_ARRAY_BUFFER,
        ),
        (
            _vertex_normals(world_vertices, body.faces).astype(np.float32),
            _COMPONENT_FLOAT,
            "VEC3",
            _TARGET_ARRAY_BUFFER,
        ),
        (
            body.joints.astype(np.uint16),
            _COMPONENT_USHORT,
            "VEC4",
            _TARGET_ARRAY_BUFFER,
        ),
        (
            body.weights.astype(np.float32),
            _COMPONENT_FLOAT,
            "VEC4",
            _TARGET_ARRAY_BUFFER,
        ),
        (
            body.faces.astype(np.uint32).reshape(-1),
            _COMPONENT_UINT,
            "SCALAR",
            _TARGET_ELEMENT_ARRAY_BUFFER,
        ),
        (inverse_bind.astype(np.float32), _COMPONENT_FLOAT, "MAT4", None),
    ]


def _motion_accessor_data(
    body: SkinnedBody, motion: Any, to_y_up: Array, fps: float
) -> list[tuple[np.ndarray, int, str, int | None]]:
    """Validated ``_pack_accessors`` entries: key times, then per bone T and R."""
    n_bones = len(body.bone_names)
    poses = np.asarray(motion, dtype=float)
    if (
        poses.ndim != 4
        or poses.shape[0] < 1
        or poses.shape[1:] != (n_bones, 4, 4)
        or not np.isfinite(poses).all()
    ):
        raise ValueError(f"motion must be a finite (F, {n_bones}, 4, 4) array")
    if not (math.isfinite(fps) and fps > 0):
        raise ValueError("fps must be finite and positive")
    times, translations, rotations = _motion_arrays(
        body.bone_parents, to_y_up @ poses, fps
    )
    entries: list[tuple[np.ndarray, int, str, int | None]] = [
        (times.astype(np.float32), _COMPONENT_FLOAT, "SCALAR", None)
    ]
    for bone in range(n_bones):
        entries.append(
            (translations[:, bone].astype(np.float32), _COMPONENT_FLOAT, "VEC3", None)
        )
        entries.append(
            (rotations[:, bone].astype(np.float32), _COMPONENT_FLOAT, "VEC4", None)
        )
    return entries


def _animation(n_bones: int, first_accessor: int, name: str) -> dict[str, Any]:
    """One glTF animation: per bone a translation and a rotation channel.

    Accessor ``first_accessor`` holds the key times, followed by translation
    then rotation outputs for bone 0, bone 1, ...
    """
    samplers: list[dict[str, Any]] = []
    channels: list[dict[str, Any]] = []
    for bone in range(n_bones):
        for offset, path in enumerate(("translation", "rotation")):
            channels.append(
                {"sampler": len(samplers), "target": {"node": bone, "path": path}}
            )
            samplers.append(
                {
                    "input": first_accessor,
                    "output": first_accessor + 1 + 2 * bone + offset,
                    "interpolation": "LINEAR",
                }
            )
    return {"name": name, "samplers": samplers, "channels": channels}


def skinned_body_gltf(
    body: SkinnedBody,
    motion: Any = None,
    *,
    fps: float = 60.0,
    animation_name: str = "spec_motion",
) -> dict[str, Any]:
    """A glTF 2.0 JSON document with one embedded base64 buffer.

    ``motion`` is an optional ``(F, B, 4, 4)`` array of world bone poses in
    the spec frame (see ``spec_motion_bone_poses``), sampled at ``fps``; when
    given, the document carries one LINEAR animation with a translation and
    a rotation channel per bone.

    Postconditions: the scene is Y-up (spec up mapped to +Y by
    ``gltf_up_rotation``); each bone node's local TRS is the spec joint
    offset, so driving bones with ``spec_body_poses`` reproduces the skin,
    and evaluating the animation at key ``f`` reproduces ``motion[f]``.
    """
    n_bones = len(body.bone_names)
    to_y_up = gltf_up_rotation(body.up_axis)
    rest_poses = to_y_up @ body.rest_poses
    motion_arrays = (
        [] if motion is None else _motion_accessor_data(body, motion, to_y_up, fps)
    )
    static_arrays = _mesh_skin_accessor_data(body, to_y_up, rest_poses)
    buffer, views, accessors = _pack_accessors(static_arrays + motion_arrays)
    # glTF requires POSITION and animation-input bounds.
    positions = static_arrays[0][0]
    accessors[0]["min"] = positions.min(axis=0).tolist()
    accessors[0]["max"] = positions.max(axis=0).tolist()
    animations: list[dict[str, Any]] = []
    if motion_arrays:
        accessors[6]["min"] = [float(motion_arrays[0][0].min())]
        accessors[6]["max"] = [float(motion_arrays[0][0].max())]
        animations.append(_animation(n_bones, 6, animation_name))
    nodes = _bone_nodes(body.bone_names, body.bone_parents, rest_poses)
    mesh_node = len(nodes)
    nodes.append({"mesh": 0, "skin": 0})
    root_bones = [i for i, p in enumerate(body.bone_parents) if p == -1]

    buffer_uri = "data:application/octet-stream;base64," + base64.b64encode(
        buffer
    ).decode("ascii")
    doc: dict[str, Any] = {
        "asset": {"version": "2.0", "generator": "UpstreamDrift skinned_body"},
        "extras": {
            "spec_sha256": body.spec_sha256,
            "license": _LICENSE_NOTE,
            "up_axis_in_spec": list(body.up_axis),
        },
        "buffers": [{"byteLength": len(buffer), "uri": buffer_uri}],
        "bufferViews": views,
        "accessors": accessors,
        "meshes": [
            {
                "primitives": [
                    {
                        "attributes": {
                            "POSITION": 0,
                            "NORMAL": 1,
                            "JOINTS_0": 2,
                            "WEIGHTS_0": 3,
                        },
                        "indices": 4,
                        "mode": 4,
                    }
                ]
            }
        ],
        "skins": [
            {
                "inverseBindMatrices": 5,
                "joints": list(range(n_bones)),
                "skeleton": root_bones[0] if root_bones else 0,
            }
        ],
        "nodes": nodes,
        "scenes": [{"nodes": root_bones + [mesh_node]}],
        "scene": 0,
    }
    if animations:
        doc["animations"] = animations
    return doc


