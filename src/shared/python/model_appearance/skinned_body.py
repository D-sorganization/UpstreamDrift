"""Procedural skinned mesh over a spec skeleton, exported as glTF 2.0 (CMB-6, #11657).

Builds one rigidly skinned triangle mesh per compiled ``full_body_spec``
document: every bone is a non-world spec body (parent-first, matching the
joint tree), and every vertex is weighted 1.0 to the single bone whose
lofted capsule produced it. Smooth blending of vertices near a joint across
two bones is a follow-up, not implemented in this slice. ``skinned_body_gltf``
packs the mesh, skin and node hierarchy into one glTF 2.0 JSON document with
a single embedded base64 buffer, so every bone maps onto exactly one spec
body and a posed test frame can be checked against the spec's own forward
kinematics for vertex-to-segment attachment error. Given a spec-coordinate
trajectory (``spec_motion_bone_poses``), the same document also carries a
glTF animation, so any glTF viewer (three.js included) drives the skin from
spec ``q`` without an engine.

License: the mesh geometry here is generated procedurally by
``build_skinned_body`` from the spec document alone (a loft of a capsule per
visual-skeleton segment, see ``motion_matching.visual_skeleton``). It
contains no third-party mesh or texture assets. MakeHuman (CC0) and SMPL-X
character assets are not used in this slice; SMPL-X's licence restricts
commercial use, so adopting it would need owner approval first.
"""

