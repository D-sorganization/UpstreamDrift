"""Simulation Data Store for High-Frequency Golf Swing Data.

This module provides the core interfaces for storing, querying, and managing
high-frequency kinematic and kinetic data generated by the physical models
(e.g., Pinocchio/Drake) and motion capture systems. It acts as the backbone
for training Physics-Informed Neural Networks (PINNs).

Disk persistence uses HDF5 (via ``h5py``) when a ``storage_path`` is provided.
Each :class:`SwingDataSequence` becomes an HDF5 group under ``/sequences/<id>``
with one chunked dataset per array field and string metadata stored as group
attributes.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field

import h5py
import numpy as np


@dataclass
class SwingDataSequence:
    """Represents a single time-series sequence of a golf swing."""

    sequence_id: str
    timestamps: np.ndarray  # Shape: (N,)
    joint_angles: np.ndarray  # Shape: (N, num_joints)
    joint_velocities: np.ndarray  # Shape: (N, num_joints)
    club_pose: np.ndarray  # Shape: (N, 7) - quaternion + translation
    applied_torques: np.ndarray  # Shape: (N, num_joints)
    metadata: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        """Validate dimensions upon initialization.

        Postcondition: every per-step array shares the same leading length as
        ``timestamps``.
        """
        n_steps = len(self.timestamps)
        if len(self.joint_angles) != n_steps:
            raise ValueError(
                f"joint_angles length {len(self.joint_angles)} != timestamps length {n_steps}"
            )
        if len(self.joint_velocities) != n_steps:
            raise ValueError(
                f"joint_velocities length {len(self.joint_velocities)} != timestamps length {n_steps}"
            )
        if len(self.club_pose) != n_steps:
            raise ValueError(
                f"club_pose length {len(self.club_pose)} != timestamps length {n_steps}"
            )
        if len(self.applied_torques) != n_steps:
            raise ValueError(
                f"applied_torques length {len(self.applied_torques)} != timestamps length {n_steps}"
            )


# HDF5 layout constants — bumping ``_FORMAT_VERSION`` forces older readers to
# fail loudly rather than silently misinterpreting the layout.
_FORMAT_VERSION = 1
_SEQUENCES_GROUP = "sequences"
_ARRAY_FIELDS: tuple[str, ...] = (
    "timestamps",
    "joint_angles",
    "joint_velocities",
    "club_pose",
    "applied_torques",
)


class SimulationDataStore:
    """In-memory store for golf simulation sequences with optional HDF5 backing."""

    def __init__(self, storage_path: str | None = None):
        """Initialize the data store.

        Args:
            storage_path: Optional path to an HDF5 file. When provided,
                :meth:`flush_to_disk` serializes all in-memory sequences to that
                file and :meth:`from_disk` reconstructs a store from one. When
                ``None``, the store is purely in-memory and ``flush_to_disk`` is
                a no-op.

        Raises:
            ValueError: If ``storage_path`` is provided but its parent directory
                does not exist (a writable parent is a precondition for flush).
        """
        if storage_path is not None:
            parent = os.path.dirname(os.path.abspath(storage_path))
            if not os.path.isdir(parent):
                raise ValueError(
                    f"storage_path parent directory does not exist: {parent}"
                )
        self.storage_path = storage_path
        self._sequences: dict[str, SwingDataSequence] = {}

    def add_sequence(self, sequence: SwingDataSequence) -> None:
        """Add a new swing sequence to the store.

        Raises:
            KeyError: If ``sequence.sequence_id`` is already present.
        """
        if sequence.sequence_id in self._sequences:
            raise KeyError(f"Sequence {sequence.sequence_id} already exists.")
        self._sequences[sequence.sequence_id] = sequence

    def get_sequence(self, sequence_id: str) -> SwingDataSequence:
        """Retrieve a sequence by its ID.

        Raises:
            KeyError: If ``sequence_id`` is not in the store.
        """
        return self._sequences[sequence_id]

    def list_sequences(self) -> list[str]:
        """Return a list of all sequence IDs."""
        return list(self._sequences.keys())

    # ------------------------------------------------------------------
    # Disk persistence
    # ------------------------------------------------------------------

    def flush_to_disk(self) -> None:
        """Serialize all sequences to ``self.storage_path`` as HDF5.

        Layout::

            /                            (attrs: format_version)
            /sequences/<id>              (attrs: each metadata key)
            /sequences/<id>/timestamps   (chunked dataset)
            /sequences/<id>/joint_angles
            /sequences/<id>/joint_velocities
            /sequences/<id>/club_pose
            /sequences/<id>/applied_torques

        Overwrites any existing file at ``storage_path``. If no
        ``storage_path`` was supplied at construction time, this is a no-op.
        """
        if self.storage_path is None:
            return

        with h5py.File(self.storage_path, "w") as h5:
            h5.attrs["format_version"] = _FORMAT_VERSION
            sequences_group = h5.create_group(_SEQUENCES_GROUP)
            for seq_id, seq in self._sequences.items():
                seq_group = sequences_group.create_group(seq_id)
                for field_name in _ARRAY_FIELDS:
                    seq_group.create_dataset(
                        field_name,
                        data=getattr(seq, field_name),
                        chunks=True,
                    )
                for key, value in seq.metadata.items():
                    seq_group.attrs[key] = value

    @classmethod
    def from_disk(cls, storage_path: str) -> SimulationDataStore:
        """Load a :class:`SimulationDataStore` from an HDF5 file.

        Args:
            storage_path: Path to a file previously written by
                :meth:`flush_to_disk`.

        Raises:
            FileNotFoundError: If ``storage_path`` does not exist.
            ValueError: If the file has an unrecognized ``format_version``.
        """
        if not os.path.isfile(storage_path):
            raise FileNotFoundError(storage_path)

        store = cls(storage_path=storage_path)
        with h5py.File(storage_path, "r") as h5:
            version = int(h5.attrs.get("format_version", 0))
            if version != _FORMAT_VERSION:
                raise ValueError(
                    f"Unsupported store format_version={version}; "
                    f"expected {_FORMAT_VERSION}"
                )
            sequences_group = h5[_SEQUENCES_GROUP]
            for seq_id in sequences_group:
                seq_group = sequences_group[seq_id]
                arrays = {
                    field_name: np.asarray(seq_group[field_name][...])
                    for field_name in _ARRAY_FIELDS
                }
                metadata = {
                    key: (
                        value.decode("utf-8")
                        if isinstance(value, bytes)
                        else str(value)
                    )
                    for key, value in seq_group.attrs.items()
                }
                store._sequences[seq_id] = SwingDataSequence(
                    sequence_id=seq_id,
                    metadata=metadata,
                    **arrays,
                )
        return store
