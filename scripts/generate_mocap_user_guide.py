"""Render docs/motion_capture/user_guide.md from the Capture Rig workflow (#9665).

The step titles, requirements and instructions live in
``src/tools/capture_rig/workflow.py`` so the tile and the guide cannot drift;
``tests/tools/capture_rig/test_user_guide_fresh.py`` fails when this file is
stale. Run: ``python3 -m scripts.generate_mocap_user_guide``.
"""

from __future__ import annotations

import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "docs" / "motion_capture" / "user_guide.md"

PREAMBLE = """<!-- Generated by scripts/generate_mocap_user_guide.py from
src/tools/capture_rig/workflow.py. Do not edit by hand. -->

# Markerless Motion Capture User Guide

This guide is rendered from the same step model the **Capture Rig** launcher
tile shows, so what you read here is what the tool asks for. Open the tile
(`python3 -m src.tools.capture_rig`), load or record a session, and the
*Workflow* panel marks each step below as done, ready, blocked (with the
reason) or skipped for this kind of session.

## One Interface, One or Many Cameras

- **Multi-camera** (two or more views): every step applies. The result is a
  3-D reconstruction with learned camera placement, bone lengths, outlier
  rejection, a swing summary, and a TRC export for the motion pipeline and
  model matching.
- **Single camera** (one view, recorded or imported): calibration,
  reconstruction and export are skipped; the *Analyse the single view* step
  gives events, tempo and normalised hand speed from the 2-D track.

Both kinds of session are plain folders written by
`python3 -m src.motion_capture.rig`; every button in the tile runs that
command, so a terminal user and a tile user produce the same files.

## Navigate, Review, and Recover

The persistent status area names the selected swing and capture folder. Hover
over its identity to see the library capture ID and full folder. Use **Library**
to name a swing, add notes, open another capture, or create an editable copy.
Original recordings stay associated with their capture.

Click a workflow step to show its actions and instructions. **Next Step** opens
the suggested step without starting work. Read the blocked reason when an action
is unavailable. The status area explains validation errors, running commands,
completion, cancellation and failures; **Retry** repeats a failed action after
you correct its settings. **View Activity Log** shows command diagnostics.

**Capture Status** lists camera views, observation sets and matched variants.
It reads detector names from saved metadata, distinguishes missing outputs and
changed swing edits, and shows each variant's input views and observation set.
Double-click an observation row to inspect its provenance. Its action history
is saved in `capture_activity.json` in that capture's folder. A running record
from an earlier app session is labelled unconfirmed, since it cannot prove a
process is still alive. Finished commands and existing files do not establish
tracking quality or scientific validity; review overlays, reliability and results.

Use **Views** to pop out Live Cameras, Playback, Results, settings, workflow,
actions or the log onto another monitor. Close a floating window to return its
existing contents to the app. Double-click video or press **F11** for fullscreen;
**Escape** restores the previous docked or floating view. **Redock All Screens**
returns detached views, and **Reset Layout** restores the initial arrangement.
Save a named layout when you are happy with the arrangement.

**Help and Workflow** provides the same step instructions inside the app, with
clickable step links and a Find field. Press Enter to find the next occurrence.

## Pose Detection and Observation Sets

MediaPipe (primary) and OpenPose BODY_25 through OpenCV DNN (second opinion)
both write the same per-view record: `observations*/<view>.json` with the
detector's own keypoint names, pixels and confidences, `time_s` per frame
and the settings used in `provenance`. So they can be overlaid, compared
(`rig compare`: coverage, confidence, jitter, agreement per joint) and fed to
the same reconstruction. Each estimator writes its own set
(`observations_<name>/`); `observations/` is the set the fit reads.

## Which Joints to Trust

*Reliability* grades every shared joint from the evidence in the session:
coverage, mean confidence and frame-to-frame jitter across every observation
set, plus outlier rejections once a fit exists. On the lab takes hips and
shoulders are the steadiest, wrists and ankles next, the face weakest. Weak
joints are pre-filled in *Exclude joints*; the fit then treats them as
unobserved and lets the rigid-segment priors place them.

## Steps
"""

AFTER = """
## After Export

`reconstruct/reconstruction.trc` is an OpenSim marker file the motion pipeline
reads directly (see `docs/motion_pipeline/README.md`): scaling, inverse
kinematics and engine retargeting follow from there, and the model-matching
tools take the same file. `reconstruction_export.json` carries the same joints
in metres with names and fps stated.
"""


def render(steps: Sequence[Any]) -> str:
    """The whole guide for ``steps`` (workflow ``Step`` objects)."""
    parts = [PREAMBLE]
    for i, step in enumerate(steps, 1):
        parts.append(f"\n### {i}. {step.title}\n\n{step.purpose}\n")
        parts.append("\n**You need**\n\n")
        parts.extend(f"- {r}\n" for r in step.requirements)
        parts.append("\n**Do**\n\n")
        parts.extend(f"{n}. {s}\n" for n, s in enumerate(step.instructions, 1))
        parts.append(f"\nTile actions: {', '.join(step.actions)}.\n")
    parts.append(AFTER)
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    sys.path.insert(0, str(REPO_ROOT))
    from src.tools.capture_rig.workflow import STEPS

    text = render(STEPS)
    args = argv if argv is not None else sys.argv[1:]
    if "--check" in args:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        return 0 if current == text else 1
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
