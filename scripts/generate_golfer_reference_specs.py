"""Regenerate ``src/config/golfer_reference_specs.json`` (#15648).

Applies the current golfer model (``with_current_golfer_model``) to each
committed legacy reference spec and records the overlay and hashes.

    python3 scripts/generate_golfer_reference_specs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from src.shared.python.model_appearance.golfer_model_versions import (  # noqa: E402
    current_golfer_model,
)
from src.shared.python.motion_matching.execution import (  # noqa: E402
    golfer_reference_specs as refs,
)
from src.shared.python.motion_matching.execution.spec_revisions import (  # noqa: E402
    with_current_golfer_model,
)
from src.shared.python.motion_matching.full_body_spec import (  # noqa: E402
    canonical_sha256,
)

PARENTS = {
    "driver": "docs/development/full_body_models/full_body_spec_anthro_driver.json",
    "iron7": "docs/development/full_body_models/full_body_spec_anthro_iron7.json",
}


def build() -> dict:
    specs = {}
    for club, parent_path in PARENTS.items():
        parent = json.loads((REPO_ROOT / parent_path).read_text(encoding="utf-8"))
        current, _ = with_current_golfer_model(parent, dict(parent["subject"]))
        specs[club] = {
            "parent": parent_path,
            "parent_sha256": canonical_sha256(parent),
            "sha256": canonical_sha256(current),
            "overlay": refs.overlay_between(parent, current),
        }
    return {
        "sources": (
            "Generated by scripts/generate_golfer_reference_specs.py (#15648): "
            "the overlay turns each legacy reference spec into the current "
            "golfer model; read it with golfer_reference_specs.reference_spec."
        ),
        "golfer_model_version": current_golfer_model().version,
        "specs": specs,
    }


def render(settings: dict) -> str:
    """Indented JSON with one overlay operation per line, for short diffs."""
    marker = "__OVERLAY_{}__"
    shell = json.loads(json.dumps(settings))
    for club, entry in shell["specs"].items():
        entry["overlay"] = marker.format(club)
    text = json.dumps(shell, indent=2)
    for club, entry in settings["specs"].items():
        ops = ",\n".join(f"        {json.dumps(op)}" for op in entry["overlay"])
        text = text.replace(f'"{marker.format(club)}"', f"[\n{ops}\n      ]")
    if json.loads(text) != json.loads(json.dumps(settings)):
        raise ValueError("rendered settings do not parse back to the same data")
    return text + "\n"


def main() -> int:
    refs.SETTINGS_PATH.write_text(render(build()), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
