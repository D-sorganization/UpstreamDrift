"""Generate the putting studio's core green presets (#14648, epic #14452).

The standalone studio (``src/apps/putting_studio``) opens from ``file://`` and
cannot import the Python core, so it drew its own analytic green. This script
writes ``js/core_greens.js``: the height grid of every core
:data:`~src.shared.python.putting_dynamics.GREEN_PRESETS` green, on the core's
own spacing, so the studio's bilinear lookup reproduces
:meth:`~src.shared.python.putting_dynamics.surfaces.HeightField.elevation` and
``gradient``. The studio puts the green's centre at the putt midpoint.

The grid spans ``EXTENT_M`` along the putt, enough for the studio's longest
45 ft putt and its roll-out, and ``HALF_WIDTH_M`` either side of the line;
past the edge the lookup clamps, as the core does.

Usage::

    python3 -m scripts.generate_studio_greens   # rewrites the fixture
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from src.shared.python.contracts import require
from src.shared.python.putting_dynamics import GREEN_PRESETS, green_preset
from src.shared.python.putting_dynamics.surfaces import HeightField
from src.tools.putting_green_gui._scene_builder import green_label

FIXTURE = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "apps"
    / "putting_studio"
    / "js"
    / "core_greens.js"
)
EXTENT_M = 18.0
HALF_WIDTH_M = 3.0
_MM_DIGITS = 3
_PREFIX = "window.CORE_GREENS = "


def core_field(name: str) -> HeightField:
    """The core height field of preset ``name``, uncropped."""
    return green_preset(name).height(EXTENT_M)


def _rows(field: HeightField) -> tuple[float, list[list[float]]]:
    """Origin y [m] and node heights [mm] of the rows within ``HALF_WIDTH_M``."""
    y0 = field.origin_m[1]
    keep = [
        iy
        for iy in range(field.heights_m.shape[0])
        if abs(y0 + iy * field.spacing_m) <= HALF_WIDTH_M + 1e-9
    ]
    require(len(keep) >= 2, "the cropped grid needs two rows", keep)
    rows = [
        [round(1e3 * float(h), _MM_DIGITS) for h in field.heights_m[iy]] for iy in keep
    ]
    return y0 + keep[0] * field.spacing_m, rows


def build() -> dict[str, Any]:
    """The fixture data: shared grid metadata and each preset's height rows."""
    fields = {name: core_field(name) for name in GREEN_PRESETS}
    cropped = {name: _rows(field) for name, field in fields.items()}
    first = next(iter(fields.values()))
    require(
        all(f.origin_m == first.origin_m for f in fields.values()),
        "every preset must share one grid",
    )
    presets = {
        name: {
            "label": green_label(name),
            "origin_m": [first.origin_m[0], y_min],
            "spacing_m": first.spacing_m,
            "heights_mm": rows,
        }
        for name, (y_min, rows) in cropped.items()
    }
    return {
        "meta": {
            "schema_version": 1,
            "source": "putting_dynamics.GREEN_PRESETS, GreenSpec.height (#14648)",
            "placement": "green centre at the putt midpoint",
        },
        "presets": presets,
    }


def render(data: dict[str, Any]) -> str:
    """The fixture file text for ``data``: one grid row per line."""
    meta = json.dumps(data["meta"], indent=1, sort_keys=True).replace("\n", "\n ")
    blocks = []
    for name, preset in data["presets"].items():
        rows = ",\n   ".join(
            json.dumps(row, separators=(",", ":")) for row in preset["heights_mm"]
        )
        head = {k: v for k, v in preset.items() if k != "heights_mm"}
        blocks.append(
            f"  {json.dumps(name)}: {json.dumps(head)[:-1]}, "
            f'"heights_mm": [\n   {rows}\n  ]}}'
        )
    body = ",\n".join(blocks)
    return (
        "// Generated by scripts/generate_studio_greens.py -- do not edit.\n"
        f'{_PREFIX}{{\n "meta": {meta},\n "presets": {{\n{body}\n }}\n}};\n'
    )


def parse(text: str) -> dict[str, Any]:
    """Inverse of :func:`render`: the data object in a fixture file."""
    start = text.index(_PREFIX) + len(_PREFIX)
    end = text.index(";\n", start)
    data: dict[str, Any] = json.loads(text[start:end])
    return data


def main() -> None:
    FIXTURE.write_text(render(build()), encoding="utf-8")


if __name__ == "__main__":
    main()
