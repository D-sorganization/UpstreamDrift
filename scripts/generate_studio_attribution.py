"""Generate the putting studio's core strokes-gained attribution (#14459).

The standalone studio (``src/apps/putting_studio``) opens from ``file://`` and
cannot call the Python core, so its 6-channel "18-hole strokes gained
variance attribution" used to be hand-tuned closed-form numbers. This script
runs the shared core's :func:`service_variance.variance_study` for the fitted
tour-average player over a distance x side-slope grid and writes the per-round
gain from removing each error source to ``js/core_attribution.js``, together
with a nearest-cell lookup the studio calls.

Usage::

    python3 -m scripts.generate_studio_attribution   # rewrites the fixture

Generation takes several minutes (one Saltelli study per cell). A side slope
is mirror-symmetric, so one fall direction covers both signs of the studio's
cross slope.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Any

from src.shared.python.putting_analytics import service_variance
from src.shared.python.putting_analytics.calibration import TOUR_AVERAGE

FIXTURE = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "apps"
    / "putting_studio"
    / "js"
    / "core_attribution.js"
)
DISTANCES_FT: tuple[float, ...] = (3.0, 6.0, 10.0, 15.0, 20.0, 30.0)
SLOPES_PCT: tuple[float, ...] = (0.0, 2.0, 4.0)
FACTORS: tuple[str, ...] = (
    "face",
    "path",
    "speed",
    "read_grade",
    "read_aspect",
    "read_stimp",
)
# Any valid expected-putts curve prices a miss; this is the core's own
# pricing curve (``sg_curve._PRICING_BASELINE``), spelled as service input.
BASELINE = {
    "distances_ft": [0.5, 3.0, 10.0, 30.0, 100.0],
    "expected_putts": [1.0, 1.1, 1.5, 1.9, 2.5],
}
SAMPLING = {"base_samples": 128, "n_samples": 512, "n_bootstrap": 20, "seed": 1}
_PREFIX = "window.CORE_SG_ATTRIBUTION = "
_LOOKUP = """
// Nearest grid cell for the studio's putt distance (ft) and cross slope (%).
function coreAttributionCell(distFt, crossSlopePct) {
  const data = window.CORE_SG_ATTRIBUTION;
  const slope = Math.abs(crossSlopePct);
  let best = null;
  let bestCost = Infinity;
  for (const cell of data.cells) {
    const cost = Math.abs(Math.log(cell.distance_ft / Math.max(distFt, 0.5)))
      + Math.abs(cell.slope_pct - slope) / 2.0;
    if (cost < bestCost) {
      best = cell;
      bestCost = cost;
    }
  }
  return best;
}
"""


def cell_args(distance_ft: float, slope_pct: float) -> dict[str, Any]:
    """``variance_study`` arguments for one grid cell, tour-average player."""
    putt: dict[str, Any] = {"distance_ft": distance_ft}
    if slope_pct:
        putt.update(slope_pct=slope_pct, orientation="right_to_left")
    return {
        "baseline": BASELINE,
        "classes": [putt],
        **dataclasses.asdict(TOUR_AVERAGE.stroke),
        **dataclasses.asdict(TOUR_AVERAGE.read),
        "face_weight": TOUR_AVERAGE.face_weight,
        "factors": list(FACTORS),
        **SAMPLING,
    }


def cell_gains(report: dict[str, Any]) -> dict[str, float]:
    """Per-round strokes gained by removing each source, rounded to 4 dp."""
    gains = {f["factor"]: f["gain_removed"] for f in report["per_round"]["factors"]}
    return {factor: round(float(gains[factor]), 4) for factor in FACTORS}


def build() -> dict[str, Any]:
    """Run the core for every cell (slow) and return the fixture data."""
    cells = [
        {
            "distance_ft": d,
            "slope_pct": s,
            "gain_removed": cell_gains(
                service_variance.variance_study(cell_args(d, s))
            ),
        }
        for d in DISTANCES_FT
        for s in SLOPES_PCT
    ]
    meta = {
        "schema_version": 1,
        "source": "service_variance.variance_study (#14459)",
        "profile": TOUR_AVERAGE.name,
        "factors": list(FACTORS),
        "units": "strokes per 18 first putts",
        "sampling": SAMPLING,
        "noise_sg": 0.2,
    }
    return {"meta": meta, "cells": cells}


def render(data: dict[str, Any]) -> str:
    """The fixture file text for ``data``: one line per cell, so diffs stay
    readable and the file stays short."""
    cells = ",\n".join(f"  {json.dumps(c, sort_keys=True)}" for c in data["cells"])
    meta = json.dumps(data["meta"], sort_keys=True)
    body = f'{{\n "cells": [\n{cells}\n ],\n "meta": {meta}\n}}'
    return (
        "// Generated by scripts/generate_studio_attribution.py -- do not edit.\n"
        f"{_PREFIX}{body};\n{_LOOKUP}"
    )


def parse(text: str) -> dict[str, Any]:
    """Inverse of :func:`render`: the data object in a fixture file."""
    start = text.index(_PREFIX) + len(_PREFIX)
    end = text.index(";\n", start)
    data: dict[str, Any] = json.loads(text[start:end])
    return data


def main() -> None:
    FIXTURE.write_text(render(build()), encoding="utf-8")


if __name__ == "__main__":
    main()
