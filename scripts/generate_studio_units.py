"""Generate the putting studio's display-unit table (#14646, epic #14452).

The standalone studio (``src/apps/putting_studio``) opens from ``file://`` and
cannot import the Python core, so it hard-coded ft, m/s and mm in its labels.
This script writes the shared :mod:`src.shared.python.ui.units` table, the one
the API serves, rescaled to the studio's stored units (putt distance in ft,
speeds in m/s, strike in mm), to ``js/core_units.js`` with the formatter the
studio's labels call. The desktop simulator uses the same helpers, so both
show the same numbers.

Usage::

    python3 -m scripts.generate_studio_units   # rewrites the fixture
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from src.shared.python.ui.units import (
    UnitSystem,
    display_unit_table,
    from_display_distance,
    to_display_distance,
)

FIXTURE = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "apps"
    / "putting_studio"
    / "js"
    / "core_units.js"
)
# The studio's stored unit for each kind of value it labels.
STORED = {"distance": "ft", "speed": "m/s", "strike": "mm"}
_FT_M = from_display_distance(1.0, UnitSystem.IMPERIAL, unit="ft")
_PREFIX = "window.CORE_UNITS = "
_FORMAT = """
// A studio value held in its stored unit (ft, m/s or mm), shown in the
// selected unit system with `digits` decimals and the unit suffix.
function coreUnitText(kind, value, digits, system) {
  const unit = window.CORE_UNITS.systems[system][kind];
  return `${(value * unit.factor).toFixed(digits)}${unit.suffix}`;
}
"""


def unit_row(system: UnitSystem) -> dict[str, dict[str, Any]]:
    """Factor from each stored unit to ``system``'s display unit, and its suffix.

    The API's :func:`display_unit_table` rescaled from SI to the studio's
    stored units: putt distance in ft, speeds in m/s, strike in mm.
    """
    table = display_unit_table(system)
    per_si = {"distance": _FT_M, "speed": 1.0, "strike": 1e-3}
    source = {"distance": "distance", "speed": "speed", "strike": "small_length"}
    rows = {
        kind: {
            "factor": table[source[kind]]["factor"] * per_si[kind],
            "suffix": table[source[kind]]["suffix"],
        }
        for kind in STORED
    }
    # One ft converted straight to the display unit, so ft to ft is exactly 1
    # (m-to-ft times ft-to-m rounds to 0.9999999999999999, #14703).
    rows["distance"]["factor"] = to_display_distance(_FT_M, system, unit="ft")
    return rows


def build() -> dict[str, Any]:
    """The fixture data: one row per unit system."""
    return {
        "meta": {
            "schema_version": 1,
            "source": "src.shared.python.ui.units (#14646)",
            "stored": STORED,
        },
        "systems": {system.value: unit_row(system) for system in UnitSystem},
    }


def render(data: dict[str, Any]) -> str:
    """The fixture file text for ``data``."""
    body = json.dumps(data, indent=1, sort_keys=True)
    return (
        "// Generated by scripts/generate_studio_units.py -- do not edit.\n"
        f"{_PREFIX}{body};\n{_FORMAT}"
    )


def parse(text: str) -> dict[str, Any]:
    """Inverse of :func:`render`: the data object in a fixture file."""
    start = text.index(_PREFIX) + len(_PREFIX)
    end = text.index(";\n", start)
    data: dict[str, Any] = json.loads(text[start:end])
    return data


def main() -> None:
    FIXTURE.write_text(render(build()), encoding="utf-8")


if __name__ == "__main__":
    main()
