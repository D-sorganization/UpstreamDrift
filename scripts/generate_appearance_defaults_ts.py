"""Generate the web UI's default-golfer module from the one contract.

``src/config/appearance_defaults.json`` is the single source (HRG-B1, #13163).
This writes ``ui/src/components/character/appearanceDefaults.generated.ts``;
a unit test fails when the checked-in file is stale. Run::

    python3 -m scripts.generate_appearance_defaults_ts
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/config/appearance_defaults.json"
TARGET = ROOT / "ui/src/components/character/appearanceDefaults.generated.ts"


def render() -> str:
    """TypeScript source for the contract. Postcondition: deterministic."""
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    d = data["default"]
    skin = {s["id"]: s["hex"] for s in data["skin_palette"]}
    for legacy, target in data["skin_aliases"].items():
        skin[legacy] = skin[target]
    hair = {h["id"]: h["hex"] for h in data["hair_palette"]}

    def table(name: str, mapping: dict[str, str]) -> str:
        rows = "".join(f"  {k}: '{v}',\n" for k, v in mapping.items())
        return f"export const {name}: Record<string, string> = {{\n{rows}}};\n"

    return (
        "// GENERATED by scripts/generate_appearance_defaults_ts.py from\n"
        "// src/config/appearance_defaults.json. Do not edit by hand.\n"
        "// Colours are sRGB hex; three.js applies its own colour management.\n\n"
        f"export const DEFAULT_SKIN_TONE = '{d['skin_tone']}';\n"
        f"export const DEFAULT_HEADWEAR = '{d['headwear']}';\n"
        f"export const DEFAULT_HAIR_MATERIAL = '{d['headwear_material']}';\n"
        f"export const DEFAULT_CLOTHING = '{d['clothing']}';\n"
        f"export const DEFAULT_CLUB_FINISH = '{d['club_finish']}';\n"
        f"export const DEFAULT_SKIN_HEX = '{skin[d['skin_tone']]}';\n"
        f"export const DEFAULT_HAIR_HEX = '{hair[d['headwear_material']]}';\n\n"
        + table("SKIN_HEX", skin)
        + "\n"
        + table("HAIR_HEX", hair)
    )


def main() -> None:
    TARGET.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
