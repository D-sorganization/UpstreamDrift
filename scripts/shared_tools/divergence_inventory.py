# CLI
# --------------------------------------------------------------------------


def check_inventory(repo_root: Path, json_path: Path) -> list[str]:
    """Return a list of staleness errors (empty when the JSON is current)."""
    if not json_path.is_file():
        return [f"inventory missing: {json_path}"]
    try:
        committed = json.loads(json_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"inventory unreadable: {json_path}: {exc}"]
    current = build_inventory(repo_root, with_authorship=False)
    errors: list[str] = []
    if committed.get("tools_pin") != current.tools_pin:
        errors.append(
            f"tools_pin drift: committed {committed.get('tools_pin')} != "
            f"gitlink {current.tools_pin}"
        )
    committed_core = {entry["path"]: entry for entry in committed.get("files", [])}
    current_core = {entry["path"]: entry for entry in current.stable_core()}
    for path in sorted(set(committed_core) | set(current_core)):
        old = committed_core.get(path)
        new = current_core.get(path)
        if old is None:
            errors.append(
                f"new path not in inventory: {path} ({new['classification']})"
            )
        elif new is None:
            errors.append(f"path no longer exists: {path}")
        elif old != new:
            errors.append(
                f"changed: {path} {old['classification']} -> {new['classification']}"
            )
    return errors


def _write_outputs(
    inventory: Inventory, repo_root: Path, json_path: Path, md_path: Path
) -> None:
    (repo_root / json_path).parent.mkdir(parents=True, exist_ok=True)
    (repo_root / json_path).write_text(
        render_json(inventory), encoding="utf-8", newline="\n"
    )
    (repo_root / md_path).write_text(
        render_markdown(inventory) + "\n", encoding="utf-8", newline="\n"
    )


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--repo-root", type=Path, default=_REPO_ROOT)
    parser.add_argument("--json", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--markdown", type=Path, default=DEFAULT_MARKDOWN)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write", action="store_true", help="Regenerate the JSON and markdown."
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Fail (exit 1) when the committed JSON is stale.",
    )
    mode.add_argument(
        "--table",
        action="store_true",
        help="Print only the package-level markdown table.",
    )
    parser.add_argument(
        "--no-authorship",
        action="store_true",
        help="Skip the per-file git log lookups (faster).",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    repo_root = args.repo_root.resolve()
    if args.check:
        errors = check_inventory(repo_root, repo_root / args.json)
        if errors:
            print("divergence inventory is STALE; regenerate with --write:")
            for error in errors[:50]:
                print(f"  - {error}")
            if len(errors) > 50:
                print(f"  ... and {len(errors) - 50} more")
            return 1
        print(f"divergence inventory is current ({args.json}).")
        return 0
    inventory = build_inventory(repo_root, with_authorship=not args.no_authorship)
    if args.table:
        print(render_package_table(inventory))
        return 0
    if args.write:
        _write_outputs(inventory, repo_root, args.json, args.markdown)
        print(f"wrote {args.json} and {args.markdown}")
    print(render_package_table(inventory))
    return 0


if __name__ == "__main__":
    sys.exit(main())
