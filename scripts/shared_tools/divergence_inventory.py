def render_committed(inventory: Inventory) -> str:
    """Render the committed artifact: header line, then one sorted record/line."""
    lines = [json.dumps(inventory.header(), sort_keys=False)]
    lines.extend(
        json.dumps(entry, sort_keys=False)
        for entry in sorted(inventory.stable_core(), key=lambda e: str(e["path"]))
    )
    return "\n".join(lines) + "\n"


def _parse_lines(json_path: Path) -> list[dict[str, object]]:
    text = json_path.read_text(encoding="utf-8")
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines:
        raise InventoryFormatError(f"{json_path}: empty inventory")
    parsed: list[dict[str, object]] = []
    for number, line in enumerate(lines, start=1):
        try:
            value = json.loads(line)
        except ValueError as exc:
            raise InventoryFormatError(
                f"{json_path}:{number}: not JSON: {exc}"
            ) from exc
        if not isinstance(value, dict):
            raise InventoryFormatError(f"{json_path}:{number}: expected an object")
        parsed.append(value)
    return parsed


def _validate_record(
    json_path: Path, number: int, record: dict[str, object], previous: object
) -> None:
    where = f"{json_path}:{number}"
    if set(record) != set(STABLE_FIELDS):
        raise InventoryFormatError(
            f"{where}: fields {sorted(record)} != {sorted(STABLE_FIELDS)}"
        )
    if record["classification"] not in CLASSIFICATIONS:
        raise InventoryFormatError(
            f"{where}: bad classification {record['classification']!r}"
        )
    if not isinstance(record["path"], str) or not isinstance(
        record["spelling_only"], bool
    ):
        raise InventoryFormatError(f"{where}: bad field types")
    if previous is not None and str(record["path"]) <= str(previous):
        raise InventoryFormatError(f"{where}: records not sorted/unique")


def load_committed(
    json_path: Path,
) -> tuple[dict[str, object], list[dict[str, object]]]:
    """Parse and validate the committed artifact (design by contract).

    Raises ``InventoryFormatError`` when a line is not JSON, the header lacks a
    required field or has the wrong schema version, or a record is malformed,
    unsorted or duplicated.
    """
    parsed = _parse_lines(json_path)
    header, records = parsed[0], parsed[1:]
    missing = [name for name in HEADER_FIELDS if name not in header]
    if missing:
        raise InventoryFormatError(f"{json_path}: header lacks {missing}")
    if header["schema_version"] != SCHEMA_VERSION:
        raise InventoryFormatError(
            f"{json_path}: schema_version {header['schema_version']} != "
            f"{SCHEMA_VERSION}; regenerate with --write"
        )
    previous: object = None
    for number, record in enumerate(records, start=2):
        _validate_record(json_path, number, record, previous)
        previous = record["path"]
    return header, records


def render_package_table(inventory: Inventory) -> str:
    """Markdown table: one row per top-level package, plus a totals row."""
    lines = [
        "| Package | Identical | Diverged | of which spelling-only | UD-only | "
        "Tools-only | Overlap |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, counts in inventory.by_package().items():
        identical = counts.get("identical", 0)
        diverged = counts.get("diverged", 0)
        lines.append(
            f"| `{name}` | {identical} | {diverged} | "
            f"{counts.get('spelling-only', 0)} | "
            f"{counts.get('ud-only', 0)} | {counts.get('tools-only', 0)} | "
            f"{identical + diverged} |"
        )
    totals = inventory.counts
    spelling_only_total = sum(1 for r in inventory.files if r.spelling_only)
    lines.append(
        f"| **Total** | **{totals.get('identical', 0)}** | "
        f"**{totals.get('diverged', 0)}** | **{spelling_only_total}** | "
        f"**{totals.get('ud-only', 0)}** | "
        f"**{totals.get('tools-only', 0)}** | "
        f"**{totals.get('identical', 0) + totals.get('diverged', 0)}** |"
    )
    return "\n".join(lines)


def render_markdown(inventory: Inventory) -> str:
    authorship_by_path = {entry.path: entry for entry in inventory.authorship}
    parts = [
        "# Shared Tools Divergence Inventory",
        "",
        "On-demand report from `python -m scripts.shared_tools.divergence_inventory "
        "--report`; not committed (UD #12833).",
        "",
        f"- Tools pin (`vendor/ud-tools` gitlink): `{inventory.tools_pin}`",
        f"- UD tree: `{inventory.ud_root}`",
        f"- Tools tree: `{inventory.tools_root}`",
        "- Program: D-sorganization/Repository_Management#1505 · Epic: UD #9406 · "
        "Ledger: Tools #4915",
        "",
        "`identical` ignores line endings, trailing whitespace and the "
        "`DO NOT EDIT` child-copy header; `diverged` means real content differs; "
        "`spelling-only` counts diverged files whose only difference is the "
        "`src.shared.python` vs `shared.python` import prefix.",
        "",
        "## Package Summary",
        "",
        render_package_table(inventory),
        "",
        "## Diverged Files by Package",
        "",
    ]
    diverged = [r for r in inventory.files if r.classification == "diverged"]
    grouped: dict[str, list[FileRecord]] = defaultdict(list)
    for record in diverged:
        grouped[record.package].append(record)
    for package, records in sorted(grouped.items()):
        parts.append(f"### Package `{package}` ({len(records)} Diverged Files)")
        parts.append("")
        parts.append(
            "| Path | Δ bytes (UD−Tools) | Spelling-only | UD last touch | "
            "Tools last touch |"
        )
        parts.append("|---|---:|:---:|---|---|")
        for record in records:
            entry = authorship_by_path.get(record.path)
            ud_touch = (
                f"{entry.ud.author} {entry.ud.date}"
                if entry and entry.ud.author
                else "?"
            )
            tools_touch = (
                f"{entry.tools.author} {entry.tools.date}"
                if entry and entry.tools.author
                else "?"
            )
            parts.append(
                f"| `{record.path}` | {record.byte_delta:+d} | "
                f"{'yes' if record.spelling_only else ''} | {ud_touch} | "
                f"{tools_touch} |"
            )
        parts.append("")
    return "\n".join(parts)


