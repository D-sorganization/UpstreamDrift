"""Inventory the divergence between ``src/shared/python`` and the pinned Tools tree.

UpstreamDrift carries a committed shadow copy of the Tools shared-code tree
(``src/shared/python``) next to the pinned ``vendor/ud-tools`` submodule. This
script compares every file under the shadow tree with the same relative path
under the vendored Tools tree and classifies each path as one of:

``identical``
    Same content after normalising line endings, trailing whitespace and the
    ``# WARNING: DO NOT EDIT THIS FILE DIRECTLY`` child-copy header.
``diverged``
    Both sides exist but the *real* content differs.
``ud-only``
    Present only in ``src/shared/python``.
``tools-only``
    Present only in ``vendor/ud-tools/src/shared/python``.

For every ``diverged`` file the inventory also records the last-touch author
and date on both sides (``git log -1``), the byte delta (UD minus Tools) and
the top-level package so the seam epic (UD #9406) and the Tools divergence
ledger (Tools #4915 / #4496) can rule per package.

Outputs (``--write``): ``docs/shared_tools/divergence_inventory.v1.json`` and a
markdown summary next to it. ``--check`` regenerates the stable core of the
inventory (path, classification, package, sizes) and fails when the committed
JSON no longer matches it; authorship is deliberately excluded from the
staleness check because it changes on every unrelated touch of a file.

Program: D-sorganization/Repository_Management#1505 (Phase 1, pillar P1).
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess  # nosec B404 - fixed git invocations, no shell
import sys
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass, field
from pathlib import Path

SCHEMA_VERSION = 1
CHILD_COPY_HEADER = "# WARNING: DO NOT EDIT THIS FILE DIRECTLY"
CLASSIFICATIONS = ("identical", "diverged", "ud-only", "tools-only")

_REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_UD_ROOT = Path("src/shared/python")
DEFAULT_TOOLS_ROOT = Path("vendor/ud-tools/src/shared/python")
DEFAULT_JSON = Path("docs/shared_tools/divergence_inventory.v1.json")
DEFAULT_MARKDOWN = Path("docs/shared_tools/divergence_inventory.md")

# Names that are never meaningful for the seam ruling.
_IGNORED_DIR_NAMES = frozenset({"__pycache__", ".pytest_cache", ".mypy_cache"})
_IGNORED_SUFFIXES = frozenset({".pyc", ".pyo"})

# Alias roots served by ``SharedImportAliasFinder`` that the vendored Tools
# tree also exposes outside ``src/shared/python`` (thin shims). They are
# reported separately so rulings do not confuse a shim with real content.
VENDOR_SHIM_ROOTS: tuple[tuple[str, Path], ...] = (
    ("sidekick", Path("vendor/ud-tools/src/sidekick")),
    ("chat", Path("vendor/ud-tools/src/chat")),
    ("chat_contracts", Path("vendor/ud-tools/src/chat_contracts")),
    ("contracts", Path("vendor/ud-tools/src/contracts.py")),
    ("utils", Path("vendor/ud-tools/src/python/src/utils")),
)


@dataclass(frozen=True)
class FileRecord:
    """One relative path in the union of the two trees (stable core)."""

    path: str
    classification: str
    package: str
    subpackage: str
    ud_bytes: int | None
    tools_bytes: int | None
    byte_delta: int | None
    byte_identical: bool
    ud_has_child_copy_header: bool


@dataclass(frozen=True)
class Authorship:
    """Last-touch authorship for one side of a diverged file."""

    author: str | None
    date: str | None
    commit: str | None


@dataclass(frozen=True)
class DivergedAuthorship:
    path: str
    ud: Authorship
    tools: Authorship


@dataclass
class Inventory:
    schema_version: int
    tools_pin: str | None
    ud_root: str
    tools_root: str
    files: list[FileRecord]
    authorship: list[DivergedAuthorship] = field(default_factory=list)
    vendor_shim_roots: dict[str, str] = field(default_factory=dict)

    @property
    def counts(self) -> Counter[str]:
        return Counter(record.classification for record in self.files)

    def by_package(self) -> dict[str, Counter[str]]:
        table: dict[str, Counter[str]] = defaultdict(Counter)
        for record in self.files:
            table[record.package][record.classification] += 1
        return dict(sorted(table.items()))

    def stable_core(self) -> list[dict[str, object]]:
        """Return the part of the inventory that ``--check`` compares."""
        return [asdict(record) for record in self.files]

    def to_json_dict(self) -> dict[str, object]:
        packages = {
            name: {cls: counts.get(cls, 0) for cls in CLASSIFICATIONS}
            for name, counts in self.by_package().items()
        }
        return {
            "schema_version": self.schema_version,
            "tools_pin": self.tools_pin,
            "ud_root": self.ud_root,
            "tools_root": self.tools_root,
            "vendor_shim_roots": self.vendor_shim_roots,
            "totals": {cls: self.counts.get(cls, 0) for cls in CLASSIFICATIONS},
            "packages": packages,
            "files": self.stable_core(),
            "authorship": [asdict(entry) for entry in self.authorship],
        }


# --------------------------------------------------------------------------
# Content normalisation
# --------------------------------------------------------------------------

_HEADER_BLOCK_RE = re.compile(
    r"\A(?:#[^\n]*\n)*?" + re.escape(CHILD_COPY_HEADER) + r"[^\n]*\n(?:#[^\n]*\n)*"
)


def normalise(content: bytes) -> bytes:
    """Normalise a file body so header-only and whitespace-only diffs vanish."""
    text = content.replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    try:
        decoded = text.decode("utf-8")
    except UnicodeDecodeError:
        return text
    if CHILD_COPY_HEADER in decoded:
        decoded = _HEADER_BLOCK_RE.sub("", decoded, count=1)
    lines = [line.rstrip() for line in decoded.split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines).encode("utf-8")


# --------------------------------------------------------------------------
# Tree walking
# --------------------------------------------------------------------------


def _iter_files(root: Path) -> dict[str, Path]:
    if not root.is_dir():
        return {}
    found: dict[str, Path] = {}
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(root)
        if any(part in _IGNORED_DIR_NAMES for part in relative.parts):
            continue
        if path.suffix in _IGNORED_SUFFIXES:
            continue
        found[relative.as_posix()] = path
    return found


def _package_of(relative: str) -> tuple[str, str]:
    parts = relative.split("/")
    if len(parts) == 1:
        return parts[0], ""
    return parts[0], parts[1] if len(parts) > 2 else ""


def _git_last_touch(repo: Path, relative: Path) -> Authorship:
    git = shutil.which("git")
    if git is None:
        return Authorship(None, None, None)
    try:
        completed = subprocess.run(  # nosec B603 - fixed args, no shell
            [
                git,
                "-C",
                str(repo),
                "log",
                "-1",
                "--format=%an|%ad|%H",
                "--date=short",
                "--",
                relative.as_posix(),
            ],
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return Authorship(None, None, None)
    line = completed.stdout.strip()
    if completed.returncode != 0 or not line:
        return Authorship(None, None, None)
    author, date, commit = (line.split("|", 2) + [None, None, None])[:3]
    return Authorship(author, date, commit)


def pinned_tools_sha(repo_root: Path) -> str | None:
    """Return the ``vendor/ud-tools`` gitlink SHA recorded in the index."""
    git = shutil.which("git")
    if git is None:
        return None
    try:
        completed = subprocess.run(  # nosec B603
            [git, "-C", str(repo_root), "ls-files", "--stage", "vendor/ud-tools"],
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    fields = completed.stdout.split()
    if len(fields) >= 2 and fields[0] == "160000":
        return fields[1]
    return None


def build_inventory(
    repo_root: Path,
    *,
    ud_root: Path = DEFAULT_UD_ROOT,
    tools_root: Path = DEFAULT_TOOLS_ROOT,
    with_authorship: bool = True,
) -> Inventory:
    """Compare the two trees and return the full inventory."""
    ud_abs = repo_root / ud_root
    tools_abs = repo_root / tools_root
    if not tools_abs.is_dir():
        raise FileNotFoundError(
            f"Pinned Tools tree missing at {tools_abs}; run "
            "`git submodule update --init vendor/ud-tools`."
        )
    ud_files = _iter_files(ud_abs)
    tools_files = _iter_files(tools_abs)

    records: list[FileRecord] = []
    for relative in sorted(set(ud_files) | set(tools_files)):
        ud_path = ud_files.get(relative)
        tools_path = tools_files.get(relative)
        package, subpackage = _package_of(relative)
        ud_content = ud_path.read_bytes() if ud_path else None
        tools_content = tools_path.read_bytes() if tools_path else None
        ud_bytes = None if ud_content is None else len(ud_content)
        tools_bytes = None if tools_content is None else len(tools_content)
        header = bool(
            ud_content is not None
            and ud_content.lstrip().startswith(CHILD_COPY_HEADER.encode("utf-8"))
        )
        if ud_content is None:
            classification = "tools-only"
            byte_identical = False
        elif tools_content is None:
            classification = "ud-only"
            byte_identical = False
        else:
            byte_identical = ud_content == tools_content
            classification = (
                "identical"
                if byte_identical or normalise(ud_content) == normalise(tools_content)
                else "diverged"
            )
        delta = (
            None if ud_bytes is None or tools_bytes is None else ud_bytes - tools_bytes
        )
        records.append(
            FileRecord(
                path=relative,
                classification=classification,
                package=package,
                subpackage=subpackage,
                ud_bytes=ud_bytes,
                tools_bytes=tools_bytes,
                byte_delta=delta,
                byte_identical=byte_identical,
                ud_has_child_copy_header=header,
            )
        )

    authorship: list[DivergedAuthorship] = []
    if with_authorship:
        vendor_repo = repo_root / "vendor" / "ud-tools"
        for record in records:
            if record.classification != "diverged":
                continue
            authorship.append(
                DivergedAuthorship(
                    path=record.path,
                    ud=_git_last_touch(repo_root, ud_root / record.path),
                    tools=_git_last_touch(
                        vendor_repo, Path("src/shared/python") / record.path
                    ),
                )
            )

    shims = {
        name: path.as_posix()
        for name, path in VENDOR_SHIM_ROOTS
        if (repo_root / path).exists()
    }
    return Inventory(
        schema_version=SCHEMA_VERSION,
        tools_pin=pinned_tools_sha(repo_root),
        ud_root=ud_root.as_posix(),
        tools_root=tools_root.as_posix(),
        files=records,
        authorship=authorship,
        vendor_shim_roots=shims,
    )


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------


def render_json(inventory: Inventory) -> str:
    return json.dumps(inventory.to_json_dict(), indent=2, sort_keys=False) + "\n"


def render_package_table(inventory: Inventory) -> str:
    """Markdown table: one row per top-level package, plus a totals row."""
    lines = [
        "| Package | Identical | Diverged | UD-only | Tools-only | Overlap |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, counts in inventory.by_package().items():
        identical = counts.get("identical", 0)
        diverged = counts.get("diverged", 0)
        lines.append(
            f"| `{name}` | {identical} | {diverged} | "
            f"{counts.get('ud-only', 0)} | {counts.get('tools-only', 0)} | "
            f"{identical + diverged} |"
        )
    totals = inventory.counts
    lines.append(
        f"| **Total** | **{totals.get('identical', 0)}** | "
        f"**{totals.get('diverged', 0)}** | **{totals.get('ud-only', 0)}** | "
        f"**{totals.get('tools-only', 0)}** | "
        f"**{totals.get('identical', 0) + totals.get('diverged', 0)}** |"
    )
    return "\n".join(lines)


def render_markdown(inventory: Inventory) -> str:
    authorship_by_path = {entry.path: entry for entry in inventory.authorship}
    parts = [
        "# Shared-tools divergence inventory (v1)",
        "",
        "Generated by `python -m scripts.shared_tools.divergence_inventory --write`.",
        "Do not edit by hand; regenerate after any change under "
        f"`{inventory.ud_root}` or a `vendor/ud-tools` pin bump.",
        "",
        f"- Tools pin (`vendor/ud-tools` gitlink): `{inventory.tools_pin}`",
        f"- UD tree: `{inventory.ud_root}`",
        f"- Tools tree: `{inventory.tools_root}`",
        "- Program: D-sorganization/Repository_Management#1505 · Epic: UD #9406 · "
        "Ledger: Tools #4915",
        "",
        "`identical` ignores line endings, trailing whitespace and the "
        "`DO NOT EDIT` child-copy header; `diverged` means real content differs.",
        "",
        "## Package summary",
        "",
        render_package_table(inventory),
        "",
        "## Diverged files by package",
        "",
    ]
    diverged = [r for r in inventory.files if r.classification == "diverged"]
    grouped: dict[str, list[FileRecord]] = defaultdict(list)
    for record in diverged:
        grouped[record.package].append(record)
    for package, records in sorted(grouped.items()):
        parts.append(f"### `{package}` ({len(records)} diverged)")
        parts.append("")
        parts.append("| Path | Δ bytes (UD−Tools) | UD last touch | Tools last touch |")
        parts.append("|---|---:|---|---|")
        for record in records:
            entry = authorship_by_path.get(record.path)
            ud_touch = (
                f"{entry.ud.author} {entry.ud.date}"
                if entry and entry.ud.author
                else "?"
            )
            tools_touch = (
                f"{entry.tools.author} {entry.tools.date}"
                if entry and entry.tools.author
                else "?"
            )
            parts.append(
                f"| `{record.path}` | {record.byte_delta:+d} | {ud_touch} | "
                f"{tools_touch} |"
            )
        parts.append("")
    return "\n".join(parts)


