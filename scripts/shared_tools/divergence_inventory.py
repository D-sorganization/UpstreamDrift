"""Inventory the divergence between ``src/shared/python`` and the pinned Tools tree.

UpstreamDrift carries a committed shadow copy of the Tools shared-code tree
(``src/shared/python``) next to the pinned ``vendor/ud-tools`` submodule. This
script compares every file under the shadow tree with the same relative path
under the vendored Tools tree and classifies each path as one of:

``identical``
    Same content after normalising line endings, trailing whitespace and the
    ``# WARNING: DO NOT EDIT THIS FILE DIRECTLY`` child-copy header.
``diverged``
    Both sides exist but the *real* content differs. ``spelling_only`` marks
    the subset whose only difference is the import prefix ``src.shared.python``
    (UD) versus ``shared.python`` (Tools); those are mechanical, not semantic.
``ud-only``
    Present only in ``src/shared/python``.
``tools-only``
    Present only in ``vendor/ud-tools/src/shared/python``.

For every ``diverged`` file the inventory also records the last-touch author
and date on both sides (``git log -1``), the byte delta (UD minus Tools) and
the top-level package so the seam epic (UD #9406) and the Tools divergence
ledger (Tools #4915 / #4496) can rule per package.

Committed artifact (``--write``): ``docs/shared_tools/divergence_inventory.v2.jsonl``
holds STABLE per-path facts only (``path``, ``classification``, ``package``,
``spelling_only``), one JSON record per line, sorted by path, after a single
header line. There are no aggregates, byte sizes or authorship in it, so two
PRs that touch different shared paths merge cleanly with git's line merge
(UD #12833; the v1 file and its markdown twin conflicted on every merge).

``--report`` prints the volatile view (package totals, byte deltas, last-touch
authorship) as markdown on stdout; it is computed on demand and never
committed. ``--check`` regenerates the inventory and fails when a path's
classification, package or spelling-only flag no longer matches the committed
file.

Program: D-sorganization/Repository_Management#1505 (Phase 1, pillar P1).
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess  # nosec B404 - fixed git invocations, no shell
import sys
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass, field
from pathlib import Path

SCHEMA_VERSION = 2
CHILD_COPY_HEADER = "# WARNING: DO NOT EDIT THIS FILE DIRECTLY"
CLASSIFICATIONS = ("identical", "diverged", "ud-only", "tools-only")

_REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_UD_ROOT = Path("src/shared/python")
DEFAULT_TOOLS_ROOT = Path("vendor/ud-tools/src/shared/python")
DEFAULT_JSON = Path("docs/shared_tools/divergence_inventory.v2.jsonl")

# The only per-path fields that are committed (stable under unrelated edits).
STABLE_FIELDS = ("path", "classification", "package", "spelling_only")
HEADER_FIELDS = ("schema_version", "tools_pin", "ud_root", "tools_root")


class InventoryFormatError(ValueError):
    """The committed inventory does not match the documented schema."""


# Names that are never meaningful for the seam ruling.
_IGNORED_DIR_NAMES = frozenset(
    {"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"}
)
_IGNORED_SUFFIXES = frozenset({".pyc", ".pyo"})

# Alias roots served by ``SharedImportAliasFinder`` that the vendored Tools
# tree also exposes outside ``src/shared/python`` (thin shims). They are
# reported separately so rulings do not confuse a shim with real content.
VENDOR_SHIM_ROOTS: tuple[tuple[str, Path], ...] = (
    ("sidekick", Path("vendor/ud-tools/src/sidekick")),
    ("chat", Path("vendor/ud-tools/src/chat")),
    ("chat_contracts", Path("vendor/ud-tools/src/chat_contracts")),
    ("contracts", Path("vendor/ud-tools/src/contracts.py")),
    ("utils", Path("vendor/ud-tools/src/python/src/utils")),
)


@dataclass(frozen=True)
class FileRecord:
    """One relative path in the union of the two trees (stable core)."""

    path: str
    classification: str
    package: str
    subpackage: str
    ud_bytes: int | None
    tools_bytes: int | None
    byte_delta: int | None
    byte_identical: bool
    ud_has_child_copy_header: bool
    spelling_only: bool = False


@dataclass(frozen=True)
class Authorship:
    """Last-touch authorship for one side of a diverged file."""

    author: str | None
    date: str | None
    commit: str | None


@dataclass(frozen=True)
class DivergedAuthorship:
    path: str
    ud: Authorship
    tools: Authorship


@dataclass
class Inventory:
    schema_version: int
    tools_pin: str | None
    ud_root: str
    tools_root: str
    files: list[FileRecord]
    authorship: list[DivergedAuthorship] = field(default_factory=list)
    vendor_shim_roots: dict[str, str] = field(default_factory=dict)

    @property
    def counts(self) -> Counter[str]:
        return Counter(record.classification for record in self.files)

    def by_package(self) -> dict[str, Counter[str]]:
        table: dict[str, Counter[str]] = defaultdict(Counter)
        for record in self.files:
            table[record.package][record.classification] += 1
            if record.spelling_only:
                table[record.package]["spelling-only"] += 1
        return dict(sorted(table.items()))

    def header(self) -> dict[str, object]:
        """Return the header record (one line, changes only on a pin bump)."""
        return {
            "schema_version": self.schema_version,
            "tools_pin": self.tools_pin,
            "ud_root": self.ud_root,
            "tools_root": self.tools_root,
            "vendor_shim_roots": self.vendor_shim_roots,
        }

    def stable_core(self) -> list[dict[str, object]]:
        """Return the per-file records written to the committed artifact."""
        return [stable_record(record) for record in self.files]


def stable_record(record: FileRecord) -> dict[str, object]:
    """Project a record onto the stable fields (the single serializer input)."""
    return {name: getattr(record, name) for name in STABLE_FIELDS}


# --------------------------------------------------------------------------
# Content normalisation
# --------------------------------------------------------------------------

_HEADER_BLOCK_RE = re.compile(
    r"\A(?:#[^\n]*\n)*?" + re.escape(CHILD_COPY_HEADER) + r"[^\n]*\n(?:#[^\n]*\n)*"
)


_SRC_PREFIX_RE = re.compile(r"\bsrc\.shared\.python\b")


def normalise(content: bytes, *, fold_import_spelling: bool = False) -> bytes:
    """Normalise a file body so header-only and whitespace-only diffs vanish.

    With ``fold_import_spelling`` the UD import prefix ``src.shared.python`` is
    folded onto the Tools spelling ``shared.python`` as well.
    """
    text = content.replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    try:
        decoded = text.decode("utf-8")
    except UnicodeDecodeError:
        return text
    if CHILD_COPY_HEADER in decoded:
        decoded = _HEADER_BLOCK_RE.sub("", decoded, count=1)
    if fold_import_spelling:
        decoded = _SRC_PREFIX_RE.sub("shared.python", decoded)
    lines = [line.rstrip() for line in decoded.split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines).encode("utf-8")


