"""Core expected-putts curve in the putting studio (#14650, epic #14452).

The studio priced a miss with a Bellman formula and a hand-tuned comeback
fit, and drew E(d) from two closed-form exponentials. ``js/core_sg.js``,
generated by ``scripts/generate_studio_sg.py``, holds the core's solved
player E(d) (``service_sg.sg_study``) for the tour-average player on a
side-slope grid. The batch's strokes gained, the E(d) chart and the optimal
pace now read it. Golden parity: the studio's E(d) and strokes gained on the
committed curve equal the core ``ExpectedPuttsCurve`` and ``score_putt``.

A full regeneration takes about 25 minutes (one policy iteration per slope at
about a second per skill-model putt on a sloped green), so the flat curve is
re-solved as the golden check, the file is checked as the generator's
rendering of its data, and the core arguments are checked against the core's
own parsers.
"""

from __future__ import annotations

import dataclasses
import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from scripts import generate_studio_sg as gen
from src.shared.python.putting_analytics import service_sg
from src.shared.python.putting_analytics.aggregate import DEFAULT_GRID_FT
from src.shared.python.putting_analytics.calibration import TOUR_AVERAGE
from src.shared.python.putting_analytics.service_dispersion import green_from_args
from src.shared.python.putting_analytics.service_variance import profile_from_args
from src.shared.python.putting_analytics.skill_roll_model import PlaneGreen

pytestmark = pytest.mark.unit

_STUDIO = Path(__file__).resolve().parents[3] / "src" / "apps" / "putting_studio"
_FIXTURE = _STUDIO / "js" / "core_sg.js"
_NODE = shutil.which("node")
_requires_node = pytest.mark.skipif(_NODE is None, reason="node is not on PATH")


def _js(name: str) -> str:
    return (_STUDIO / "js" / name).read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def committed() -> dict[str, Any]:
    return gen.parse(_FIXTURE.read_text(encoding="utf-8"))


def _node(expression: str) -> object:
    script = (
        "const window = globalThis;\n"
        + _FIXTURE.read_text(encoding="utf-8")
        + f"\nprocess.stdout.write(JSON.stringify({expression}));"
    )
    assert _NODE is not None
    out = subprocess.run(
        [_NODE, "-e", script], capture_output=True, text=True, check=True, timeout=30
    )
    return json.loads(out.stdout)


def test_fixture_is_the_rendering_of_its_own_data(committed: dict[str, Any]) -> None:
    assert gen.render(committed) == _FIXTURE.read_text(encoding="utf-8")


def test_golden_curve_matches_the_core(committed: dict[str, Any]) -> None:
    # Ties the fixture to the core: the flat curve re-solved by sg_study
    # (seconds; the sloped cells are the slow part) is the committed one.
    slope = gen.SLOPES_PCT[0]
    expected = gen.cell_curve(service_sg.sg_study(gen.cell_args(slope)), slope)
    assert committed["curves"][0] == expected


def test_fixture_holds_a_solved_curve_per_slope(committed: dict[str, Any]) -> None:
    assert [c["slope_pct"] for c in committed["curves"]] == list(gen.SLOPES_PCT)
    meta = committed["meta"]
    assert meta["profile"] == TOUR_AVERAGE.name
    assert meta["sampling"] == gen.SAMPLING
    assert meta["paces_ft"] == list(service_sg.DEFAULT_SG_PACES_FT)
    for curve in committed["curves"]:
        assert curve["distances_ft"] == list(DEFAULT_GRID_FT)
        assert set(curve["pace_ft_past"]) <= set(service_sg.DEFAULT_SG_PACES_FT)
        e = curve["expected_putts"]
        # A tap-in is one putt; a 45 ft putt costs well over one more.
        assert 1.0 <= e[0] <= 1.05
        assert e[-1] > e[0] + 0.5


def test_cell_args_are_the_tour_average_player_on_the_side_slope() -> None:
    args = gen.cell_args(2.0)
    profile = profile_from_args(args)
    assert profile.stroke == TOUR_AVERAGE.stroke
    assert profile.read == TOUR_AVERAGE.read
    assert green_from_args(args) == PlaneGreen(2.0, 90.0, gen.STIMP_FT)
    assert args["distances_ft"] == list(DEFAULT_GRID_FT)
    assert args["n"] == gen.SAMPLING["n"] and args["seed"] == gen.SAMPLING["seed"]
    assert dataclasses.asdict(TOUR_AVERAGE.stroke).items() <= args.items()


def test_curve_rounds_the_core_report() -> None:
    report = {
        "curve": {
            "distances_ft": [1.0, 2.0],
            "expected_putts": [1.000049, 1.23456789],
            "pace_ft_past": [0.5, 1.5],
        }
    }
    assert gen.cell_curve(report, 4.0) == {
        "slope_pct": 4.0,
        "distances_ft": [1.0, 2.0],
        "expected_putts": [1.0, 1.2346],
        "pace_ft_past": [0.5, 1.5],
    }


@_requires_node
def test_studio_expected_putts_is_the_core_curve(committed: dict[str, Any]) -> None:
    curve = committed["curves"][1]
    points = [0.2, 0.5, 2.7, 10.0, 12.5, 33.0, 45.0, 60.0]
    got = _node(
        f"{json.dumps(points)}.map((d) => coreExpectedPutts(window.CORE_SG.curves[1], d))"
    )
    expected = np.interp(points, curve["distances_ft"], curve["expected_putts"])
    assert got == pytest.approx(expected.tolist(), abs=1e-12)


@_requires_node
@pytest.mark.parametrize(
    ("distance", "holed", "leave"),
    [(10.0, True, 0.0), (10.0, False, 2.4), (25.0, False, 6.5)],
)
def test_studio_strokes_gained_is_the_core_score(
    committed: dict[str, Any], distance: float, holed: bool, leave: float
) -> None:
    curve = committed["curves"][2]
    report = {"distance_ft": distance, "curve": curve}
    expected = service_sg.score_putt(report, holed, leave)
    got = _node(
        f"coreStrokesGained(window.CORE_SG.curves[2], {distance}, "
        f"{json.dumps(holed)}, {leave})"
    )
    assert got == pytest.approx(expected, abs=1e-12)


@_requires_node
def test_studio_picks_the_nearest_slope() -> None:
    got = _node("[-0.4, 1.2, -2.6, 3.1, 7].map((s) => coreSgCurve(s).slope_pct)")
    assert got == [0.0, 2.0, 2.0, 4.0, 4.0]


def test_page_reads_the_core_curve() -> None:
    html = (_STUDIO / "index.html").read_text(encoding="utf-8")
    assert html.index('src="js/core_sg.js"') < html.index('src="js/green3d.js"')
    green = _js("green3d.js")
    assert "eComebackCB" not in green and "eComebackUN" not in green
    assert "coreStrokesGained(" in green
    assert "valOptPaceStrat" in green
    charts = _js("charts2d.js")
    assert "Math.exp(-d / 14.5)" not in charts and "Math.exp(-d / 9.5)" not in charts
    assert "coreExpectedPutts(" in charts
