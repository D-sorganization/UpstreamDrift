"""Core green presets in the putting studio (#14648, epic #14452).

The studio drew its own analytic green, and undulation only switched on with
slope. It now reads ``js/core_greens.js``, generated by
``scripts/generate_studio_greens.py`` from the core ``GREEN_PRESETS``: each
preset's height grid. A Green Type selector picks one; the green's centre
sits at the putt midpoint. Golden parity: the studio's height and slope at a
point are the core ``HeightField`` elevation and gradient there.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from scripts import generate_studio_greens as gen
from src.shared.python.putting_dynamics import GREEN_PRESETS

pytestmark = pytest.mark.unit

_STUDIO = Path(__file__).resolve().parents[3] / "src" / "apps" / "putting_studio"
_FIXTURE = _STUDIO / "js" / "core_greens.js"
_PHYSICS = _STUDIO / "js" / "putting_physics.js"
_NODE = shutil.which("node")
_requires_node = pytest.mark.skipif(_NODE is None, reason="node is not on PATH")
_POINTS = [(-0.4, 0.0), (0.0, 0.3), (0.9, -1.2), (1.7, 0.55), (2.6, -0.05), (4.3, 2.1)]


def _js(name: str) -> str:
    return (_STUDIO / "js" / name).read_text(encoding="utf-8")


def _node(expression: str) -> object:
    script = (
        "const window = globalThis;\n"
        + _FIXTURE.read_text(encoding="utf-8")
        + f"\nconst PuttingPhysics = require({json.dumps(str(_PHYSICS))});"
        + f"\nprocess.stdout.write(JSON.stringify({expression}));"
    )
    assert _NODE is not None
    out = subprocess.run(
        [_NODE, "-e", script], capture_output=True, text=True, check=True, timeout=30
    )
    return json.loads(out.stdout)


def test_fixture_is_the_generator_output() -> None:
    assert _FIXTURE.read_text(encoding="utf-8") == gen.render(gen.build())


def test_fixture_holds_every_core_preset_on_the_core_grid() -> None:
    data = gen.parse(_FIXTURE.read_text(encoding="utf-8"))
    assert sorted(data["presets"]) == sorted(GREEN_PRESETS)
    field = gen.core_field("tiered")
    for preset in data["presets"].values():
        assert preset["spacing_m"] == field.spacing_m
        assert preset["origin_m"] == [field.origin_m[0], -gen.HALF_WIDTH_M]


@_requires_node
@pytest.mark.parametrize("name", sorted(GREEN_PRESETS))
@pytest.mark.parametrize("dist_ft", [6.0, 25.0])
def test_studio_green_is_the_core_height_field(name: str, dist_ft: float) -> None:
    hole_x = dist_ft * 0.3048
    field = gen.core_field(name)
    js = _node(
        json.dumps(_POINTS)
        + ".map(([x, y]) => PuttingPhysics.evalGreen(x, y, "
        + f"{hole_x}, 0, 0, window.CORE_GREENS.presets[{json.dumps(name)}]))"
    )
    assert isinstance(js, list)
    for (x, y), got in zip(_POINTS, js, strict=True):
        gx, gy = x - hole_x / 2.0, y  # the green's centre is the putt midpoint
        assert got["z"] == pytest.approx(field.elevation(gx, gy), abs=1e-6)
        dzdx, dzdy = field.gradient(gx, gy)
        assert got["dz_dx"] == pytest.approx(dzdx, abs=1e-5)
        assert got["dz_dy"] == pytest.approx(dzdy, abs=1e-5)


@_requires_node
@pytest.mark.parametrize("name", sorted(GREEN_PRESETS))
def test_studio_clamps_off_the_core_grid_as_the_core_does(name: str) -> None:
    # #14703: past the core grid's ends the lookup clamps to the edge cell.
    edge = gen.EXTENT_M / 2.0
    points = [(-edge - 1.5, 0.4), (edge + 2.0, -1.1), (edge + 0.25, 2.9)]
    field = gen.core_field(name)
    js = _node(
        json.dumps(points)
        + ".map(([gx, gy]) => PuttingPhysics.coreGreenAt("
        + f"window.CORE_GREENS.presets[{json.dumps(name)}], gx, gy))"
    )
    assert isinstance(js, list)
    for (gx, gy), got in zip(points, js, strict=True):
        assert got["z"] == pytest.approx(field.elevation(gx, gy), abs=1e-6)
        dzdx, dzdy = field.gradient(gx, gy)
        assert got["dz_dx"] == pytest.approx(dzdx, abs=1e-5)
        assert got["dz_dy"] == pytest.approx(dzdy, abs=1e-5)


@_requires_node
def test_undulation_is_selectable_without_slope() -> None:
    putt = (
        "PuttingPhysics.simulateSinglePuttRK4({vClubMps: 1.4, aimDeg: 0, "
        "pathErrDeg: 0, faceErrDeg: 0, stimpFt: 10, upPct: 0, crossPct: 0, "
        "distFt: 12, roughnessMm: 0, skidTable: [[0, 0, 0], [5, 0, 5]], coreGreen: %s})"
        ".finalY"
    )
    undulating = "window.CORE_GREENS.presets.undulating_championship"
    assert _node(putt % "null") == pytest.approx(0.0, abs=1e-9)
    assert abs(float(_node(putt % undulating))) > 0.01  # type: ignore[arg-type]


def test_page_selects_a_core_green_everywhere_it_reads_one() -> None:
    html = (_STUDIO / "index.html").read_text(encoding="utf-8")
    assert 'id="greenPresetSelect"' in html
    order = re.findall(r'<script src="js/([a-z0-9_]+)\.js"', html)
    assert order.index("core_greens") < order.index("green3d")
    for name in ("green3d.js", "charts2d.js"):
        assert "evalUndulatingGreen(" not in _js(name), name
    assert _js("green3d.js").count("coreGreen: activeCoreGreen()") == 2
    assert "activeCoreGreen()" in _js("controls_c.js")
    assert 'id="greenPresetSelect"' in html
    assert "function activeCoreGreen()" in _js("state.js")


@_requires_node
@pytest.mark.parametrize("name", sorted(GREEN_PRESETS))
def test_locked_slope_is_the_core_slope_at_the_ball(name: str) -> None:
    # #14703: with a core preset the locked sliders read its slope at the ball.
    hole_x = 25.0 * 0.3048
    got = _node(
        "PuttingPhysics.coreSlopePctAtBall("
        + f"window.CORE_GREENS.presets[{json.dumps(name)}], {hole_x})"
    )
    assert isinstance(got, dict)
    dzdx, dzdy = gen.core_field(name).gradient(-hole_x / 2.0, 0.0)
    assert got["upPct"] == pytest.approx(100.0 * dzdx, abs=1e-3)
    assert got["crossPct"] == pytest.approx(100.0 * dzdy, abs=1e-3)


