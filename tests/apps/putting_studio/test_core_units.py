"""Selectable units in the putting studio (#14646, epic #14452).

The studio's distance, speed and strike labels hard-coded ft, m/s and mm. They
now go through ``js/core_units.js``, generated by
``scripts/generate_studio_units.py`` from the shared ``ui/units.py``, and
follow a Metric/Imperial selector. Golden parity: the studio's label text for
each kind and system is what the shared helpers give.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from scripts import generate_studio_units as gen
from src.shared.python.ui.units import (
    UnitSystem,
    display_unit_table,
    distance_suffix,
    from_display_distance,
    speed_suffix,
    to_display_distance,
    to_display_speed,
)

pytestmark = pytest.mark.unit

_STUDIO = Path(__file__).resolve().parents[3] / "src" / "apps" / "putting_studio"
_FIXTURE = _STUDIO / "js" / "core_units.js"
_NODE = shutil.which("node")
_FT_M = from_display_distance(1.0, UnitSystem.IMPERIAL, unit="ft")


def _expected(kind: str, value: float, digits: int, system: UnitSystem) -> str:
    """The desktop's label for a studio value in its stored unit."""
    if kind == "distance":
        shown = to_display_distance(value * _FT_M, system, unit="ft")
        return f"{shown:.{digits}f}{distance_suffix(system, unit='ft')}"
    if kind == "speed":
        return f"{to_display_speed(value, system):.{digits}f}{speed_suffix(system)}"
    shown = value if system == UnitSystem.METRIC else value / 1e3 / _FT_M * 12.0
    return f"{shown:.{digits}f}{' mm' if system == UnitSystem.METRIC else ' in'}"


def test_fixture_is_the_generator_output() -> None:
    # Freshness and golden parity together: build() reads the shared helpers.
    assert _FIXTURE.read_text(encoding="utf-8") == gen.render(gen.build())


def test_fixture_covers_both_systems_and_the_stored_kinds() -> None:
    data = gen.parse(_FIXTURE.read_text(encoding="utf-8"))
    assert set(data["systems"]) == {s.value for s in UnitSystem}
    for row in data["systems"].values():
        assert set(row) == set(gen.STORED)


CASES = [
    ("distance", 10.0, 1),
    ("distance", 45.0, 1),
    ("speed", 0.58, 2),
    ("speed", 1.35, 2),
    ("strike", 10.0, 1),
    ("strike", -6.5, 2),
]


@pytest.mark.skipif(_NODE is None, reason="node is not on PATH")
@pytest.mark.parametrize("system", list(UnitSystem))
def test_studio_labels_match_the_shared_helpers(system: UnitSystem) -> None:
    calls = ",".join(
        f"coreUnitText({json.dumps(k)}, {v}, {d}, {json.dumps(system.value)})"
        for k, v, d in CASES
    )
    script = (
        "const window = globalThis;\n"
        + _FIXTURE.read_text(encoding="utf-8")
        + f"\nprocess.stdout.write(JSON.stringify([{calls}]));"
    )
    assert _NODE is not None
    out = subprocess.run(
        [_NODE, "-e", script], capture_output=True, text=True, check=True, timeout=30
    )
    assert json.loads(out.stdout) == [_expected(k, v, d, system) for k, v, d in CASES]


def test_page_has_the_selector_and_loads_the_table() -> None:
    html = (_STUDIO / "index.html").read_text(encoding="utf-8")
    assert 'id="unitSystemSelect"' in html
    assert '<option value="imperial"' in html and '<option value="metric"' in html
    assert html.index('src="js/core_units.js"') < html.index('src="js/io.js"')


def test_labels_go_through_the_table() -> None:
    io_js = (_STUDIO / "js" / "io.js").read_text(encoding="utf-8")
    controls = (_STUDIO / "js" / "controls_c.js").read_text(encoding="utf-8")
    assert "function refreshUnitLabels" in io_js
    for kind in ("distance", "speed", "strike"):
        assert f"coreUnitText('{kind}'" in io_js
    # No label sets a hand-written unit any more.
    for text in (io_js, controls):
        assert "toFixed(1)} ft`" not in text
        assert "toFixed(2)} m/s`" not in text
        assert "toeOffsetMm.toFixed(1)} mm`" not in text
        assert "'+0.0 mm'" not in text and "'+10.0 mm'" not in text


def test_matrix_marks_studio_and_desktop_units_present() -> None:
    matrix = _STUDIO.parents[2] / "src" / "config" / "putting_parity_matrix.json"
    features = json.loads(matrix.read_text(encoding="utf-8"))["features"]
    cells = features["units"]["cells"]
    for surface in ("studio", "pyqt6", "core_api"):
        assert cells[surface].startswith("present |"), surface


def test_generator_reads_the_shared_display_table() -> None:
    # The studio rows are the API's table rescaled to the stored units.
    for system in UnitSystem:
        table = display_unit_table(system)
        row = gen.unit_row(system)
        assert row["distance"]["factor"] == pytest.approx(
            table["distance"]["factor"] * _FT_M, rel=1e-12
        )
        assert row["strike"]["factor"] == pytest.approx(
            table["small_length"]["factor"] * 1e-3, rel=1e-12
        )
        assert row["strike"]["suffix"] == table["small_length"]["suffix"]


