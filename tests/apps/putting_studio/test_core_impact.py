"""Core skid-to-roll and launch in the putting studio (#14647, epic #14452).

The studio ended the skid at a fixed share of the hole distance and did not
model launch. It now reads ``js/core_impact.js``, generated by
``scripts/generate_studio_impact.py`` from the core ``simulate_strike``: the
skid distance for each ball speed and the launch angle of the typical putter.
Golden parity: the studio's skid for a ball speed is the core's.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from scripts import generate_studio_impact as gen
from src.shared.python.putting_dynamics import PutterState, simulate_strike
from src.shared.python.putting_dynamics.surfaces import SurfaceSpec

pytestmark = pytest.mark.unit

_STUDIO = Path(__file__).resolve().parents[3] / "src" / "apps" / "putting_studio"
_FIXTURE = _STUDIO / "js" / "core_impact.js"
_PHYSICS = _STUDIO / "js" / "putting_physics.js"
_NODE = shutil.which("node")
_requires_node = pytest.mark.skipif(_NODE is None, reason="node is not on PATH")


def _core(club_mps: float) -> tuple[float, float]:
    """Ball speed and skid distance of the core typical putter at ``club_mps``."""
    result = simulate_strike(PutterState.typical(club_mps), SurfaceSpec.flat_uniform())
    assert result.collision is not None
    return result.collision.ball_speed_mps, result.skid_distance_m


def _node(expression: str) -> object:
    script = (
        "const window = globalThis;\n"
        + _FIXTURE.read_text(encoding="utf-8")
        + f"\nconst PuttingPhysics = require({json.dumps(str(_PHYSICS))});"
        + f"\nprocess.stdout.write(JSON.stringify({expression}));"
    )
    assert _NODE is not None
    out = subprocess.run(
        [_NODE, "-e", script], capture_output=True, text=True, check=True, timeout=30
    )
    return json.loads(out.stdout)


def test_fixture_is_the_generator_output() -> None:
    # Freshness and golden parity together: build() runs the core solver.
    assert _FIXTURE.read_text(encoding="utf-8") == gen.render(gen.build())


def test_fixture_rows_are_the_core_skid() -> None:
    data = gen.parse(_FIXTURE.read_text(encoding="utf-8"))
    rows = data["skid"]
    assert rows[0][:2] == [0.0, 0.0]
    speeds = [row[0] for row in rows]
    assert speeds == sorted(speeds)
    for club in (0.6, 1.4, 2.6):
        ball, skid = _core(club)
        assert [round(ball, 6), round(skid, 6)] in [row[:2] for row in rows]


def test_fixture_launch_is_the_core_launch() -> None:
    meta = gen.parse(_FIXTURE.read_text(encoding="utf-8"))["meta"]
    report = simulate_strike(
        PutterState.typical(1.5), SurfaceSpec.flat_uniform()
    ).collision
    assert report is not None
    assert meta["launch_angle_deg"] == pytest.approx(report.launch_angle_deg, abs=1e-6)
    assert meta["loft_deg"] == pytest.approx(report.effective_loft_deg, abs=1e-9)


@_requires_node
@pytest.mark.parametrize("club", [0.5, 1.1, 1.75, 2.3, 3.1])
def test_studio_skid_matches_the_core_between_rows(club: float) -> None:
    ball, skid = _core(club)
    got = _node(f"PuttingPhysics.coreSkidDistanceM(window.CORE_IMPACT.skid, {ball})")
    assert got == pytest.approx(skid, abs=2e-3)


@_requires_node
def test_putt_skids_the_core_distance_not_a_share_of_the_hole() -> None:
    # Same ball speed, putts of 8 and 30 ft: the skid no longer scales with
    # the hole distance.
    calls = ",".join(
        "PuttingPhysics.simulateSinglePuttRK4({vClubMps: 1.6, aimDeg: 0, "
        "pathErrDeg: 0, faceErrDeg: 0, stimpFt: 10, roughnessMm: 0, "
        f"distFt: {d}, skidTable: window.CORE_IMPACT.skid}})"
        for d in (8, 30)
    )
    near, far = _node(f"[{calls}].map(r => [r.v0, r.skidDist])")
    expected = _node(
        f"PuttingPhysics.coreSkidDistanceM(window.CORE_IMPACT.skid, {near[0]})"
    )
    assert near[1] == pytest.approx(expected, abs=0.02)
    assert far[1] == pytest.approx(near[1], abs=0.02)


@_requires_node
def test_a_strike_without_the_table_is_refused() -> None:
    with pytest.raises(subprocess.CalledProcessError):
        _node(
            "PuttingPhysics.simulateSinglePuttRK4({vClubMps: 1.6, aimDeg: 0, "
            "pathErrDeg: 0, faceErrDeg: 0, stimpFt: 10, distFt: 10})"
        )


def test_page_loads_the_table_and_shows_launch() -> None:
    html = (_STUDIO / "index.html").read_text(encoding="utf-8")
    assert html.index('src="js/core_impact.js"') < html.index('src="js/green3d.js"')
    green = (_STUDIO / "js" / "green3d.js").read_text(encoding="utf-8")
    assert green.count("skidTable: window.CORE_IMPACT.skid") == 3  # + speed solve
    assert "CORE_IMPACT.meta.launch_angle_deg" in green
    charts = (_STUDIO / "js" / "charts2d.js").read_text(encoding="utf-8")
    assert "0.12 * holeX" not in charts


def test_matrix_marks_the_studio_impact_model_present() -> None:
    matrix = _STUDIO.parents[2] / "src" / "config" / "putting_parity_matrix.json"
    features = json.loads(matrix.read_text(encoding="utf-8"))["features"]
    assert features["impact_model"]["cells"]["studio"].startswith("present |")
