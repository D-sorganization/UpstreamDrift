"""Core-generated strokes-gained attribution for the studio (#14459, epic #14452).

The studio's 6-channel attribution used to be hand-tuned closed-form numbers.
It now reads ``js/core_attribution.js``, generated by
``scripts/generate_studio_attribution.py`` from the shared core's
``variance_study`` for the fitted tour-average player. Golden parity: one grid
cell is recomputed here with the core and must match the committed fixture.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest

from scripts import generate_studio_attribution as gen
from src.shared.python.putting_analytics import service_variance

pytestmark = pytest.mark.unit

_STUDIO = Path(__file__).resolve().parents[3] / "src" / "apps" / "putting_studio"
_FIXTURE = _STUDIO / "js" / "core_attribution.js"
_NODE = shutil.which("node")


@pytest.fixture(scope="module")
def committed() -> dict[str, Any]:
    return gen.parse(_FIXTURE.read_text(encoding="utf-8"))


def test_fixture_covers_the_whole_grid(committed: dict[str, Any]) -> None:
    keys = {(c["distance_ft"], c["slope_pct"]) for c in committed["cells"]}
    assert keys == {(d, s) for d in gen.DISTANCES_FT for s in gen.SLOPES_PCT}
    assert committed["meta"]["profile"] == "tour-average"
    assert committed["meta"]["factors"] == list(gen.FACTORS)
    assert "strike" not in committed["meta"]["factors"]  # core channel lands in #14461


def test_fixture_is_the_rendering_of_its_own_data(committed: dict[str, Any]) -> None:
    # Freshness without a full regeneration: the file is exactly what the
    # generator writes for this data (no hand edits).
    assert gen.render(committed) == _FIXTURE.read_text(encoding="utf-8")


def test_golden_cell_matches_the_core(committed: dict[str, Any]) -> None:
    distance, slope = gen.DISTANCES_FT[0], 0.0
    report = service_variance.variance_study(gen.cell_args(distance, slope))
    expected = gen.cell_gains(report)
    cell = next(
        c
        for c in committed["cells"]
        if (c["distance_ft"], c["slope_pct"]) == (distance, slope)
    )
    assert cell["gain_removed"] == expected


def test_cell_args_use_the_tour_average_player() -> None:
    args = gen.cell_args(10.0, 2.0)
    assert args["classes"] == [
        {"distance_ft": 10.0, "slope_pct": 2.0, "orientation": "right_to_left"}
    ]
    assert gen.cell_args(10.0, 0.0)["classes"] == [{"distance_ft": 10.0}]
    assert args["face_sd_deg"] == pytest.approx(1.7234)
    assert args["factors"] == list(gen.FACTORS)


def test_gains_are_rounded_per_factor() -> None:
    report = {
        "per_round": {
            "factors": [
                {"factor": f, "gain_removed": 0.123456789, "gain_cut": 0.0}
                for f in gen.FACTORS
            ]
        }
    }
    assert gen.cell_gains(report) == dict.fromkeys(gen.FACTORS, 0.1235)


@pytest.mark.skipif(_NODE is None, reason="node is not on PATH")
def test_studio_lookup_picks_the_nearest_cell() -> None:
    script = (
        _FIXTURE.read_text(encoding="utf-8")
        + "\nconst c = coreAttributionCell(11.2, -2.6);"
        + "\nprocess.stdout.write(JSON.stringify([c.distance_ft, c.slope_pct]));"
    )
    out = subprocess.run(
        [_NODE, "-e", "const window = globalThis;\n" + script],
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
    )
    assert json.loads(out.stdout) == [10.0, 2.0]  # |slope| is used: mirror-symmetric


def test_page_loads_the_fixture_and_shows_core_channels() -> None:
    html = (_STUDIO / "index.html").read_text(encoding="utf-8")
    assert html.index('src="js/core_attribution.js"') < html.index(
        'src="js/green3d.js"'
    )
    for element_id in (
        "chLossFace",
        "chLossPath",
        "chLossSpeed",
        "chLossReadGrade",
        "chLossReadAspect",
        "chLossReadStimp",
        "valCoreAttributionNote",
    ):
        assert f'id="{element_id}"' in html
    # Studio-only rows stay (ADR-0045) but are labelled as not from the core.
    for element_id in ("chGainCT", "chLossSpot", "chLossRough"):
        assert f'id="{element_id}"' in html
    assert "Illustrative (studio model, not core)" in html
