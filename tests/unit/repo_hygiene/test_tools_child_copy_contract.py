_HEADER = "# WARNING: DO NOT EDIT THIS FILE DIRECTLY."

# Files that carry the child-copy header but have no counterpart in the pinned
# Tools tree. This is a *shrink-only* backlog, not an allowlist: a file not
# listed here fails immediately, and a listed file that gains a counterpart
# must be removed from the list (see the two assertions in
# test_tools_child_copy_headers_have_tools_counterparts).
#
# It replaces a four-path opt-in allowlist that validated 3 of 146 headered
# files and so missed ai/tools/sidekick_analytics.py entirely -- headered,
# frozen against editing here, and absent from Tools, leaving its defect
# unfixable in either repo (UpstreamDrift#9474).
#
# Entries are retired by the seam cleanup epic UpstreamDrift#9406.
_MISSING_COUNTERPART_WAIVERS = (
    _REPO_ROOT
    / "tests"
    / "unit"
    / "repo_hygiene"
    / "tools_child_copy_missing_counterparts.txt"
)


def _pinned_vendor_revision() -> str | None:
    """Return the exact Tools gitlink revision recorded by the superproject."""
    result = _run_git("ls-tree", "HEAD", "--", "vendor/ud-tools")
    if result is None or result.returncode != 0:
        return None
    fields = result.stdout.strip().split(maxsplit=3)
    if (
        len(fields) != 4
        or fields[0] != "160000"
        or fields[1] != "commit"
        or fields[3] != "vendor/ud-tools"
    ):
        return None
    return fields[2]


def _candidate_tools_repos() -> list[tuple[Path, str]]:
    candidates: list[tuple[Path, str]] = []
    vendor_repo = _REPO_ROOT / "vendor" / "ud-tools"
    pinned_revision = _pinned_vendor_revision()
    if (vendor_repo / ".git").exists() and pinned_revision is not None:
        candidates.append((vendor_repo, pinned_revision))
    return candidates


def _tools_shared_paths() -> set[str] | None:
    git_bin = shutil.which("git")
    if git_bin is None:
        return None
    for repo, ref in _candidate_tools_repos():
        result = subprocess.run(  # nosec B603 - fixed args, no shell
            [
                git_bin,
                "-C",
                str(repo),
                "ls-tree",
                "-r",
                "--name-only",
                ref,
                "src/shared/python",
            ],
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=30,
        )
        if result.returncode != 0:
            continue
        prefix = "src/shared/python/"
        paths = {
            line.removeprefix(prefix)
            for line in result.stdout.splitlines()
            if line.startswith(prefix)
        }
        if paths:
            return paths
    return None


def _require_tools_shared_paths(tools_paths: set[str] | None) -> set[str]:
    """Return an authoritative Tools inventory or fail closed unless opted out."""
    if tools_paths is not None:
        return tools_paths
    msg = missing_vendor_instructions(_REPO_ROOT / "vendor" / "ud-tools")
    if os.environ.get("CI") or not seam_tests_allow_skip():
        raise AssertionError(
            f"An authoritative Tools path inventory is required for child-copy "
            f"ownership enforcement (issue #9501).\n{msg}"
        )
    pytest.skip("Tools checkout is unavailable for child-copy counterpart check")


def _is_tools_child_copy(path: Path) -> bool:
    try:
        first_line = path.read_text(encoding="utf-8").splitlines()[0]
    except (IndexError, OSError, UnicodeDecodeError):
        return False
    return first_line == _HEADER


def _run_git(*args: str) -> subprocess.CompletedProcess[str] | None:
    """Run a read-only Git command from the repository root."""
    git_bin = shutil.which("git")
    if git_bin is None:
        return None
    return subprocess.run(  # nosec B603 - fixed executable, no shell
        [git_bin, *args],
        cwd=str(_REPO_ROOT),
        check=False,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=30,
    )


def _merge_base_with_main() -> str | None:
    """Return a comparison base available in full or shallow PR checkouts."""
    result = _run_git("merge-base", "HEAD", "origin/main")
    if result is not None and result.returncode == 0:
        merge_base = result.stdout.strip()
        if merge_base:
            return merge_base

    # A depth-1 PR checkout can contain the fetched base tree while Git still
    # treats the synthetic merge commit as a shallow boundary. A direct base
    # comparison is conservative (it may inspect extra paths) and keeps the
    # ownership check fail-closed without requiring full repository history.
    result = _run_git("rev-parse", "--verify", "origin/main")
    if result is None or result.returncode != 0:
        return None
    return "origin/main"


def _changed_shared_python_paths(base: str) -> list[Path]:
    """Return non-deleted shared Python paths changed since ``base``."""
    result = _run_git(
        "diff",
        "--name-only",
        "--diff-filter=ACMRT",
        f"{base}..HEAD",
        "--",
        "src/shared/python",
    )
    assert result is not None and result.returncode == 0, (
        "Unable to inspect shared-file changes for child-copy enforcement"
    )
    prefix = "src/shared/python/"
    return [
        Path(line.removeprefix(prefix))
        for line in result.stdout.splitlines()
        if line.startswith(prefix) and line.endswith(".py")
    ]


def _base_revision_is_tools_child_copy(base: str, relative: Path) -> bool:
    """Return whether ``relative`` carried the child-copy header at ``base``."""
    source_path = f"src/shared/python/{relative.as_posix()}"
    result = _run_git("show", f"{base}:{source_path}")
    if result is None or result.returncode != 0:
        return False
    first_line = result.stdout.partition("\n")[0]
    return first_line == _HEADER


# UpstreamDrift#9474: a child copy may be edited to *converge* on canonical Tools,
# never to diverge from it. The two trees differ only by the documented seam
# rewrites -- UpstreamDrift spells shared imports ``src.shared.python`` and its
# copies may carry the DO-NOT-EDIT banner -- so normalising both sides for those
# two differences turns "is this edit pure convergence?" into an exact string
# test. Anything else (a UpstreamDrift-only tweak, a partial port, a stale copy)
# still fails, so the guard keeps forbidding drift while allowing a fix that
# already landed in Tools to reach the copy that actually runs.
_SEAM_IMPORT_PREFIX = re.compile(r"(?m)^(\s*)from src\.shared\.python\.")

# UpstreamDrift#9406: some clusters are ruled `ud-canonical` -- UpstreamDrift
# authored them and Tools carries the stale copy. The seam rulings say so
# explicitly ("Upstream first, then delete here"), so an edit under one of those
# is the *expected* way to make progress, not drift.
#
# Without this the guard is inverted for exactly the packages that need work
# most: `model_generation` and `humanoid_character_builder` are both
# `ud-canonical` and both appear in the pinned Tools tree, so any fix to them was
# reported as a forbidden child-copy edit -- while the failing tests those fixes
# address sit in UpstreamDrift's own suite. Tools-owned clusters are unaffected.
_SEAM_RULINGS = _REPO_ROOT / "docs" / "shared_tools" / "seam_rulings.v1.json"


def _ud_canonical_entries() -> frozenset[str]:
    """Return the top-level shared entries UpstreamDrift is ruled to own."""
    if not _SEAM_RULINGS.is_file():
        return frozenset()
    rulings = json.loads(_SEAM_RULINGS.read_text(encoding="utf-8")).get("rulings", {})
    return frozenset(
        name for name, entry in rulings.items() if entry.get("ruling") == "ud-canonical"
    )


def _is_ud_canonical(relative: Path) -> bool:
    """Return whether ``relative`` falls under a ud-canonical ruling."""
    parts = relative.as_posix().split("/")
    candidate = parts[0] if len(parts) > 1 else relative.as_posix()
    return candidate in _ud_canonical_entries()


def _normalise_seam_imports(text: str) -> str:
    """Rewrite UpstreamDrift's ``src.shared.python`` spelling to canonical."""
    return _SEAM_IMPORT_PREFIX.sub(r"\1from shared.python.", text)


def _strip_child_copy_header(text: str) -> str:
    """Drop the leading DO-NOT-EDIT banner, which canonical Tools never carries."""
    lines = text.split("\n")
    if not lines or not lines[0].startswith(_HEADER):
        return text
    index = 0
    while index < len(lines) and lines[index].startswith("#"):
        index += 1
    while index < len(lines) and not lines[index].strip():
        index += 1
    return "\n".join(lines[index:])


def _canonical_child_copy_text(relative: Path) -> str | None:
    """Return the pinned Tools text for ``relative``, or ``None`` if absent."""
    for repo, ref in _candidate_tools_repos():
        result = _run_git(
            "-C",
            str(repo),
            "show",
            f"{ref}:src/shared/python/{relative.as_posix()}",
        )
        if result is not None and result.returncode == 0:
            return result.stdout
    return None


def _converges_on_canonical(relative: Path) -> bool:
    """Return True when the local copy equals pinned Tools modulo seam rewrites."""
    canonical = _canonical_child_copy_text(relative)
    if canonical is None:
        return False
    local_path = _SHARED_ROOT / relative
    if not local_path.is_file():
        return False
    local = local_path.read_text(encoding="utf-8")
    normalised_local = _normalise_seam_imports(_strip_child_copy_header(local))
    return normalised_local == _normalise_seam_imports(canonical)


def _direct_tools_edit_offenders(
    base: str,
    tools_paths: set[str],
) -> list[str]:
    """Return changed Python paths owned by Tools or marked as child copies."""
    return [
        relative.as_posix()
        for relative in _changed_shared_python_paths(base)
        if (
            relative.as_posix() in tools_paths
            or _base_revision_is_tools_child_copy(base, relative)
            or _is_tools_child_copy(_SHARED_ROOT / relative)
        )
        and not _converges_on_canonical(relative)
        and not _is_ud_canonical(relative)
    ]


def _local_only_chat_sidekick_paths(tools_paths: set[str]) -> set[str]:
    """Return every local Chat/Sidekick Python path absent from pinned Tools."""
    return {
        path.relative_to(_SHARED_ROOT).as_posix()
        for scope in ("chat", "sidekick")
        for path in sorted((_SHARED_ROOT / scope).rglob("*.py"))
        if path.relative_to(_SHARED_ROOT).as_posix() not in tools_paths
    }


def _load_waived_missing_counterparts() -> list[str]:
    """Return the recorded backlog of headered files lacking counterparts."""
    if not _MISSING_COUNTERPART_WAIVERS.is_file():
        return []
    return [
        line.strip()
        for line in _MISSING_COUNTERPART_WAIVERS.read_text(
            encoding="utf-8"
        ).splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def _headered_paths_missing_counterparts(
    shared_root: Path,
    tools_paths: set[str],
) -> list[str]:
    """Return every headered file under ``shared_root`` absent from Tools.

    The scan is deliberately unscoped: the header is the claim of Tools
    ownership, so carrying it is the only condition for being checked. Any
    opt-in scoping here re-opens the hole this function was written to close,
    because a file the list does not know about is a file the guard cannot
    see.
    """
    missing: list[str] = []
    for path in sorted(shared_root.rglob("*.py")):
        if not _is_tools_child_copy(path):
            continue
        relative = path.relative_to(shared_root).as_posix()
        if relative not in tools_paths:
            missing.append(relative)
    return missing


def test_tools_child_copy_headers_have_tools_counterparts() -> None:
    """Every headered file must map to a Tools file, or be a known waiver."""
    tools_paths = _require_tools_shared_paths(_tools_shared_paths())

    missing = set(_headered_paths_missing_counterparts(_SHARED_ROOT, tools_paths))
    waived = set(_load_waived_missing_counterparts())

    unwaived = sorted(missing - waived)
    assert not unwaived, (
        "Shared Python files with the Tools child-copy header must have a "
        "same-relative-path counterpart in Tools. Move canonical code to Tools "
        "before marking it as a synchronized child copy.\n\n"
        "Missing counterparts:\n  " + "\n  ".join(unwaived)
    )

    # The backlog may only shrink. A waiver whose file now has a counterpart
    # is stale, and a stale waiver is how an allowlist rots back into the hole
    # this guard is closing.
    stale = sorted(waived - missing)
    assert not stale, (
        "These paths are recorded as missing a Tools counterpart but now have "
        f"one. Remove them from {_MISSING_COUNTERPART_WAIVERS.name}; the "
        "backlog is shrink-only.\n\n"
        "Stale waivers:\n  " + "\n  ".join(stale)
    )


def test_current_branch_does_not_edit_tools_child_copies() -> None:
    """PRs must change canonical Tools source, not existing UD child copies."""
    base = _merge_base_with_main()
    if base is None:
        assert not os.environ.get("CI"), (
            "origin/main is required in CI for child-copy diff enforcement"
        )
        pytest.skip("origin/main is unavailable for child-copy diff enforcement")

    tools_paths = _require_tools_shared_paths(_tools_shared_paths())
    offenders = _direct_tools_edit_offenders(base, tools_paths)

    assert not offenders, (
        "This branch directly modifies Tools-owned child copies in "
        "UpstreamDrift. Make each change in D-sorganization/Tools, merge or "
        "pin that canonical revision, and update only vendor/ud-tools here. "
        "Deleting a migrated child copy remains allowed.\n\n"
        "Direct child-copy edits:\n  " + "\n  ".join(offenders)
    )


