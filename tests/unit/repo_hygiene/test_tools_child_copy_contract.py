    """A sibling checkout may differ from the Tools gitlink consumed by UD."""
    repo_root = tmp_path / "UpstreamDrift"
    (tmp_path / "Tools" / ".git").mkdir(parents=True)
    module = sys.modules[__name__]
    monkeypatch.setattr(module, "_REPO_ROOT", repo_root)
    monkeypatch.setattr(module, "_pinned_vendor_revision", lambda: "a" * 40)

    assert _candidate_tools_repos() == []


