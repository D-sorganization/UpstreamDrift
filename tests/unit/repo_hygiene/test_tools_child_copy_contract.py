def test_no_counterpart_files_have_file_level_ownership_manifest() -> None:
    """Ambiguous child files must never exist without an explicit owner record."""
    assert _OWNERSHIP_MANIFEST.is_file()
    raw = yaml.safe_load(_OWNERSHIP_MANIFEST.read_text(encoding="utf-8")) or {}
    assert raw.get("schema_version") == 1
    entries = raw.get("paths")
    assert isinstance(entries, dict) and entries

    for relative_text, metadata in entries.items():
        assert isinstance(relative_text, str) and relative_text.endswith(".py")
        assert isinstance(metadata, dict)
        assert metadata.get("owner") in {"UpstreamDrift", "Unresolved"}
        rationale = metadata.get("rationale")
        assert isinstance(rationale, str) and rationale.strip()
        issue = metadata.get("tracking_issue")
        assert isinstance(issue, int) and issue > 0
        review_date = metadata.get("review_date")
        assert isinstance(review_date, str)
        assert date.fromisoformat(review_date) >= date.today()

    tools_paths = _require_tools_shared_paths(_tools_shared_paths())
    ambiguous_paths = _local_only_chat_sidekick_paths(tools_paths)

    assert set(entries) == ambiguous_paths
    assert not (set(entries) & tools_paths)


_CANONICAL_FIXTURE = "from shared.python.ai.types import ExpertiseLevel\n\nVALUE = 1\n"
_CHILD_COPY_FIXTURE = (
    f"{_HEADER}\n"
    "# This file is a child copy that shadows Tools.\n"
    "\n"
    "from src.shared.python.ai.types import ExpertiseLevel\n"
    "\n"
    "VALUE = 1\n"
)


def _stage_child_copy(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    *,
    local: str,
    canonical: str | None,
) -> Path:
    """Point the convergence check at a throwaway shared tree."""
    relative = Path("ai/demo.py")
    shared_root = tmp_path / "shared" / "python"
    (shared_root / relative.parent).mkdir(parents=True, exist_ok=True)
    (shared_root / relative).write_text(local, encoding="utf-8")
    monkeypatch.setattr(sys.modules[__name__], "_SHARED_ROOT", shared_root)
    monkeypatch.setattr(
        sys.modules[__name__],
        "_canonical_child_copy_text",
        lambda _relative: canonical,
    )
    return relative


def test_convergence_exemption_accepts_an_exact_port_of_canonical(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A copy equal to Tools modulo header and import prefix is not an offender."""
    relative = _stage_child_copy(
        tmp_path,
        monkeypatch,
        local=_CHILD_COPY_FIXTURE,
        canonical=_CANONICAL_FIXTURE,
    )

    assert _converges_on_canonical(relative) is True


def test_convergence_exemption_rejects_any_divergence(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """One changed character is still a direct child-copy edit.

    This is the assertion that keeps the exemption honest: it may only be used
    to carry a Tools fix into the copy verbatim, never to smuggle an
    UpstreamDrift-only change past the guard.
    """
    relative = _stage_child_copy(
        tmp_path,
        monkeypatch,
        local=_CHILD_COPY_FIXTURE.replace("VALUE = 1", "VALUE = 2"),
        canonical=_CANONICAL_FIXTURE,
    )

    assert _converges_on_canonical(relative) is False


def test_convergence_exemption_rejects_a_copy_with_no_counterpart(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """With nothing canonical to converge on, the edit stays forbidden."""
    relative = _stage_child_copy(
        tmp_path,
        monkeypatch,
        local=_CHILD_COPY_FIXTURE,
        canonical=None,
    )

    assert _converges_on_canonical(relative) is False


def test_ud_canonical_clusters_may_be_edited_here() -> None:
    """A cluster UpstreamDrift is ruled to own is not a forbidden child copy.

    `model_generation` and `humanoid_character_builder` are both ruled
    `ud-canonical` -- "UD authored it ... Upstream first, then delete here" --
    and both appear in the pinned Tools tree. Before this exemption the guard
    reported any fix to them as a direct child-copy edit, which left the two
    largest failing test clusters in the repository unfixable from either side
    (UpstreamDrift#9406).
    """
    ud_canonical = _ud_canonical_entries()

    assert ud_canonical, (
        "the rulings file should record at least one ud-canonical entry"
    )
    assert _is_ud_canonical(Path("model_generation/editor/editor_modifications.py"))
    assert _is_ud_canonical(Path("humanoid_character_builder/__init__.py"))


def test_tools_canonical_clusters_are_still_guarded() -> None:
    """The exemption is scoped to the ruling; Tools-owned clusters stay frozen."""
    rulings = json.loads(_SEAM_RULINGS.read_text(encoding="utf-8"))["rulings"]
    tools_owned = [
        name
        for name, entry in rulings.items()
        if entry.get("ruling") == "tools-canonical"
    ]

    assert tools_owned, "fixture assumption: some clusters are Tools-owned"
    for name in tools_owned:
        assert not _is_ud_canonical(Path(name) / "anything.py"), (
            f"{name} is tools-canonical and must stay guarded"
        )
