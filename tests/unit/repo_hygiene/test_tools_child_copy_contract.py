def test_missing_tools_inventory_fails_closed_in_ci(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """CI cannot waive ownership merely because the pinned inventory is missing."""
    monkeypatch.setenv("CI", "true")

    with pytest.raises(AssertionError, match="authoritative Tools path inventory"):
        _require_tools_shared_paths(None)


def test_missing_tools_inventory_skips_only_outside_ci(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A developer without any Tools source receives an explicit local skip."""
    monkeypatch.delenv("CI", raising=False)

    with pytest.raises(pytest.skip.Exception, match="Tools checkout is unavailable"):
        _require_tools_shared_paths(None)


def test_no_counterpart_files_have_file_level_ownership_manifest() -> None:
    """Ambiguous child files must never exist without an explicit owner record."""
    assert _OWNERSHIP_MANIFEST.is_file()
    raw = yaml.safe_load(_OWNERSHIP_MANIFEST.read_text(encoding="utf-8")) or {}
    assert raw.get("schema_version") == 1
    entries = raw.get("paths")
    assert isinstance(entries, dict) and entries

    for relative_text, metadata in entries.items():
        assert isinstance(relative_text, str) and relative_text.endswith(".py")
        assert isinstance(metadata, dict)
        assert metadata.get("owner") in {"UpstreamDrift", "Unresolved"}
        rationale = metadata.get("rationale")
        assert isinstance(rationale, str) and rationale.strip()
        issue = metadata.get("tracking_issue")
        assert isinstance(issue, int) and issue > 0
        review_date = metadata.get("review_date")
        assert isinstance(review_date, str)
        assert date.fromisoformat(review_date) >= date.today()

    tools_paths = _require_tools_shared_paths(_tools_shared_paths())
    ambiguous_paths = _local_only_chat_sidekick_paths(tools_paths)

    assert set(entries) == ambiguous_paths
    assert not (set(entries) & tools_paths)
