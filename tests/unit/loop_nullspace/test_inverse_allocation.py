# ---------------------------------------------------------- bootstrap
def test_block_bootstrap_is_seeded_and_brackets_the_truth() -> None:
    frames, _ = _trajectory(12, cap=1.0e3)
    tau = _generate(frames, {"effort": 0.7, "rate": 2.5})
    prob = _problem(frames, tau)
    one = block_bootstrap_log_ratio(
        prob, "rate", "effort", resamples=50, block=3, seed=7
    )
    two = block_bootstrap_log_ratio(
        prob, "rate", "effort", resamples=50, block=3, seed=7
    )
    assert one == two
    lo, hi = one
    assert lo <= np.log10(2.5 / 0.7) + 1e-3 <= hi + 1e-3


# -------------------------------------------------------- preconditions
@pytest.mark.parametrize("bad", ["shape", "nan", "scale", "times"])
def test_preconditions_raise_value_error(bad: str) -> None:
    frames, _ = _trajectory(4, cap=1.0e3)
    tau = _generate(frames, {"effort": 1.0, "rate": 1.0})
    kw = {
        "feasible_sets": tuple(frames),
        "times_s": _times(4),
        "torque_scale": SCALE,
        "observed_torque": tau,
    }
    if bad == "shape":
        kw["observed_torque"] = tau[:, :3]
    elif bad == "nan":
        kw["observed_torque"] = np.where(tau > 0, np.nan, tau)
    elif bad == "scale":
        kw["torque_scale"] = -SCALE
    else:
        kw["times_s"] = _times(3)
    with pytest.raises(ValueError):
        InverseProblem(**kw)


def test_reference_weight_requires_reference_for_replay() -> None:
    frames, _ = _trajectory(4, cap=1.0e3)
    tau = _generate(frames, {"effort": 1.0, "rate": 1.0})
    with pytest.raises(ValueError, match="reference"):
        replay_allocation(_problem(frames, tau), {"effort": 1.0, "reference": 1.0})
    with pytest.raises(TypeError):
        fit_allocation_weights("not a problem")  # type: ignore[arg-type]


def test_problem_is_immutable() -> None:
    frames, _ = _trajectory(3, cap=1.0e3)
    tau = _generate(frames, {"effort": 1.0, "rate": 1.0})
    prob = _problem(frames, tau)
    with pytest.raises(dataclasses.FrozenInstanceError):
        prob.times_s = prob.times_s  # type: ignore[misc]
