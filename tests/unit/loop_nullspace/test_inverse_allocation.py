"""Tests for inverse optimal control of the allocation weights (NSX-71, #12589).

Data are generated by the NSX-23 allocator itself with *known* weights on the
planar golfer fixture; the inverse fit must recover the weights up to the
objective's positive-scale invariance.  Oracles are independent of the module
under test: finite differences of an objective written here, and the known
generating weights.
"""

