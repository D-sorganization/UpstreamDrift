def test_compute_cache_key_sensitivity() -> None:
    """Cache key is identical for same inputs and changes on preset, registry_version, or engine change."""
    trajectory = default_fixture_trajectory()
    k1 = compute_cache_key(
        trajectory,
        engine="pinocchio",
        preset="capacity_min_effort",
        options={"registry_version": "1.0.0"},
    )
    k2 = compute_cache_key(
        trajectory,
        engine="pinocchio",
        preset="capacity_min_effort",
        options={"registry_version": "1.0.0"},
    )
    k_preset = compute_cache_key(
        trajectory,
        engine="pinocchio",
        preset="smooth_capacity",
        options={"registry_version": "1.0.0"},
    )
    k_reg = compute_cache_key(
        trajectory,
        engine="pinocchio",
        preset="capacity_min_effort",
        options={"registry_version": "2.0.0"},
    )
    assert k1 == k2
    assert len(k1) == 64
    assert k1 != k_preset
    assert k1 != k_reg


def test_service_caching_and_mocked_facade_delegation() -> None:
    """LoopNullspaceService caches by compute_cache_key and delegates math to facade."""
    calls: list[dict[str, Any]] = []

    def spy_analyze(
        trajectory: Any,
        engine: str = "pinocchio",
        preset: str = "capacity_min_effort",
        options: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        calls.append({"engine": engine, "preset": preset, "options": options})
        return analyze(trajectory, engine=engine, preset=preset, options=options)

    service = LoopNullspaceService(analyzer=spy_analyze)
    req = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "capacity_min_effort",
        "options": {"registry_version": "1.0.0"},
    }
    res1 = service.run(req)
    res2 = service.run(req)
    assert len(calls) == 1
    assert res1["compute_cache_key"] == res2["compute_cache_key"]
    assert service.cache_stats()["hits"] == 1

    # Changing registry_version or preset triggers a cache miss
    req_v2 = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "capacity_min_effort",
        "options": {"registry_version": "1.1.0"},
    }
    res3 = service.run(req_v2)
    assert len(calls) == 2
    assert res3["compute_cache_key"] != res1["compute_cache_key"]

    req_preset = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "envelope_only",
        "options": {"registry_version": "1.0.0"},
    }
    res4 = service.run(req_preset)
    assert len(calls) == 3
    assert res4["compute_cache_key"] != res1["compute_cache_key"]


def test_service_partial_invariants_and_job_lifecycle() -> None:
    """Jobs expose partial invariants first while in progress, then settle to completed or cancelled."""
    service = LoopNullspaceService()
    req = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "capacity_min_effort",
        "options": {"defer_completion": True},
    }
    job_id = service.create_job(req)
    status_mid = service.get_job(job_id)
    assert status_mid["job_id"] == job_id
    assert status_mid["status"] == "running"
    assert status_mid["partial_invariants"] is not None
    assert "bare_club_net_wrench" in status_mid["partial_invariants"]
    assert status_mid["report"] is None

    # Cancel the running job
    cancelled = service.cancel_job(job_id)
    assert cancelled["status"] == "cancelled"
    assert service.get_job(job_id)["status"] == "cancelled"


def test_fastapi_routes_create_poll_and_delete_jobs() -> None:
    """FastAPI routes POST, GET, and DELETE /analysis/loop-nullspace/jobs work end-to-end."""
    app = FastAPI()
    service = LoopNullspaceService()
    app.dependency_overrides[get_loop_nullspace_service] = lambda: service
    app.include_router(router)
    client = TestClient(app)

    payload = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "capacity_min_effort",
        "options": {"include_restriction_sensitivity": True},
    }
    post_resp = client.post("/analysis/loop-nullspace/jobs", json=payload)
    assert post_resp.status_code == 202
    data = post_resp.json()
    job_id = data["job_id"]
    assert data["status"] in ("running", "completed")

    get_resp = client.get(f"/analysis/loop-nullspace/jobs/{job_id}")
    assert get_resp.status_code == 200
    polled = get_resp.json()
    assert polled["status"] == "completed"
    assert polled["cache_hit"] is False
    assert polled["report"]["preset"] == "capacity_min_effort"
    jsonschema.validate(instance=polled["report"], schema=_load_schema())

    # Second identical job hits the result cache
    post_resp2 = client.post("/analysis/loop-nullspace/jobs", json=payload)
    assert post_resp2.status_code == 202
    job_id_2 = post_resp2.json()["job_id"]
    polled_2 = client.get(f"/analysis/loop-nullspace/jobs/{job_id_2}").json()
    assert polled_2["status"] == "completed"
    assert polled_2["cache_hit"] is True
    assert (
        polled_2["report"]["compute_cache_key"] == polled["report"]["compute_cache_key"]
    )

    # Create a deferred job to test DELETE cancellation
    deferred_payload = {
        "trajectory": default_fixture_trajectory(),
        "engine": "pinocchio",
        "preset": "smooth_capacity",
        "options": {"defer_completion": True},
    }
    post_def = client.post("/analysis/loop-nullspace/jobs", json=deferred_payload)
    def_id = post_def.json()["job_id"]
    mid_poll = client.get(f"/analysis/loop-nullspace/jobs/{def_id}").json()
    assert mid_poll["status"] == "running"
    assert "bare_club_net_wrench" in mid_poll["partial_invariants"]

    del_resp = client.delete(f"/analysis/loop-nullspace/jobs/{def_id}")
    assert del_resp.status_code == 200
    assert del_resp.json()["status"] == "cancelled"


