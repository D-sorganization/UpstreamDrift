def test_facade_analyze_validates_against_schema_v1() -> None:
    """Fixture report generated by facade.analyze validates against loop-nullspace-report-v1.json."""
    schema = _load_schema()
    trajectory = default_fixture_trajectory()
    report = analyze(
        trajectory,
        engine="pinocchio",
        preset="capacity_min_effort",
        options={"include_restriction_sensitivity": True},
    )
    assert isinstance(report, dict)
    jsonschema.validate(instance=report, schema=schema)

    typed_report = NSXAnalysisReport.from_dict(report)
    assert typed_report.compute_cache_key == report["compute_cache_key"]
    assert typed_report.preset == "capacity_min_effort"
    assert typed_report.engine == "pinocchio"
    assert typed_report.to_dict() == report


