def test_display_decision_table(
    allocation_dependence: str,
    surface: Any,
    gate_status: str,
    calibration_qualified: bool,
    preset_name: str | None,
    hypotheses: tuple[str, ...],
    expected_allowed: bool,
    expected_mode: str,
    expected_underlay: bool,
) -> None:
    """Decision table test covering every axis combination x surface and fail-closed defaults."""
    record = {
        "quantity_id": "test_quantity",
        "allocation_dependence": allocation_dependence,
        "gate_status": gate_status,
        "reason": "gate residual exceeded threshold" if gate_status != "PASS" else None,
        "hypotheses": list(hypotheses),
        "conventions": ["C-FRAME-GRIP"],
        "model_provenance": {
            "engine": "pinocchio",
            "spec_sha256": "a" * 64,
            "inertial_source": "full_body_spec_anthro_driver",
            "bare_club_partition_id": "bare_club_0.313kg",
            "kkt_regularization": 0.0,
        },
    }
    decision = display_decision(
        record,
        surface,
        calibration_qualified=calibration_qualified,
        preset_name=preset_name,
    )
    assert isinstance(decision, DisplayDecision)
    assert decision.allowed is expected_allowed
    assert decision.render_mode == expected_mode
    assert decision.requires_band_underlay is expected_underlay
    if expected_mode == "INVARIANT_LINE_WITH_BADGE":
        assert "MODEL_CONDITIONED_INVARIANT" in decision.badge_text
        assert "pinocchio" in decision.badge_text
    if expected_mode == "UNAVAILABLE_REASON":
        assert decision.reason != ""


