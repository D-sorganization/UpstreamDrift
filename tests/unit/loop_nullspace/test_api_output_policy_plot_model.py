def test_build_plot_model_matches_golden_fixture() -> None:
    """build_plot_model produces the exact cross-UI golden_plot_model_v1.json fixture."""
    report = analyze(
        default_fixture_trajectory(),
        engine="pinocchio",
        preset="capacity_min_effort",
        options={"include_restriction_sensitivity": True},
    )
    model = build_plot_model(report, preset_name="capacity_min_effort")
    assert isinstance(model, NSXPlotModel)

    model_dict = model.to_dict()
    rebuilt = NSXPlotModel.from_dict(model_dict)
    assert rebuilt.to_dict() == model_dict

    # 5 required panels
    assert set(model.panels.keys()) == {
        "invariants",
        "envelopes",
        "hand_split",
        "allocation_representative",
        "diagnostics",
    }

    # Check segment display classes and binding hypotheses from active duals
    env_panel = model.panels["envelopes"]
    assert len(env_panel.envelope_series) >= 1
    first_env = env_panel.envelope_series[0]
    classes = {seg.display_class for seg in first_env.segments}
    assert classes <= {"DETERMINED_SIGN", "INDETERMINATE", "UNBOUNDED"}
    assert "INDETERMINATE" in classes
    assert "DETERMINED_SIGN" in classes
    assert any(len(seg.binding_hypotheses) > 0 for seg in first_env.segments)
    for seg in first_env.segments:
        for hyp in seg.binding_hypotheses:
            assert hyp.startswith("H-")

    # Golden JSON parity check
    assert GOLDEN_PLOT_PATH.is_file()
    golden = json.loads(GOLDEN_PLOT_PATH.read_text(encoding="utf-8"))
    assert model_dict == golden


def test_build_plot_model_forbids_standalone_representative_without_band() -> None:
    """DbC precondition: requesting an allocation representative without its envelope band raises ValueError."""
    report = analyze(
        default_fixture_trajectory(),
        engine="pinocchio",
        preset="capacity_min_effort",
    )
    # Remove a matching envelope band while keeping its representative in allocation
    corrupted = dict(report)
    corrupted["envelopes"] = {}
    with pytest.raises(ValueError, match="without its corresponding envelope band"):
        build_plot_model(corrupted, preset_name="capacity_min_effort")
