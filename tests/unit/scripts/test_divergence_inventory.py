def _write(path: Path, text: str | bytes) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(text, bytes):
        path.write_bytes(text)
    else:
        path.write_text(text, encoding="utf-8", newline="\n")
    return path


@pytest.fixture
def fake_repo(tmp_path: Path) -> Path:
    ud = tmp_path / inv.DEFAULT_UD_ROOT
    tools = tmp_path / inv.DEFAULT_TOOLS_ROOT
    # identical (byte-for-byte)
    _write(ud / "theme/__init__.py", "x = 1\n")
    _write(tools / "theme/__init__.py", "x = 1\n")
    # identical modulo header + CRLF
    _write(
        ud / "theme/colors.py",
        b"# WARNING: DO NOT EDIT THIS FILE DIRECTLY.\r\n# copied from Tools\r\ny = 2\r\n",
    )
    _write(tools / "theme/colors.py", "y = 2\n")
    # diverged
    _write(ud / "ai/gui/panel.py", "def f():\n    return 1\n")
    _write(tools / "ai/gui/panel.py", "def f():\n    return 2\n")
    # ud-only / tools-only
    _write(ud / "movement_optimizer/core.py", "z = 3\n")
    _write(tools / "swing_sim/model.py", "w = 4\n")
    _write(tools / "safe_eval.py", "s = 5\n")
    # ignored noise
    _write(ud / "theme/__pycache__/colors.cpython-311.pyc", b"\x00")
    return tmp_path


def test_normalise_strips_header_and_line_endings() -> None:
    a = b"# WARNING: DO NOT EDIT THIS FILE DIRECTLY.\r\n# more\r\nimport os \r\n\r\n"
    assert inv.normalise(a) == b"import os"
    assert inv.normalise(b"import os\n") == b"import os"


def test_classification(fake_repo: Path) -> None:
    inventory = inv.build_inventory(fake_repo, with_authorship=False)
    by_path = {record.path: record for record in inventory.files}
    assert by_path["theme/__init__.py"].classification == "identical"
    assert by_path["theme/__init__.py"].byte_identical is True
    assert by_path["theme/colors.py"].classification == "identical"
    assert by_path["theme/colors.py"].byte_identical is False
    assert by_path["theme/colors.py"].ud_has_child_copy_header is True
    assert by_path["ai/gui/panel.py"].classification == "diverged"
    assert by_path["ai/gui/panel.py"].package == "ai"
    assert by_path["ai/gui/panel.py"].subpackage == "gui"
    assert by_path["movement_optimizer/core.py"].classification == "ud-only"
    assert by_path["swing_sim/model.py"].classification == "tools-only"
    assert by_path["safe_eval.py"].package == "safe_eval.py"
    assert by_path["safe_eval.py"].subpackage == ""
    assert not any("__pycache__" in path for path in by_path)
    assert inventory.counts == {
        "identical": 2,
        "diverged": 1,
        "ud-only": 1,
        "tools-only": 2,
    }


def test_byte_delta_sign_is_ud_minus_tools(fake_repo: Path) -> None:
    inventory = inv.build_inventory(fake_repo, with_authorship=False)
    record = next(r for r in inventory.files if r.path == "ai/gui/panel.py")
    assert record.ud_bytes is not None and record.tools_bytes is not None
    assert record.byte_delta == record.ud_bytes - record.tools_bytes


