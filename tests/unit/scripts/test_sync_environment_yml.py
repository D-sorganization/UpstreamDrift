from __future__ import annotations

from pathlib import Path

import pytest
from scripts.sync_environment_yml import (
    DependencySpec,
    build_environment,
    load_dependency_spec,
    render_environment_yml,
)


def test_load_dependency_spec_reads_runtime_and_selected_extras(tmp_path: Path) -> None:
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(
        """
[project]
dependencies = [
    "numpy>=1.26.4,<3.0.0",
    "uvicorn[standard]>=0.30.0",
]

[project.optional-dependencies]
dev = [
    "pytest>=9.0.3",
]
gui-test = [
    "PyQt6>=6.5.0",
]
""".strip(),
        encoding="utf-8",
    )

    spec = load_dependency_spec(pyproject, extras=("dev",))

    assert spec.runtime == ("numpy>=1.26.4,<3.0.0", "uvicorn[standard]>=0.30.0")
    assert spec.extras == {"dev": ("pytest>=9.0.3",)}


def test_load_dependency_spec_rejects_missing_requested_extra(tmp_path: Path) -> None:
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text("[project]\ndependencies = []\n", encoding="utf-8")

    with pytest.raises(ValueError, match="optional dependency extra"):
        load_dependency_spec(pyproject, extras=("dev",))


def test_render_environment_yml_marks_generated_provenance() -> None:
    environment = build_environment(
        DependencySpec(
            runtime=("numpy>=1.26.4,<3.0.0",),
            extras={"dev": ("pytest>=9.0.3",)},
        )
    )

    rendered = render_environment_yml(environment)

    assert (
        "Generated by scripts/sync_environment_yml.py from pyproject.toml" in rendered
    )
    assert "- python=3.11" in rendered
    assert "      - numpy>=1.26.4,<3.0.0" in rendered
    assert "      - pytest>=9.0.3" in rendered
