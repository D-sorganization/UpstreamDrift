"""Guard the ``MplCanvas`` consolidation performed for #9474.

Before this change the class was defined eight times with near-identical
bodies, so a canvas-teardown fix had eight places to drift between. The
UpstreamDrift-owned copies now delegate to
:mod:`src.shared.python.plotting.mpl_canvas`.

The copies that remain live under paths owned by the Tools repository, so
they cannot be edited here (``tests/unit/repo_hygiene/
test_tools_child_copy_contract.py`` fails closed on any such edit). They
are enumerated below so the debt stays visible and so a *new* duplicate
in UpstreamDrift-owned code fails this test.
"""

from __future__ import annotations

import ast
from pathlib import Path

import pytest

pytestmark = [pytest.mark.unit, pytest.mark.headless_safe]

_REPO_ROOT = Path(__file__).resolve().parents[4]
_CANONICAL = Path("src/shared/python/plotting/mpl_canvas.py")

# Definitions that are NOT UpstreamDrift's to remove. Each has a Tools
# counterpart or carries the Tools child-copy header, so consolidating it
# requires a Tools-side pull request and a vendor bump.
_TOOLS_OWNED_DEFINITIONS = {
    # Carries the "DO NOT EDIT THIS FILE DIRECTLY" child-copy header.
    Path("src/shared/python/ui/qt/plotting.py"),
    Path("src/shared/python/ui/qt/widgets/signal_toolkit_widget.py"),
    # Has a same-relative counterpart in the Tools repository.
    Path("src/shared/python/signal_toolkit/widget.py"),
    Path("src/shared/python/signal_toolkit/polynomial_generator.py"),
    Path("src/shared/python/sidekick/process_calculators/psa_package/psa_gui.py"),
    Path(
        "src/shared/python/sidekick/process_calculators/psa_package/ui/"
        "sensitivity_plot.py"
    ),
}

# The documented headless fallback in plotting/base.py: not a duplicate
# implementation but a stub that raises when Qt is unavailable.
_HEADLESS_STUB = Path("src/shared/python/plotting/base.py")

# Delegating subclasses. These keep the class name so existing imports
# still resolve, but carry no implementation of their own -- see
# ``test_engine_widget_delegates_rather_than_redefines``.
_DELEGATING_SUBCLASSES = {
    Path(
        "src/engines/Simscape_Multibody_Models/3D_Golf_Model/python/src/apps/"
        "ui/widgets/mpl_canvas.py"
    ),
}

_SEARCH_ROOTS = (Path("src"),)
_EXCLUDED_PARTS = {"vendor", "node_modules", "__pycache__", ".venv"}


def _defines_mpl_canvas(path: Path) -> bool:
    """Return whether ``path`` contains a ``class MplCanvas`` statement."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, UnicodeDecodeError):
        return False
    return any(
        isinstance(node, ast.ClassDef) and node.name == "MplCanvas"
        for node in ast.walk(tree)
    )


def _definition_sites() -> set[Path]:
    """Return every non-vendored source file defining ``MplCanvas``."""
    found: set[Path] = set()
    for root in _SEARCH_ROOTS:
        for path in (_REPO_ROOT / root).rglob("*.py"):
            relative = path.relative_to(_REPO_ROOT)
            if _EXCLUDED_PARTS.intersection(relative.parts):
                continue
            if _defines_mpl_canvas(path):
                found.add(relative)
    return found


def test_canonical_definition_exists() -> None:
    """The shared canvas is the single UpstreamDrift-owned implementation."""
    assert (_REPO_ROOT / _CANONICAL).is_file()
    assert _CANONICAL in _definition_sites()


def test_no_new_upstreamdrift_owned_duplicates() -> None:
    """Only the canonical class, the headless stub, and Tools copies remain."""
    permitted = (
        {_CANONICAL, _HEADLESS_STUB} | _TOOLS_OWNED_DEFINITIONS | _DELEGATING_SUBCLASSES
    )
    unexpected = sorted(str(p) for p in _definition_sites() - permitted)

    assert not unexpected, (
        "New MplCanvas definition(s) found. Import "
        f"{_CANONICAL.as_posix()} instead of redefining the class:\n  "
        + "\n  ".join(unexpected)
    )


def test_tools_owned_definitions_are_still_present() -> None:
    """Keep the deferred-debt list honest as Tools copies are consolidated.

    If a Tools-side pull request removes one of these, delete its entry
    here rather than letting the list rot.
    """
    stale = sorted(
        str(path)
        for path in _TOOLS_OWNED_DEFINITIONS
        if not _defines_mpl_canvas(_REPO_ROOT / path)
    )
    assert not stale, (
        "These paths no longer define MplCanvas; remove them from "
        "_TOOLS_OWNED_DEFINITIONS:\n  " + "\n  ".join(stale)
    )


def test_engine_widget_delegates_rather_than_redefines() -> None:
    """The 3D Golf Model widget subclasses instead of copying the body.

    Parsed statically so the assertion holds without importing the Qt
    application package (whose nested ``src`` root needs sys.path setup).
    """
    module = (
        _REPO_ROOT
        / "src/engines/Simscape_Multibody_Models/3D_Golf_Model/python/src/apps"
        / "ui/widgets/mpl_canvas.py"
    )
    tree = ast.parse(module.read_text(encoding="utf-8"))

    imports_shared = any(
        isinstance(node, ast.ImportFrom)
        and node.module == "src.shared.python.plotting.mpl_canvas"
        for node in ast.walk(tree)
    )
    assert imports_shared, "engine widget must import the shared canvas"

    classes = [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
    assert [c.name for c in classes] == ["MplCanvas"]

    # A delegating subclass: one __init__ that defers via super().
    body_methods = [n.name for n in classes[0].body if isinstance(n, ast.FunctionDef)]
    assert body_methods == ["__init__"], (
        "the engine subclass should only pin defaults; behaviour belongs "
        f"on the shared canvas, but it defines {body_methods}"
    )
